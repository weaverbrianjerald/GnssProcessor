#!/usr/bin/env python3
"""Card CM2 arm generator (SPEC_event_harness s24.12): the s24.8 knob arms on the leveling vehicle.

    python scripts/cm2_make_arms.py [--base config/test_suite/_pv_b.json] [--runs C:/GnssProcessor/runs]
        [--prefix _cm_] [--arms b1,b2,b2b,b3,b4,b5,b6,b7,b8] [--out-dir <dir>] [--force]

Each arm is a byte-for-byte copy of the PV-B base (`config/test_suite/_pv_b.json`, the field golden as
card CM's control A0 ran it, plus the leveling-vehicle delta only) with one knob changed (two JSON
leaves where the knob is a pair) and its own `network.product_output_path` /
`network.state_snapshot_path` under `<runs>/<prefix><arm>/`.  The script writes the config to
`<runs>/<prefix><arm>/arm.json` and `<runs>/<prefix><arm>/seed.json` (scripts/cm_grade.py's wire-vs-CODE
census reads `seed.json` for the CODE product identity) and prints the leaf diff against the base, so the
"one knob plus two paths" property can be read off the console rather than assumed.

b9 is the union arm, not generated by default: pass `--arms b9 --union b2,b5` (the contributors
named by the grade) and the script applies every contributor's knobs together.

The spellings are the loader's, taken from GnssConfigLoad.cpp and GnssConfigLoadNetwork.cpp; s24.12's prose
abbreviates two of them (`network.representation_sigma_tecu` is
`estimation.global_vtec_sh.representation_sigma_tecu`, and b8's pair lives under `estimation.zwd_constraint`).
The loader ignores unknown JSON keys rather than rejecting them, so a mistyped key is a silent no-op; the
run's `logs/gnss_config.log` effect line is the real check, and cm_grade.py prints it per arm.
"""
import argparse
import json
import os
import shutil
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# arm -> (description, [(dotted json path, value), ...])
ARMS = {
    "b1": ("network.carry_rx_code_bias: false — the receiver code-bias carry (the frozen first-epoch memory)",
           [("network.carry_rx_code_bias", False)]),
    "b2": ("network.carry_zwd: true + network.zwd_carry_q: 1e-8 — the B9 ZWD random-walk carry (physical q)",
           [("network.carry_zwd", True), ("network.zwd_carry_q", 1e-8)]),
    "b2b": ("network.carry_zwd: true + network.zwd_carry_q: 1e-7 — the same, the stiffness axis",
            [("network.carry_zwd", True), ("network.zwd_carry_q", 1e-7)]),
    "b3": ("network.cb_kaula_prior: false — the 3 m Kaula prior on the satellite code biases",
           [("network.cb_kaula_prior", False)]),
    "b4": ("filter.process_noise.sat_code_bias_q: 1e-4 — unfreeze the satellite code-bias states (1e-10 -> 1e-4)",
           [("filter.process_noise.sat_code_bias_q", 1e-4)]),
    "b5": ("network.estimate_iono_sh: false — the SH-VTEC tie off (the sim's posture C, free slant iono)",
           [("network.estimate_iono_sh", False)]),
    "b6": ("network.estimate_sat_code_bias: false + model_corrections.enable_code_phase_bias: true — CODE's OSB "
           "in place of the estimated satellite code biases (W6 off)",
           [("network.estimate_sat_code_bias", False), ("model_corrections.enable_code_phase_bias", True)]),
    "b7": ("estimation.global_vtec_sh.representation_sigma_tecu: 20 — the SH<->slant tie 4x looser",
           [("estimation.global_vtec_sh.representation_sigma_tecu", 20.0)]),
    "b8": ("estimation.zwd_constraint.enabled: true + sigma_m: 0.2 — the a-priori ZWD pseudo-observation "
           "(s24.8's A7 read it as RT-engine-only; re-tested on the leveling vehicle)",
           [("estimation.zwd_constraint.enabled", True), ("estimation.zwd_constraint.sigma_m", 0.2)]),
}


def dset(d, dotted, value):
    """Set a dotted json path, creating intermediate objects; returns the previous value or '<absent>'."""
    parts = dotted.split(".")
    cur = d
    for p in parts[:-1]:
        if p not in cur or not isinstance(cur[p], dict):
            cur[p] = {}
        cur = cur[p]
    prev = cur.get(parts[-1], "<absent>")
    cur[parts[-1]] = value
    return prev


def flat(d, p=""):
    out = {}
    if isinstance(d, dict):
        for k, v in d.items():
            out.update(flat(v, p + "." + k if p else k))
    elif isinstance(d, list):
        out[p] = "<%d entries>" % len(d) if p.endswith("stations") else json.dumps(d)
    else:
        out[p] = d
    return out


def leaf_diff(a, b):
    fa, fb = flat(a), flat(b)
    return [(k, fa.get(k, "<absent>"), fb.get(k, "<absent>"))
            for k in sorted(set(fa) | set(fb))
            if not k.startswith(("_comment", "_promotion_note", "_cm2")) and fa.get(k, "<absent>") != fb.get(k, "<absent>")]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", default=os.path.join(REPO, "config", "test_suite", "_pv_b.json"))
    ap.add_argument("--runs", default="C:/GnssProcessor/runs")
    ap.add_argument("--prefix", default="_cm_")
    ap.add_argument("--arms", default="b1,b2,b2b,b3,b4,b5,b6,b7,b8")
    ap.add_argument("--union", default="", help="for --arms b9: the comma-separated contributor arms whose knobs b9 unions")
    ap.add_argument("--out-dir", default="", help="also write <arm>.json here (default: run dir only)")
    ap.add_argument("--force", action="store_true", help="overwrite an existing arm.json")
    a = ap.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    with open(a.base, encoding="utf-8") as fh:
        base_txt = fh.read()
    base = json.loads(base_txt)

    for arm in [s for s in a.arms.split(",") if s]:
        if arm == "b9":
            union = [s for s in a.union.split(",") if s]
            if not union:
                sys.exit("b9 needs --union <contributor arms>")
            desc = "UNION of the contributors " + "+".join(union) + ": " + " ; ".join(ARMS[u][0] for u in union)
            knobs = [kv for u in union for kv in ARMS[u][1]]
        elif arm in ARMS:
            desc, knobs = ARMS[arm]
        else:
            sys.exit(f"unknown arm {arm}")

        cfg = json.loads(base_txt)
        rundir = os.path.join(a.runs, f"{a.prefix}{arm}").replace("\\", "/")
        applied = []
        for dotted, val in knobs:
            applied.append((dotted, dset(cfg, dotted, val), val))
        dset(cfg, "network.product_output_path", f"{rundir}/products.txt")
        dset(cfg, "network.state_snapshot_path", f"{rundir}/state_snapshot.bin")
        cfg["_cm2_arm"] = [
            f"CARD CM2 ARM {arm} (SPEC_event_harness s24.12, pre-registered).  Base: {os.path.relpath(a.base, REPO).replace(os.sep, '/')} "
            f"(PV-B = the field golden as _cm_a0 ran it + the leveling-VEHICLE delta only).",
            f"THE ONE KNOB: {desc}",
            "Everything else, including the run paths' parent, is PV-B's.  Control = runs/_cm_pvb (not re-run).",
        ]

        os.makedirs(os.path.join(rundir, "logs"), exist_ok=True)
        dest = os.path.join(rundir, "arm.json")
        if os.path.isfile(dest) and not a.force:
            print(f"!! {dest} exists — pass --force to overwrite; skipped")
            continue
        txt = json.dumps(cfg, indent=2)
        with open(dest, "w", encoding="utf-8") as fh:
            fh.write(txt)
        shutil.copyfile(dest, os.path.join(rundir, "seed.json"))
        if a.out_dir:
            os.makedirs(a.out_dir, exist_ok=True)
            shutil.copyfile(dest, os.path.join(a.out_dir, f"{arm}.json"))

        d = leaf_diff(base, cfg)
        print(f"\n{arm}: {desc}\n  -> {dest} (+ seed.json)")
        for k, old, new in d:
            print(f"     {k:<60s} {old} -> {new}")
        n_knob = len([x for x in d if not x[0].endswith(("product_output_path", "state_snapshot_path"))])
        n_path = len(d) - n_knob
        ok = (n_knob == len(knobs) and n_path == 2)
        print(f"  {'OK' if ok else '!! UNEXPECTED'}: {n_knob} knob leaf/leaves (expected {len(knobs)}) + {n_path} path leaves (expected 2)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
