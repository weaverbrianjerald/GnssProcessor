class Fail(SystemExit):
    pass


def fail(msg):
    raise Fail("nom_pb1_cut: " + msg)


# ---------------------------------------------------------------------------------------------
# The frozen function with the knob move applied
# ---------------------------------------------------------------------------------------------
def knob_moved(text):
    """@p text with each KNOB_MOVE alias initializer replaced (each matches exactly once inside
    its alias statement)."""
    P = frozen.PassB(text)
    edits = []
    for name, old, new in rows.KNOB_MOVE:
        st = [s for s in P.aliases if s.name == name]
        if len(st) != 1:
            fail(f"KNOB_MOVE: alias {name} found {len(st)} times")
        s = st[0]
        a, b = P.T[s.a].pos, P.T[s.b - 1].end
        seg = text[a:b]
        if seg.count(old) != 1:
            fail(f"KNOB_MOVE: {old!r} occurs {seg.count(old)} times in the alias {name}")
        k = a + seg.index(old)
        edits.append((k, k + len(old), new))
    for a, b, new in sorted(edits, reverse=True):
        text = text[:a] + new + text[b:]
    return text


# ---------------------------------------------------------------------------------------------
# Bindings
# ---------------------------------------------------------------------------------------------
def used_names(P, lines_text):
    T = frozen.nom_cpp.Tokens(lines_text)
    return {n for n, _ in frozen.free_ids(T, 0, T.n)}


def closure(P, need, free_function):
    """The binding statements (roots, aliases) a text that reads @p need requires."""
    need = set(need)
    alias = {s.name: s for s in P.aliases}
    changed = True
    while changed:
        changed = False
        for s in P.aliases:
            if s.name not in need:
                continue
            if free_function and s.name == "log":
                continue                    # a ROOT in a free function (run.log)
            for r in s.reads:
                if r not in need and (r in alias or any(x.name == r for x in P.roots)
                                      or r == "config_"):
                    need.add(r)
                    changed = True
    roots = [s for s in P.roots if s.name in need]
    aliases = [s for s in P.aliases if s.name in need and not (free_function and s.name == "log")]
    return need, roots, aliases


def root_line(P, s, params):
    line = _root_line(P, s, params)
    if len(line) > 100 and " = " in line:                 # EP1's wrap of a long binding
        head, init = line.split(" = ", 1)
        line = head + " =\n        " + init
    return line


def _root_line(P, s, params):
    """A stage's binding line for frozen root @p s (EP1's realization; CONST_VIEW where a
    written output is only read)."""
    src = " ".join(l.strip() for l in s.text(P, with_comment=False))
    m = re.match(r"^(.*?)\b(\w+)\s*=\s*(.*?);\s*(//.*)?$", src)
    if not m:
        fail(f"root {s.name}: cannot read {src!r}")
    decl, name, init, comment = m.group(1).strip(), m.group(2), m.group(3).strip(), m.group(4)
    group = init.split(".")[0]
    if group == "nep":
        return f"    {decl} {name} = ep.{init[4:]};"
    if group == "run":
        return f"    {src}"
    if group in OUTPUT_GROUPS:
        ptype = OUTPUT_GROUPS[group]
        if f"{ptype}& {group}" in params and f"const {ptype}& {group}" not in params:
            return f"    {src}"                              # the stage writes it too
        cdecl = decl if decl.startswith("const ") else "const " + decl
        if f"const {ptype}& {group}" in params:
            return f"    {cdecl} {name} = {init};"           # the caller's group, passed const
        if group == "assembly":
            fail(f"{name}: a stage reading the assembly must take it as a parameter "
                 "(nom_epoch_lint V10: the caller still writes the group)")
        return f"    {cdecl} {name} = ep.{init};"            # read through the epoch
    fail(f"root {s.name}: unknown source {init!r}")


def preamble(P, need, params):
    need, roots, aliases = closure(P, need, free_function=True)
    out = list(PREAMBLE_HEAD)
    for s in roots:
        out.extend(root_line(P, s, params).split("\n"))
        if s.name == "ctx":
            for r in ("config_", "log"):
                if r in need:
                    out.append(FREE_ROOTS[r])
    if "ctx" not in need and ("config_" in need or "log" in need):
        fail("config_/log without ctx: place them")
    out.append("    // ---- End of the bindings ----")
    if aliases:
        out.append(ALIAS_HEAD)
        for s in aliases:
            out.extend(s.text(P))
    return out, roots, aliases


# ---------------------------------------------------------------------------------------------
# Stage bodies
# ---------------------------------------------------------------------------------------------
def negate(cond):
    c = cond.strip()
    if re.fullmatch(r"[A-Za-z_][\w.]*", c):
        return "!" + c
    return "!(" + c + ")"


def code_index(lines):
    return [k for k, l in enumerate(lines) if l.strip() and not frozen.is_comment(l)]


def guard(lines, cond):
    """GUARD: the piece's one top-level statement `if (C) {` ... `}` becomes `if (!C) return;`
    with the body one level out."""
    ci = code_index(lines)
    head, tail = ci[0], ci[-1]
    if lines[head] != f"    if ({cond}) {{" or lines[tail] != "    }":
        fail(f"GUARD {cond!r}: the piece is not one `if ({cond}) {{ ... }}`")
    inner = lines[head + 1:tail]
    out = lines[:head] + [f"    if ({negate(cond)}) return;"]
    for l in inner:
        if l.strip() and not l.startswith("        "):
            fail(f"GUARD {cond!r}: a body line is not indented two levels: {l!r}")
        out.append(l[4:] if l.strip() else l)
    return out + lines[tail + 1:]


def signature(name, spec, ep="ep"):
    ps = ["NetworkRun& run", f"const NetworkEpoch& {ep}"] + spec["params"]
    head = f"{spec['ret']} {name}("
    one = head + ", ".join(ps) + ")"
    if len(one) <= 96:
        return one
    lines, cur = [], head
    for k, p in enumerate(ps):
        piece = p + (", " if k + 1 < len(ps) else ")")
        if len(cur) + len(piece.rstrip()) > 96 and cur.strip() != head.strip():
            lines.append(cur.rstrip())
            cur = " " * len(head)
        cur += piece
    lines.append(cur)
    return "\n".join(lines)


def stage_function(P, name, spec):
    p = next(x for x in P.pieces if x["name"] == name)
    body = P.piece_lines(p)
    if spec.get("guard"):
        body = guard(body, spec["guard"])
    if spec.get("ret_stmt"):
        body = body + [f"    {spec['ret_stmt']}"]
    btext = "\n".join(body)
    used = used_names(P, btext)
    for bad in ("run", "ep"):
        if bad in used:
            fail(f"{name}: `{bad}` is a free identifier of the frozen piece")
    members = sorted(n for n in used if n.endswith("_") and n != "config_")
    if members:
        fail(f"{name}: the piece reads Application members {members}")
    pnames = {pp.split()[-1] for pp in spec["params"]}
    pre, roots, aliases = preamble(P, used - pnames, spec["params"])
    text = [signature(name, spec) + " {"] + pre + [""] + body + ["}"]
    root_text = pre[len(PREAMBLE_HEAD):pre.index("    // ---- End of the bindings ----")]
    return text, root_text, aliases, used


# ---------------------------------------------------------------------------------------------
# networkPassB_
# ---------------------------------------------------------------------------------------------
def orchestrator(P):
    """The new body lines of networkPassB_ (between its braces)."""
    seg = []          # (kind, lines)
    groups = {}
    for p in P.pieces:
        if p["name"] is None:
            seg.append(("piece", P.piece_lines(p)))
        else:
            call = "    " + rows.STAGES[p["name"]]["call"]
            if seg and seg[-1][0] == "calls":
                seg[-1][1].append(call)
            else:
                c = rows.CALL_GROUP_COMMENT.get(p["piece"])
                seg.append(("calls", ([f"    {c}"] if c else []) + [call]))
    body = []
    for k, (_, lines) in enumerate(seg):
        if k:
            body.append("")
        body.extend(lines)
    btext = "\n".join(body)
    used = used_names(P, btext)
    need, roots, aliases = closure(P, used - {"run", "nep", "pass_a", "assembly"}, free_function=False)
    pre = P.lines[P.ep1_head - 1:roots[0].first - 1]          # the EP1 head comment
    for s in roots:
        pre.extend(s.text(P, with_comment=False))
    pre.append(P.lines[P.ep1_end - 1])
    for s in aliases:
        pre.extend(s.text(P))
    return pre + [""] + body, roots, aliases


# ---------------------------------------------------------------------------------------------
# Doxygen and file assembly
# ---------------------------------------------------------------------------------------------
def wrap(prefix, text, width=96, cont=None):
    cont = cont if cont is not None else " * " + " " * (len(prefix) - 3)
    return textwrap.wrap(text, width=width, initial_indent=prefix, subsequent_indent=cont,
                         break_on_hyphens=False, break_long_words=False)


def binding_source(line):
    m = re.match(r"^\s*(.*?)\b(\w+)\s*=\s*(.*?);", line)
    return (m.group(2), m.group(3)) if m else (None, None)


def doxygen(name, spec, root_lines):
    out = ["/**"]
    out += wrap(" * @brief ", spec["brief"])
    out.append(" *")
    out += wrap(" * ", spec["detail"], cont=" * ")
    out.append(" *")
    out += wrap(" * ", ("Epoch form (card NOM3 step PB1a; generated by scripts/nom_pb1_cut.py): "
                        "a serial stage of Application::networkPassB_, cut with the alias lines of "
                        "networkPassB_ it reads.  Below its bindings is the frozen text; a piece "
                        "wholly inside one `if` returns early instead (scripts/nom_pb1/declared.py)."),
                cont=" * ")
    out.append(" *")
    run_b, ep_b, out_b = [], [], {}
    for l in root_lines:
        n, init = binding_source(l)
        if n is None:
            continue
        if init.startswith("run."):
            run_b.append(f"{init} ({n})")
        elif init.startswith("ep."):
            ep_b.append(f"{init} ({n})")
        else:
            out_b.setdefault(init.split(".")[0], []).append(f"{init} ({n})")
    out += wrap(" * @param run ", "The run (app/NetworkRun.hpp). Bindings: " + ", ".join(run_b) + ".")
    out += wrap(" * @param ep ", "The epoch (app/NetworkEpoch.hpp), read only. Bindings: "
                + (", ".join(ep_b) if ep_b else "none") + ".")
    for pp in spec["params"]:
        pn = pp.split()[-1]
        doc = spec.get("param_doc", {}).get(pn, "")
        if pn in out_b:
            doc += " Bindings: " + ", ".join(out_b[pn]) + "."
        out += wrap(f" * @param {pn} ", doc.strip())
    if spec.get("return_doc"):
        out += wrap(" * @return ", spec["return_doc"])
    out.append(" */")
    return out


def insert_before_namespace_close(text, block, rel):
    k = text.rfind("\n} // namespace GnssProcessor")
    if k < 0:
        fail(f"{rel}: no namespace close")
    return text[:k + 1] + "\n".join(block) + "\n\n" + text[k + 1:]


def add_includes(text, incs, rel):
    """Each include of @p incs the file lacks, after its last #include line."""
    missing = [i for i in incs if f"#include {i.split()[0]}" not in text]
    if not missing:
        return text
    lines = text.split("\n")
    last = max(k for k, l in enumerate(lines) if l.startswith("#include"))
    lines[last + 1:last + 1] = [f"#include {i}" for i in missing]
    return "\n".join(lines)


