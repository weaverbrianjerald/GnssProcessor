def header_block(name, spec, roots_text):
    return doxygen(name, spec, roots_text) + [signature(name, spec) + ";"]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--stage", required=True, choices=["pb1a"])
    ap.add_argument("--base", default=rows.BASE)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(ROOT))
    a = ap.parse_args(argv)
    root = pathlib.Path(a.root)

    def base(rel):
        try:
            return frozen.git_show(root, a.base, rel)
        except Exception:
            return None

    outputs = {}
    asm0 = base(rows.ASM)
    asm1 = knob_moved(asm0)
    P = frozen.PassB(asm1)

    # Stages, grouped by home.
    by_home = {}
    report = []
    stage_alias_names = set()
    for p in P.pieces:
        if p["name"] is None:
            continue
        spec = rows.STAGES[p["name"]]
        ftext, root_text, aliases, used = stage_function(P, p["name"], spec)
        by_home.setdefault(spec["home"], []).append((p["name"], spec, ftext, root_text))
        stage_alias_names.update(s.name for s in aliases)
        report.append(f"{p['name']}: {len(root_text)} roots, {len(aliases)} alias lines")

    # networkPassB_.
    body, oroots, oaliases = orchestrator(P)
    L = asm1.split("\n")
    new_asm = "\n".join(L[:P.open_line] + body + L[P.close_line - 1:])
    anchor = '#include "filter/NetworkPrefitCensus.hpp"'
    k = new_asm.index("\n", new_asm.index(anchor)) + 1
    stage_incs = ['#include "filter/NetworkShDevVtec.hpp"     // networkShDevCarryAge (card NOM3 step PB1a)',
                  '#include "filter/NetworkStationBuild.hpp"  // networkAssemblyTally (card NOM3 step PB1a)',
                  '#include "filter/NetworkSolveStations.hpp" // the consume and the in-solve track (PB1a)',
                  '#include "filter/NetworkChainDatum.hpp"    // networkEq34PinAudit (card NOM3 step PB1a)']
    new_asm = new_asm[:k] + "\n".join(i for i in stage_incs if i.split("//")[0].strip() not in new_asm) \
        + "\n" + new_asm[k:]
    kept = stage_alias_names | {s.name for s in oaliases} | {"log"}
    dead = [s.name for s in P.aliases if s.name not in kept]
    outputs[rows.ASM] = new_asm
    report.append(f"networkPassB_: {len(oroots)} roots, {len(oaliases)} alias lines; "
                  f"dropped everywhere: {dead}")

    # Homes.
    for home, fns in by_home.items():
        src_rel, hdr_rel = f"src/core/filter/{home}.cpp", f"include/filter/{home}.hpp"
        src, hdr = base(src_rel), base(hdr_rel)
        if home in rows.NEW_FILES:
            brief, body_doc = NEW_HEADER_DOC[home]
            src = NEW_SOURCE.format(name=home, brief=brief)
            hdr = NEW_HEADER.format(name=home, brief=brief,
                                    body="\n".join(wrap(" * ", body_doc, cont=" * ")))
        block = [REGION_OPEN, ""]
        decls = [REGION_OPEN.replace("serial stages", "serial stages, declarations"), ""]
        for name, spec, ftext, root_text in fns:
            block += ftext + [""]
            decls += header_block(name, spec, root_text) + [""]
        block.append(REGION_CLOSE)
        decls.append(REGION_CLOSE.replace("serial stages", "serial stages, declarations"))
        src = add_includes(src, SRC_INCLUDES + EXTRA_INCLUDES[home], src_rel)
        src = insert_before_namespace_close(src, block, src_rel)
        if home not in rows.NEW_FILES:
            fwd = [f for f in ("NetworkRun", "NetworkEpoch", "EpochPassA", "EpochAssembly")
                   if not re.search(rf"^struct {f};", hdr, re.M)]
            if fwd:
                decls = [f"struct {f};" + " " * max(1, 24 - len(f)) + "// app/"
                         + ("NetworkRun" if f == "NetworkRun" else "NetworkEpoch") + ".hpp"
                         for f in fwd] + [""] + decls
        hdr = insert_before_namespace_close(hdr, decls, hdr_rel)
        if home in rows.NEW_FILES:
            hdr = hdr.replace("\nstruct NetworkRun;", "\nstruct NetworkRun;", 1)
        outputs[src_rel] = src
        outputs[hdr_rel] = hdr

    # Knobs.
    kc = base(rows.KNOBS_CPP)
    anchor = "    k.rxcb_blk = config_.networkCarryRxCodeBiasInBlock();"
    k = kc.index(anchor)
    k = kc.index("\n", k) + 1
    snap = [
        "    // The live block predicates and the free-epoch consult, resolved once here (card NOM3",
        "    // step PB1a): networkPassB_ derived them per epoch and the harvest a second time.",
        "    k.pl_blk_on       = k.pl_local_block && k.carry_cpl_cond;",
        "    k.zwd_blk_on      = k.zwd_in_block && k.pl_blk_on;",
        "    k.iono_blk_on     = k.iono_blk && k.pl_blk_on;",
        "    k.rxclk_blk_on    = k.rxclk_blk && k.pl_blk_on;",
        "    k.rxcb_blk_on     = k.rxcb_blk && k.pl_blk_on && k.rx_cb_on;",
        "    k.relevel_free_on = config_.networkCycleSlipRelevelFreeEpoch();",
    ]
    outputs[rows.KNOBS_CPP] = kc[:k] + "\n".join(snap) + "\n" + kc[k:]
    kh = base(rows.KNOBS_HPP)
    anchor = "        bool rxcb_blk{};"
    k = kh.index(anchor)
    k = kh.index("\n", k) + 1
    fields = [
        "        /// The live F3 block predicate: @ref pl_local_block and @ref carry_cpl_cond (the block's",
        "        /// rows are coupling rows).  Read by networkPassB_ (the produce's block route and the",
        "        /// tally's F3 telemetry) and, through the four predicates below, by the harvest",
        "        /// (card NOM3 step PB1a; it was derived in both).",
        "        bool pl_blk_on{};",
        "        /// The carried ZWD column joins the F3 block: @ref zwd_in_block and @ref pl_blk_on.",
        "        /// Read by networkPassB_ and networkLocalCarryHarvest.",
        "        bool zwd_blk_on{};",
        "        /// The carried slant-iono columns join the F3 block: @ref iono_blk and @ref pl_blk_on.",
        "        /// Read by networkPassB_ and networkLocalCarryHarvest.",
        "        bool iono_blk_on{};",
        "        /// The receiver clock (and ISB) columns join the F3 block: @ref rxclk_blk and",
        "        /// @ref pl_blk_on.  Read by networkPassB_ and networkLocalCarryHarvest.",
        "        bool rxclk_blk_on{};",
        "        /// The receiver code-bias columns join the F3 block: @ref rxcb_blk, @ref pl_blk_on and",
        "        /// @ref rx_cb_on.  Read by networkPassB_ and networkLocalCarryHarvest.",
        "        bool rxcb_blk_on{};",
        "        /// network.cycle_slip.relevel_free_epoch: the produce consults the latched free-epoch",
        "        /// set and the tally folds its skips (SPEC_slip_relevel_walk).  Read by networkPassB_.",
        "        bool relevel_free_on{};",
    ]
    outputs[rows.KNOBS_HPP] = kh[:k] + "\n".join(fields) + "\n" + kh[k:]

    # The harvest's four derivations (decision 6).
    hv = base(rows.HARVEST)
    HP = harvest_edits(hv)
    outputs[rows.HARVEST] = HP

    # CMakeLists.txt.
    cm = base("CMakeLists.txt")
    for home in rows.NEW_FILES:
        anchor = "    src/core/filter/NetworkShDevVtec.cpp\n"
        line = f"    src/core/filter/{home}.cpp\n"
        if line not in cm:
            cm = cm.replace(anchor, anchor + line, 1)
    tline = "    tests/test_network_knobs_station_assembly.cpp\n"
    anchor = "    tests/test_network_knobs_epoch_driver.cpp\n"
    if tline not in cm:
        cm = cm.replace(anchor, anchor + tline, 1)
    outputs["CMakeLists.txt"] = cm

    status = {}
    for rel, text in outputs.items():
        p = root / rel
        data = text.encode("utf-8")
        old = p.read_bytes() if p.exists() else None
        if old == data:
            status[rel] = "unchanged"
        elif a.check:
            status[rel] = "differs"
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)
            status[rel] = "written"
    for r in report:
        print(r)
    for rel, s in sorted(status.items()):
        print(f"  {s:9} {rel}")
    return 1 if a.check and any(s == "differs" for s in status.values()) else 0


def harvest_edits(text):
    out = text
    for name in rows.HARVEST_MOVE:
        m = re.search(rf"(const bool\s+{name}\s*=\s*)([^;]*);", out)
        if not m or len(re.findall(rf"const bool\s+{name}\s*=", out)) != 1:
            fail(f"harvest: {name} not found once")
        out = out[:m.start(2)] + f"ctx.knobs.{name}" + out[m.end(2):]
    return out


