#!/usr/bin/env python3
"""Generator of card NOM3 step PB1a: PASS B's serial stages as seams in EP1's form.

    python scripts/nom_pb1_cut.py --stage pb1a [--base 7141240] [--check]

Reads Application::networkPassB_ at the base revision (git show; scripts/nom_pb1/frozen.py)
and the canonical rows (scripts/nom_pb1/rows.py), and writes into the working tree:

  - each stage of rows.STAGES as a free function `R networkX(NetworkRun& run, const
    NetworkEpoch& ep[, kept][, outputs])` in a generated region at the end of its home .cpp,
    with its declaration and Doxygen in the home header.  The function opens with the root
    bindings it reads (EP1's: through `ep` for reads, through its output parameters for
    writes, `// written`; the logger and the configuration from the run), then verbatim
    copies of the alias lines of networkPassB_ it reads (ALIAS_SPLIT), then its frozen piece:
    GUARD turns `if (C) {...}` into `if (!C) return;` and the body one level out, RETURN
    appends `return epoch_ok;`;
  - networkPassB_ itself: its bindings and alias lines restricted to what it still reads,
    each stage piece replaced by its call at the frozen position (STAGE_CALL);
  - the six NetworkKnobs fields (KNOB_MOVE): their snapshot lines and declarations, the alias
    lines of networkPassB_ read them, and the harvest's four derivations
    (src/core/app/NetworkLocalCarryHarvest.cpp, decision 6) read them too;
  - the two new file pairs and their CMakeLists.txt entries.

The generator never reads its own output: every edit starts from the base text of the file,
so a second run is a no-op and --check reports any file whose bytes differ from what the
generator would write.  Line ends are LF (the checkout's).
"""
