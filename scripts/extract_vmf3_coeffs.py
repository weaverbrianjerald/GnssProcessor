#!/usr/bin/env python3
"""Extract VMF3 spherical harmonic coefficients from vmf3.m and emit a C++ header.

The TU Wien VMF3 reference implementation
(https://vmf.geo.tuwien.ac.at/codes/vmf3.m) hardcodes 8 coefficient matrices,
each 91×5 (degree/order 12, with 5 seasonal harmonic columns A0,A1,B1,A2,B2):

    anm_bh, bnm_bh, anm_bw, bnm_bw,
    anm_ch, bnm_ch, anm_cw, bnm_cw

This script reads the MATLAB source verbatim, parses each `name = [...]`
literal, and writes the values into a single C++ header used by the
GnssProcessor VMF3 implementation.  The (n,m) row ordering matches the
loops in vmf3.m so the synthesis code can index by a single linear
counter from 0 to 90.

Usage:
    python scripts/extract_vmf3_coeffs.py path/to/vmf3.m \
        include/atmosphere/Vmf3Coefficients.hpp
"""

from __future__ import annotations
import re
import sys
from pathlib import Path

MATRIX_NAMES = [
    "anm_bh", "anm_bw", "anm_ch", "anm_cw",
    "bnm_bh", "bnm_bw", "bnm_ch", "bnm_cw",
]

# (n, m) pairs in the order the synthesis loop iterates: n=0..12, m=0..n.
NM_PAIRS = [(n, m) for n in range(13) for m in range(n + 1)]
assert len(NM_PAIRS) == 91


def parse_matrix(text: str, name: str) -> list[list[float]]:
    """Find `name = [ ... ];` in the MATLAB text and return as list[91][5]."""
    pattern = re.compile(rf"\b{name}\s*=\s*\[(.*?)\];", re.DOTALL)
    m = pattern.search(text)
    if not m:
        raise RuntimeError(f"Matrix '{name}' not found in source")
    body = m.group(1)
    rows = [r.strip() for r in body.split(";") if r.strip()]
    if len(rows) != 91:
        raise RuntimeError(f"{name}: expected 91 rows, got {len(rows)}")
    out: list[list[float]] = []
    for i, r in enumerate(rows):
        cols = r.split()
        if len(cols) != 5:
            raise RuntimeError(f"{name} row {i}: expected 5 columns, got {len(cols)}")
        out.append([float(c) for c in cols])
    return out


def emit_array(out: list[str], cname: str, matrix: list[list[float]]) -> None:
    out.append(f"    constexpr double {cname}[91][5] = {{")
    for i, row in enumerate(matrix):
        n, mn = NM_PAIRS[i]
        cells = ", ".join(f"{v: .17g}" for v in row)
        out.append(f"        {{ {cells} }}, // n={n}, m={mn}")
    out.append("    };")
    out.append("")


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 1
    src_path = Path(argv[1])
    dst_path = Path(argv[2])

    text = src_path.read_text(encoding="utf-8", errors="replace")
    matrices = {name: parse_matrix(text, name) for name in MATRIX_NAMES}

    out: list[str] = [
        "#pragma once",
        "",
        "/**",
        " * @file Vmf3Coefficients.hpp",
        " * @brief Spherical harmonic coefficients for VMF3 b/c parameters.",
        " *",
        " * Generated by scripts/extract_vmf3_coeffs.py from the TU Wien",
        " * reference implementation vmf3.m (Landskron & Boehm 2018).  Do",
        " * not edit by hand — regenerate from the upstream MATLAB file.",
        " *",
        " * Each array is 91 × 5: 91 (n,m) pairs with n=0..12, m=0..n in",
        " * the order the synthesis loop expects, and 5 seasonal harmonic",
        " * columns (A0, A1, B1, A2, B2) evaluated against DOY/365.25.",
        " */",
        "",
        "namespace GnssProcessor {",
        "namespace Vmf3Coeffs {",
        "",
    ]
    for name in MATRIX_NAMES:
        emit_array(out, name, matrices[name])
    out.append("} // namespace Vmf3Coeffs")
    out.append("} // namespace GnssProcessor")
    out.append("")

    dst_path.parent.mkdir(parents=True, exist_ok=True)
    dst_path.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {dst_path} ({dst_path.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
