BIND_HEAD = ["    // ---- From the station build (card NOM3 step PB1b; generated by scripts/nom_pb1b_cut.py,",
             "    //      each line checked by scripts/nom_pb1b_verify.py). ----"]
ALIAS_HEAD = "    // The alias lines of networkPassB_ this function reads, verbatim (card NOM3 step PB1b)."
BIND_END = "    // ---- End of the bindings ----"
HARVEST_MARK = ["// ---- Harvest half (card NOM3 step HV1 fills this section; empty after step PB1b) ----",
                "// ---- End of the harvest half ----"]
REVERSE_SED = pathlib.Path("D:/GnssProcessorSupport/gates/pb1b/reverse.sed")


class Fail(SystemExit):
    pass


def fail(msg):
    raise Fail("nom_pb1b_cut: " + msg)


def base(rel):
    return fz.git_show(ROOT, rows.BASE, rel)


# ---------------------------------------------------------------------------------------------
# Text helpers
# ---------------------------------------------------------------------------------------------
def indent_of(l):
    return len(l) - len(l.lstrip(" "))


def shift(lines, n, what):
    out = []
    for l in lines:
        if not l.strip():
            out.append("")
            continue
        if not l.startswith(" " * n):
            fail(f"{what}: a line is indented less than {n}: {l!r}")
        out.append(l[n:])
    return out


def is_code(l):
    s = l.strip()
    return bool(s) and not fz.is_comment(l)


def negate(cond):
    c = cond.strip()
    if re.fullmatch(r"[A-Za-z_][\w.]*", c):
        return "!" + c
    return "!(" + c + ")"


def conj(ops):
    out = []
    for o in ops:
        out.append(f"({o})" if ("||" in o or "?" in o) and len(ops) > 1 else o)
    return " && ".join(out)


def trailing_comment(l):
    """The `// ...` comment at the end of code line @p l (outside string literals), or ''."""
    q = False
    for k in range(len(l) - 1):
        c = l[k]
        if c == '"' and (k == 0 or l[k - 1] != "\\"):
            q = not q
        if not q and l[k:k + 2] == "//":
            return l[k:]
    return ""


def wrap(prefix, text, width=96, cont=None):
    cont = cont if cont is not None else " * "
    return textwrap.wrap(text, width=width, initial_indent=prefix, subsequent_indent=cont,
                         break_on_hyphens=False, break_long_words=False)


# ---------------------------------------------------------------------------------------------
# The frozen function
# ---------------------------------------------------------------------------------------------
class Cut:
    def __init__(self):
        self.asm = base(rows.ASM)
        self.P = fz.Frozen(self.asm)
        self.alias = {s.name: s for s in self.P.aliases}
        self.alias_order = [s.name for s in self.P.aliases]
        self.roots = dict(rows.ROOTS)
        self.frame = {n: (b, t) for n, b, t in rows.FRAME_MEMBERS}
        self.callables = {c["lam"]: c for c in rows.CALLABLES}
        self.lambdas = {}          # lam -> dict(comment, header, body, params)
        self.plpend = None         # the frozen struct's lines
        self.functions = {}        # home -> [source lines blocks]
        self.decls = {}            # home -> [header lines blocks]
        self.alias_used = set()
        for key, _ in rows.PIECES:
            text = "\n".join(self.P.piece_lines(key))
            used = fz.names_used(text)
            for bad in ("build", "carry"):
                if bad in used:
                    fail(f"piece {key}: `{bad}` is a free identifier of the frozen text")

    # ---- bindings ---------------------------------------------------------------------------
    def bindings(self, body, kind, declared=()):
        """The binding lines for @p body (lines).  kind: 'top' (StationBuild& build), 'carry'
        (StationCarryFrame& carry), 'helper' (a CALLABLE helper, carry param)."""
        text = "\n".join(body)
        used = fz.names_used(text) - fz.top_level_decls(text) - set(declared)
        need = {n for n in used if n in self.roots or n in self.alias or n in self.frame
                or n in self.callables}
        changed = True
        while changed:
            changed = False
            for n in list(need):
                deps = []
                if n in self.alias:
                    deps = [r for r in self.alias[n].reads
                            if r in self.alias or r in self.roots]
                deps += rows.ROOT_DEPS.get(n, [])
                for d in deps:
                    if d not in need:
                        need.add(d)
                        changed = True
        if kind == "top" and any(n in self.frame or n in self.callables for n in need):
            fail(f"a top-level step reads frame names {sorted(n for n in need if n in self.frame)}")
        out = list(BIND_HEAD)
        roots = [(n, l) for n, l in rows.ROOTS if n in need]
        if roots and kind != "top":
            out.append("    " + rows.BUILD_FROM_CARRY)
        out += ["    " + l for _, l in roots]
        out += ["    " + b for n, b, _ in rows.FRAME_MEMBERS if n in need]
        for c in rows.CALLABLES:
            if c["lam"] in need:
                out += self.forwarder(c)
        aliases = [n for n in self.alias_order if n in need]
        if aliases:
            out.append(ALIAS_HEAD)
            for n in aliases:
                out += self.alias[n].text()
                self.alias_used.add(n)
        out.append(BIND_END)
        return out

    def forwarder(self, c):
        lam = self.lambdas[c["lam"]]
        head = lam["header"]
        ind = indent_of(head[0])
        out = ["    " + l[ind:] if l.strip() else "" for l in head]
        args = ", ".join(["carry"] + [p["name"] for p in lam["params"]])
        ret = "return " if c["ret"] != "void" else ""
        out.append(f"        {ret}{c['func']}({args});")
        out.append("    };")
        return out

    # ---- pieces ------------------------------------------------------------------------------
    def guard_piece(self, lines, b, cond, split=(), ret="return StationStep::Next;"):
        """GUARD: the piece is comments, one `if (cond) {`, its body, `}`, comments; base
        indentation @p b.  Returns the function-body lines (indentation 4)."""
        ci = [k for k, l in enumerate(lines) if is_code(l)]
        head, tail = ci[0], ci[-1]
        if lines[head] != " " * b + f"if ({cond}) {{" or lines[tail] != " " * b + "}":
            fail(f"GUARD {cond!r}: the piece is not one `if ({cond}) {{ ... }}` at {b}: "
                 f"{lines[head]!r} / {lines[tail]!r}")
        g = negate(conj(list(split) + [cond]))
        return (shift(lines[:head], b - 4, cond) + [f"    if ({g}) {ret}"]
                + shift(lines[head + 1:tail], b, cond) + shift(lines[tail + 1:], b - 4, cond))

    def frame_decl(self, lines, name, binding, require=True):
        """FRAME: replace the frozen declaration of frame member @p name (a statement of one or
        more lines) by @p binding at the same position, keeping the first line's trailing
        comment."""
        _, ftype = self.frame[name]
        pat = re.compile(r"^(\s*)" + re.escape(ftype) + r"\s+" + re.escape(name) + r"\s*(=|;|\{)")
        hits = [k for k, l in enumerate(lines) if pat.match(l)]
        if len(hits) != 1:
            if not require and not hits:
                return lines
            fail(f"FRAME {name}: {len(hits)} frozen declarations in the piece")
        k = hits[0]
        e = k
        while not re.sub(r"//.*$", "", lines[e]).rstrip().endswith(";"):
            e += 1
        ind = indent_of(lines[k])
        tc = trailing_comment(lines[k])
        new = " " * ind + binding + (("  " + tc) if tc else "")
        self.frame_src = getattr(self, "frame_src", {})
        self.frame_src[name] = lines[k:e + 1]
        return lines[:k] + [new] + lines[e + 1:]

    def take_lambdas(self, lines):
        """CALLABLE and TYPE_MOVE: cut the three lambdas (with the comment blocks directly above
        them) and the PlPend struct out of piece c1."""
        out = list(lines)
        for c in rows.CALLABLES:
            pat = re.compile(r"^(\s*)const auto " + c["lam"] + r" = \[&\]\(")
            hits = [k for k, l in enumerate(out) if pat.match(l)]
            if len(hits) != 1:
                fail(f"CALLABLE {c['lam']}: {len(hits)} definitions")
            k = hits[0]
            ind = indent_of(out[k])
            h = k
            while not out[h].rstrip().endswith("{"):
                h += 1
            e = next(j for j in range(h + 1, len(out)) if out[j] == " " * ind + "};")
            cfirst = k
            while cfirst - 1 >= 0 and fz.is_comment(out[cfirst - 1]):
                cfirst -= 1
            header = out[k:h + 1]
            htext = " ".join(l.strip() for l in header)
            m = re.match(r"const auto \w+ = \[&\]\((.*)\) \{$", htext)
            if not m:
                fail(f"CALLABLE {c['lam']}: cannot read the header {htext!r}")
            params = []
            for p in split_top(m.group(1)):
                d = None
                if "=" in p:
                    p, d = [x.strip() for x in p.split("=", 1)]
                params.append(dict(text=p.strip(), name=re.findall(r"\w+", p)[-1], default=d))
            self.lambdas[c["lam"]] = dict(comment=out[cfirst:k], header=header,
                                          body=out[h + 1:e], params=params, indent=ind)
            out = out[:cfirst] + out[e + 1:]
        k = next(k for k, l in enumerate(out) if l.strip().startswith("struct PlPend {"))
        e = next(j for j in range(k, len(out)) if out[j].strip() == "};")
        self.plpend = out[k:e + 1]
        out = out[:k] + out[e + 1:]
        # A pointer comment where the lambdas stood (comments are not verified).
        k = next(k for k, l in enumerate(out) if "const bool do_amb_carry" in l)
        ind = indent_of(out[k])
        note = [" " * ind + "// The variance tail, the fold note and the row build are the three "
                "ambiguity-carry",
                " " * ind + "// helpers of NetworkLevelingCarry.cpp, bound above under their "
                "frozen names (card NOM3",
                " " * ind + "// step PB1b, CALLABLE); PlPend is a namespace type "
                "(filter/NetworkStationBuild.hpp)."]
        e = k
        while not out[e].rstrip().endswith(";"):
            e += 1
        return out[:e + 1] + note + out[e + 1:]

    def common_edits(self, lines, what):
        out = []
        for l in lines:
            for old, new in rows.CALL_SITES:
                if old in l:
                    l = l.replace(old, new)
                    self.call_hits[old] = self.call_hits.get(old, 0) + 1
            out.append(l)
        return out

    # ---- the steps -----------------------------------------------------------------------------
    def step_body(self, row, table):
        P = self.P
        name = row["name"]
        if table == "top":
            b = 12
            if name == "carried_priors":
                return self.carried_priors_body(row)
            lines = P.piece_lines(row["pieces"][0])
            if row.get("guard"):
                body = self.guard_piece(lines, b, row["guard"])
            else:
                body = shift(lines, b - 4, name)
            if name == "data_rows":
                body = self.data_rows_edits(body)
            body = body + ["    return StationStep::Next;"]
        else:
            b = 16
            lines = P.piece_lines(row["pieces"][0])
            if name == "ambiguity":
                lines = self.take_lambdas(lines)
                if lines[0] != " " * b + row["head_old"]:
                    fail(f"ambiguity: the piece does not open with {row['head_old']!r}")
                body = (["    if (" + negate(conj(row["split"])) + ") return;"]
                        + shift(lines[1:], b - 4, name) + ["    " + row["tail_insert"]])
            elif row.get("guard"):
                body = self.guard_piece(lines, b, row["guard"], split=row.get("split", ()),
                                        ret="return;")
            elif row.get("unwrap"):
                ci = [k for k, l in enumerate(lines) if is_code(l)]
                if lines[ci[0]] != " " * b + "{" or lines[ci[-1]] != " " * b + "}":
                    fail("UNWRAP: the piece is not one bare block")
                body = (shift(lines[:ci[0]], b - 4, name) + shift(lines[ci[0] + 1:ci[-1]], b, name)
                        + shift(lines[ci[-1] + 1:], b - 4, name))
            else:
                body = (["    if (" + negate(conj(row["split"])) + ") return;"]
                        + shift(lines, b - 4, name))
            for n, bnd, _ in rows.FRAME_MEMBERS:
                if n in ("legacy_local_inject", "x_lin", "cb", "inj", "inj_prior"):
                    continue
                body = self.frame_decl(body, n, bnd, require=False)
        return self.common_edits(body, name)

    def data_rows_edits(self, body):
        old, new, ref = rows.RESULT
        k = [j for j, l in enumerate(body) if l.strip() == old]
        if len(k) != 1:
            fail("RESULT: the measurement update line not found once")
        k = k[0]
        body[k] = body[k].replace(old, new)
        e = k
        while not body[e].rstrip().endswith(";"):
            e += 1
        body.insert(e + 1, " " * indent_of(body[k]) + ref)
        n = 0
        for j, l in enumerate(body):
            if rows.EXIT[0] in l:
                body[j] = l.replace(rows.EXIT[0], rows.EXIT[1])
                n += 1
        if n != 2:
            fail(f"EXIT: {n} loop-level continues in data_rows (2 expected)")
        return body

    def carried_priors_body(self, row):
        P = self.P
        lli = shift(P.piece_lines("LLI"), 8, "LLI")
        head = P.piece_lines("T10") + P.piece_lines("T10close")
        body = self.guard_piece(head, 12, row["guard"])
        # FRAME: the frozen declarations of x_lin, inj, inj_prior and cb become references to
        # the frame's members; the frame is constructed at the first of them.
        for n in ("x_lin", "inj", "inj_prior", "cb"):
            body = self.frame_decl(body, n, self.frame[n][0])
        src = self.frame_src
        dac = " ".join(l.strip() for l in self.frame_src_dac())
        m = re.match(r"const bool do_amb_carry =\s*(.*);$", dac)
        if not m:
            fail(f"PURE_DECL_MOVE: cannot read do_amb_carry: {dac!r}")
        xl = re.match(r"\s*const Eigen::VectorXd x_lin = (.*);\s*$", src["x_lin"][0])
        cbl = src["cb"]
        if not cbl[0].strip().startswith("CouplingRowBuilder cb{"):
            fail("FRAME cb: unexpected frozen form")
        cb_lines = [cbl[0].strip().replace("CouplingRowBuilder cb{", "CouplingRowBuilder{")]
        cb_lines += [l.strip() for l in cbl[1:]]
        cb_lines[-1] = cb_lines[-1][:-1]          # the frozen `;`
        pad = " " * len("    StationCarryFrame carry{")
        cpad = " " * len("CouplingRowBuilder{")
        frame = ["    StationCarryFrame carry{build, legacy_local_inject,",
                 f"{pad}{m.group(1)},",
                 f"{pad}{xl.group(1)},",
                 f"{pad}{cb_lines[0]}"]
        frame += [f"{pad}{cpad}{l}" for l in cb_lines[1:]]
        frame[-1] += "};"
        k = next(j for j, l in enumerate(body) if l.strip().startswith("const Eigen::VectorXd& x_lin"))
        body = (body[:k]
                + ["    // The frame (filter/NetworkStationBuild.hpp): the values the carry steps hand",
                   "    // each other (card NOM3 step PB1b; do_amb_carry is the frozen P12 predicate)."]
                + frame + body[k:])
        walk = ["    // The carry steps, in table order (kStationCarrySteps, card NOM3 step PB1b).",
                "    for (const StationCarryStep& s : kStationCarrySteps) s.build(carry);",
                "    return StationStep::Next;"]
        body = lli + body + walk
        return self.common_edits(body, row["name"])

    def frame_src_dac(self):
        lines = self.P.piece_lines("c1")
        k = next(j for j, l in enumerate(lines) if l.strip().startswith("const bool do_amb_carry ="))
        e = k
        while not lines[e].rstrip().endswith(";"):
            e += 1
        return lines[k:e + 1]

    def step_function(self, row, table):
        body = self.step_body(row, table)
        if table == "top":
            sig = f"StationStep {row['func']}(StationBuild& build) {{"
            binds = self.bindings(body, "top")
        else:
            sig = f"void {row['func']}(StationCarryFrame& carry) {{"
            binds = self.bindings(body, "carry")
        return [sig] + binds + [""] + body + ["}"]

    def callable_function(self, c):
        lam = self.lambdas[c["lam"]]
        body = shift(lam["body"], lam["indent"], c["lam"])
        frame = "const StationCarryFrame& carry" if c["const_frame"] else "StationCarryFrame& carry"
        params = ", ".join([frame] + [p["text"] for p in lam["params"]])
        sig = wrap_sig(f"{c['ret']} {c['func']}(", params, ") {")
        binds = self.bindings(body, "helper")
        comment = shift(lam["comment"], lam["indent"], c["lam"])
        return comment + sig + binds + [""] + body + ["}"]

    def callable_decl(self, c):
        lam = self.lambdas[c["lam"]]
        frame = "const StationCarryFrame& carry" if c["const_frame"] else "StationCarryFrame& carry"
        params = ", ".join([frame] + [p["text"] + (f" = {p['default']}" if p["default"] else "")
                                      for p in lam["params"]])
        doc = ["/**",
               f" * @brief The ambiguity carry's `{c['lam']}` (card NOM3 step PB1b, CALLABLE): the frozen",
               " *        lambda's body as a function of the station's carry frame.  The ambiguity and",
               " *        local-block steps bind the frozen name to a forwarder with the frozen parameter",
               " *        list.",
               " * @param carry The station's carry frame (filter/NetworkStationBuild.hpp).",
               " */"]
        return doc + wrap_sig(f"{c['ret']} {c['func']}(", params, ");")

    # ---- MEMBER_TO_FREE ---------------------------------------------------------------------------
    def helper_function(self, h):
        P = self.P
        info = P.helpers[h["old"]]
        L = P.lines
        comment = L[info["comment_first"] - 1:info["sig_first"] - 1]
        body_first = P.T.line(info["body_open"])
        if L[body_first - 1].rstrip().endswith("{") is False:
            fail(f"{h['old']}: the body brace is not at a line end")
        body = L[body_first:info["end"] - 1]
        params = ", ".join(h["lead"] + P.helper_params(h["old"]))
        ret = L[info["sig_first"] - 1].split("Application::")[0].strip()
        return comment + wrap_sig(f"{ret} {h['new']}(", params, ") {") + body + ["}"]

    def helper_decl(self, h, app_hpp):
        """The helper's Doxygen block from Application.hpp, de-indented, and its declaration."""
        P = self.P
        doc = app_decl_doc(app_hpp, h["old"])
        info = P.helpers[h["old"]]
        ret = P.lines[info["sig_first"] - 1].split("Application::")[0].strip()
        params = ", ".join(h["lead"] + P.helper_params(h["old"]))
        doc = doc[:-1] + [" *",
                          " * Card NOM3 step PB1b: a free function (formerly Application::"
                          f"{h['old']}), so the station",
                          " * steps in the family files can call it"
                          + ("; @p config_ is the run's configuration" if h["lead"] else "")
                          + (", @p gim_ Application::gim_" if len(h["lead"]) > 1 else "") + "."] + [doc[-1]]
        return doc + wrap_sig(f"{ret} {h['new']}(", params, ");")


def split_top(s):
    out, d, cur = [], 0, ""
    for ch in s:
        if ch in "(<[{":
            d += 1
        elif ch in ")>]}":
            d -= 1
        if ch == "," and d == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [x.strip() for x in out]


def wrap_sig(head, params, tail, width=100):
    one = head + params + tail
    if len(one) <= width:
        return [one]
    ps = split_top(params)
    lines, cur = [], head
    for k, p in enumerate(ps):
        piece = p + (", " if k + 1 < len(ps) else tail)
        if len(cur) + len(piece.rstrip()) > width and cur.strip() != head.strip():
            lines.append(cur.rstrip())
            cur = " " * len(head)
        cur += piece
    lines.append(cur)
    return lines


def app_decl_doc(app, old):
    """The Doxygen block directly above Application's declaration of @p old, de-indented."""
    L = app.split("\n")
    k = next(j for j, l in enumerate(L) if re.search(r"\b" + re.escape(old) + r"\(", l)
             and not l.strip().startswith("*") and not l.strip().startswith("//"))
    e = k - 1
    if L[e].strip() != "*/":
        fail(f"Application.hpp: no Doxygen block above {old}")
    s = e
    while L[s].strip() != "/**":
        s -= 1
    return [l[4:] if l.startswith("    ") else l for l in L[s:e + 1]]


def app_decl_range(app, olds):
    """[first, last) line indices of Application.hpp's contiguous block of the declarations of
    @p olds (each with its Doxygen), plus one trailing blank line."""
    L = app.split("\n")
    spans = []
    for old in olds:
        k = next(j for j, l in enumerate(L) if re.search(r"\b" + re.escape(old) + r"\(", l)
                 and not l.strip().startswith("*") and not l.strip().startswith("//"))
        s = k - 1
        while L[s].strip() != "/**":
            s -= 1
        e = k
        while not L[e].rstrip().endswith(";"):
            e += 1
        spans.append((s, e + 1))
    spans.sort()
    for (a, b), (c, d) in zip(spans, spans[1:]):
        if any(L[j].strip() for j in range(b, c)):
            fail("Application.hpp: the helper declarations are not contiguous")
    lo, hi = spans[0][0], spans[-1][1]
    if hi < len(L) and not L[hi].strip():
        hi += 1
    return lo, hi


