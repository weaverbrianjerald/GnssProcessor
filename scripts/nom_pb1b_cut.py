#!/usr/bin/env python3
"""Generator of card NOM3 step PB1b: PASS B's parallel produce as two declared step tables.

    python scripts/nom_pb1b_cut.py [--check] [--survey]

Reads Application::networkPassB_ at rows_pb1b.BASE (git show; scripts/nom_pb1/frozen_pb1b.py)
and the canonical rows (scripts/nom_pb1/rows_pb1b.py), and writes into the working tree:

  - each station step of rows.TOP / rows.CARRY as a free function in a generated region at
    the end of its family file (filter/<home>.cpp), its declaration and Doxygen in the family
    header; ten family file pairs are new.  A step opens with its bindings (the closed ROOT
    list, the frame members it reads, the CALLABLE forwarders, verbatim copies of the alias
    lines of networkPassB_ it reads) and continues with its frozen pieces, shifted, under the
    declared transforms of rows_pb1b's docstring;
  - the three ambiguity-carry lambdas as functions (CALLABLE), PlPend as a namespace type;
  - Application's five row builders as free functions in their family files (MEMBER_TO_FREE;
    their declarations leave include/app/Application.hpp);
  - include/filter/NetworkStationBuild.hpp: StationStep, StationBuild, StationCarryFrame and the
    two tables; src/core/filter/NetworkStationBuild.cpp: the tables, the walk and
    networkAssemblyProduce (the frozen loop around the walk);
  - networkPassB_: its bindings restricted to what it still reads, the loop replaced by the
    call of networkAssemblyProduce, the fallback parameter name nep back to ep;
  - the declared output moves (rows.OUTPUT_MOVES, the contributions builder column) and their
    reverse map D:/GnssProcessorSupport/gates/pb1b/reverse.sed;
  - CMakeLists.txt entries, the ContributionKindSet alias.

Every edit starts from the base text of the file it edits, so a second run is a no-op, and
--check reports any file whose bytes differ from what the generator would write.
"""
