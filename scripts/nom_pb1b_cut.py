def plpend_type(cut):
    lines = shift(cut.plpend, indent_of(cut.plpend[0]), "PlPend")
    out = []
    for l in lines:
        tc = trailing_comment(l)
        if tc and not l.strip().startswith("//"):
            code = l[:l.index(tc)].rstrip()
            out.append(code if l.strip().startswith("struct PlPend") else f"{code}   ///< {tc[2:].strip()}")
        else:
            out.append(l)
    return "\n".join(out)


def station_build_header(text, cut):
    text = add_includes(text, SB_INCLUDES)
    k = text.index("// ---- PASS B serial stages, declarations")
    fwd = "\n".join(SB_FWD) + "\n"
    text = text[:k] + fwd + "\n" + text[k:]
    block = SB_TYPES.replace("@PLPEND@", plpend_type(cut)).replace("@PRODUCE_DOC@", PRODUCE_DOC)
    return insert_before_namespace_close(text, block.split("\n"), "NetworkStationBuild.hpp")


def kinds_expr(kinds):
    if not kinds:
        return "0"
    return " | ".join(f"kindBit(CK::{k})" for k in kinds)


def station_build_source(text, cut):
    homes = sorted({r["home"] for r in rows.TOP + rows.CARRY} | {h["home"] for h in rows.HELPERS})
    text = add_includes(text, [f'"filter/{h}.hpp"' for h in homes if h != "NetworkStationBuild"]
                        + ['"app/NetworkRun.hpp"', '"app/NetworkEpoch.hpp"', '"common/EpochMeasurement.hpp"'])
    carry_union = []
    for r in rows.CARRY:
        for k in r["kinds"]:
            if k not in carry_union:
                carry_union.append(k)
    out = [REGION_OPEN, "", "namespace {", "using CK = ContributionKind;", "}  // namespace", ""]
    out.append("const std::array<StationBuildStep, kStationBuildStepCount> kStationBuildSteps = {{")
    for r in rows.TOP:
        ks = carry_union if r["kinds"] == "carry" else r["kinds"]
        out.append(f'    {{"{r["name"]}", "filter/{r["home"]}",')
        out += wrap("     ", kinds_expr(ks) + ",", width=100, cont="     ")
        out.append(f"     &{r['func']}}},")
    out.append("}};")
    out.append("")
    out.append("const std::array<StationCarryStep, kStationCarryStepCount> kStationCarrySteps = {{")
    for r in rows.CARRY:
        out.append(f'    {{"{r["name"]}", "filter/{r["home"]}",')
        out += wrap("     ", kinds_expr(r["kinds"]) + ",", width=100, cont="     ")
        out.append(f"     &{r['func']}}},")
    out.append("}};")
    out += ["", "bool networkStationBuild(StationBuild& build) {",
            "    for (const StationBuildStep& s : kStationBuildSteps)",
            "        if (s.build(build) == StationStep::Done) return false;",
            "    return true;", "}", ""]
    out += produce_function(cut)
    out += ["", REGION_CLOSE]
    return insert_before_namespace_close(text, out, "NetworkStationBuild.cpp")


