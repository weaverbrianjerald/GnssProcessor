def passb_new(cut):
    P = cut.P
    L = P.lines
    rest_hi = L[P.banner - 1:P.pragma - 1] + [
        "    // The parallel produce: one station's block per OpenMP iteration, the station steps of",
        "    // kStationBuildSteps (filter/NetworkStationBuild.hpp, card NOM3 step PB1b).",
        "    networkAssemblyProduce(run, ep, gim_, assembly);",
    ] + L[P.loop_close:P.close_line - 1]
    rest_hi = [re.sub(r"\bnep\b", "ep", l) for l in rest_hi]
    text = "\n".join(rest_hi)
    used = fz.names_used(text) | {"gim_"}
    need = {n for n in used if n in cut.alias or any(s.name == n for s in P.roots)}
    changed = True
    while changed:
        changed = False
        for n in list(need):
            if n in cut.alias:
                for r in cut.alias[n].reads:
                    if (r in cut.alias or any(s.name == r for s in P.roots)) and r not in need:
                        need.add(r)
                        changed = True
    sig = [re.sub(r"\bnep\b", "ep", l) for l in L[P.sig_first - 1:P.open_line]]
    head = L[P.ep1_head - 1:P.ep1_head + 2]
    roots = []
    for s in P.roots:
        if s.name in need:
            roots += [re.sub(r"\bnep\b", "ep", l) for l in s.text(with_comment=False)]
    aliases = []
    for s in P.aliases:
        if s.name in need:
            aliases += s.text()
    return sig + head + roots + [L[P.ep1_end - 1]] + aliases + [""] + rest_hi + [L[P.close_line - 1]], need


