ROOT = HERE.parent
GEN = "scripts/nom_pb1b_cut.py"
REGION_OPEN = f"// ---- PASS B station steps (card NOM3 step PB1b; generated by {GEN}) ----"
REGION_CLOSE = "// ---- End of the PASS B station steps (card NOM3 step PB1b) ----"
HREGION_OPEN = f"// ---- PASS B station steps, declarations (card NOM3 step PB1b; generated by {GEN}) ----"
