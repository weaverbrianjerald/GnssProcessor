def produce_function(cut):
    P = cut.P
    L = P.lines
    # Replace the try body (prod_head ... prod_tail) by the walk.
    s, _ = P.pieces["prod_head"]
    t, _ = P.pieces["prod_tail"]
    head = L[P.pragma - 1:s]                       # pragma .. NetStation& st
    tail = L[t - 1:P.loop_close]                   # R.ok = true; .. loop close
    walk = ["            StationBuild build{ctx, config_, est, setup, se, epoch_clock, pass_a, gim, i, st, R};",
            "            if (!networkStationBuild(build)) continue;   // empty innovations or an H/state mismatch"]
    body = head + walk + tail
    pre = ["void networkAssemblyProduce(NetworkRun& run, const NetworkEpoch& ep,",
           "                            const std::unique_ptr<GlobalIonosphereMap>& gim,",
           "                            EpochAssembly& assembly) {",
           "    // ---- From the run and the epoch (card NOM3 step PB1b; generated by scripts/nom_pb1b_cut.py,",
           "    //      each line checked by scripts/nom_pb1b_verify.py). Reads bind through `ep`; writes bind",
           "    //      through the output parameters and are marked `// written`. ----",
           "    NetworkRunContext& ctx = run.ctx;",
           "    const GnssConfig& config_ = run.config;",
           "    NetworkSetupResult& setup = run.setup;",
           "    NetworkEstimator& est = run.engines.est;",
           "    const SyncedEpoch& se = ep.se;",
           "    const EpochClock& epoch_clock = ep.clock;",
           "    const EpochPassA& pass_a = ep.pass_a;",
           "    const std::vector<bool>& present = pass_a.present;",
           "    std::vector<StationAssembly>& asm_res = assembly.asm_res;  // written",
           ALIAS_HEAD]
    for n in ("stations", "n_sta_total", "parallel_on", "n_threads"):
        pre += cut.alias[n].text()
        cut.alias_used.add(n)
    pre.append(BIND_END)
    return pre + body + ["}"]


