def contributions(text):
    sed = []
    lines = text.split("\n")
    # The shared constants: rewrite their literal text.
    for const, (step, func, file) in rows.CONTRIB_BUILDERS.items():
        k = next(j for j, l in enumerate(lines) if l.startswith(f"constexpr const char* {const} "))
        e = k
        while not lines[e].rstrip().endswith(";"):
            e += 1
        old = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', "\n".join(lines[k:e + 1])))
        new = rows.builder_text(step, func, file)
        decl = f"constexpr const char* {const} = "
        lines[k:e + 1] = [decl + f'"{new}";']
        sed.append(sed_line(new, old))
    # Per-kind constants.
    consts = {}
    for kind, (const, step, func, file) in rows.CONTRIB_KIND_BUILDERS.items():
        consts[const] = rows.builder_text(step, func, file)
    k = next(j for j, l in enumerate(lines) if l.startswith("constexpr const char* kCplRows "))
    new_consts = [f'constexpr const char* {c} = "{t}";' for c, t in consts.items()]
    lines[k:k] = ["// The builder column of the station kinds, from the step rows of card NOM3 step PB1b",
                  "// (scripts/nom_pb1/rows_pb1b.py, decision 3): the function and file that create the",
                  "// kind's rows, and the station step that calls it."] + new_consts
    text = "\n".join(lines)
    old_const_text = {}
    for c in ("kCarryWalk", "kGloFold"):
        m = re.search(r"constexpr const char\* " + c + r" = ((?:\s*\"(?:[^\"\\]|\\.)*\")+);", text)
        if m:
            old_const_text[c] = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1)))
    old_glo = None
    for kind, (const, step, func, file) in rows.CONTRIB_KIND_BUILDERS.items():
        m = re.search(r"\{CK::" + kind + r",(.*?)\},\n", text, re.S)
        if not m:
            fail(f"contributions: no spec row for {kind}")
        row = m.group(0)
        lits = re.findall(r'"Application::networkAppend\w+_ \(ApplicationNetworkAssembly\.cpp\)"', row)
        if lits:
            new_row = row.replace(lits[0], const)
            sed.append(sed_line(consts[const], lits[0].strip('"')))
        elif "kCarryWalk" in row:
            new_row = re.sub(r"\bkCarryWalk\b", const, row)
            sed.append(sed_line(consts[const], old_const_text["kCarryWalk"]))
        elif "kGloFold" in row:
            new_row = re.sub(r"\bkGloFold\b", const, row)
            old_glo = "Application::networkPassB_, GLONASS anchors (ApplicationNetworkAssembly.cpp)"
            sed.append(sed_line(consts[const], old_glo))
        else:
            fail(f"contributions: {kind}'s builder is not a known literal")
        text = text.replace(row, new_row)
    # kCarryWalk is now unused: drop it.
    text = re.sub(r"constexpr const char\* kCarryWalk = (?:\s*\"(?:[^\"\\]|\\.)*\")+;\n", "", text)
    # A sed line per new text once (duplicates folded, longer patterns first).
    seen, out = set(), []
    for s in sorted(sed, key=len, reverse=True):
        if s not in seen:
            seen.add(s)
            out.append(s)
    return text, out


