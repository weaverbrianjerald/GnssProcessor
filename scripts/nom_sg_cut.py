#!/usr/bin/env python3
"""Generator of card NOM3 step SG (the solve as a linear orchestrator).

    python scripts/nom_sg_cut.py --survey          # every resolved piece and the coverage
    python scripts/nom_sg_cut.py --stage sg1       # write the generated regions
    python scripts/nom_sg_cut.py --check           # regenerate in memory; exit 1 on any difference

The frozen source is src/core/filter/NetworkSolveGlue.cpp at the base (scripts/nom_sg/stages.py,
BASE), read with `git show`.  The table is scripts/nom_sg/rows.py.  Each new function is written
inside the marked region of its home file:

    // ---- Solve stages (card NOM3 step SG; generated by scripts/nom_sg_cut.py) ----
    ...
    // ---- End of the solve stages ----

A function is: a one-line comment, its signature, a generated preamble (one binding per name
its body reads from the solve's scope, in the solve's order, dependency-closed: a frozen
binding line verbatim, or a declared REALIZE / KNOB / FRESH_STATELESS line of its row), the
frozen pieces with the generated statements between them, and the generated tail.  The regions
of the home files are created by hand (the file banners, includes and hand-written exit table
are not generated); this script only fills them.
"""
import argparse
import re
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from nom_sg import stages as S  # noqa: E402
from nom_sg import rows as R    # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]


def solve_scope(fz):
    """Canon statements and the names the solve declared (canon, locals, parameters)."""
    canon = S.canon(fz)
    names = {c[0] for c in canon} | set(S.SOLVE_LOCALS) | set(S.SOLVE_PARAMS)
    return canon, names


def own_locals(fz, fn):
    """The solve's function-scope locals whose declaring line lies in this function's pieces."""
    lines = set()
    for item in fn.body:
        if isinstance(item, S.P):
            a, b = S.resolve(fz, item)
            lines.update(range(a, b + 1))
    out = set()
    for name, anchor in S.SOLVE_LOCALS.items():
        try:
            n = fz.find(anchor)
        except AssertionError:
            continue
        if n in lines:
            out.add(name)
    return out


GEN_DECL = re.compile(r"^\s+(?:const\s+)?[\w:<>]+\s+(\w+)\s*(?:=|;)")


def gen_declared(fn):
    """Names the function's generated lines declare (the orchestrator's typed values)."""
    out = set()
    for item in fn.body:
        if isinstance(item, S.G):
            for line in item.lines:
                m = GEN_DECL.match(line)
                if m and not line.strip().startswith("return"):
                    out.add(m.group(1))
    return out


def preamble(fz, fn, canon, names):
    """The preamble lines (absolute indent) for fn, and the names it binds."""
    body = S.render_body(fz, fn) + fn.tail
    read = S.idents_read("\n".join(S.code_lines(body)))
    provided = set(fn.params) | own_locals(fz, fn) | gen_declared(fn)
    binds = {b[0]: b for b in fn.binds}
    canon_by = {c[0]: c for c in canon}
    want = set()
    todo = [n for n in read if n in names or n in binds]
    while todo:
        n = todo.pop()
        if n in provided or n in want:
            continue
        if n in binds:
            want.add(n)
            rhs = binds[n][1].split("=", 1)[1] if "=" in binds[n][1] else ""
            todo.extend(d for d in S.idents_read(S.blank_code(rhs, [False])) if d in names or d in binds)
        elif n in canon_by:
            want.add(n)
            todo.extend(d for d in canon_by[n][2] if d in names or d in binds)
        else:
            raise SystemExit(f"{fn.name}: unbound solve-scope name {n!r} (no parameter, binding or local)")
    out = []
    for name, text, _deps in canon:
        if name in want and name not in binds:
            out.extend(text)
    for name, line, _cls in fn.binds:
        if name in want:
            out.append("    " + line)
    return out, want


def render_fn(fz, fn, canon, names):
    if fn.kind == "comment":
        return S.render_body(fz, fn)
    pre, _ = preamble(fz, fn, canon, names)
    out = [f"/// {fn.brief} (card NOM3 step SG; Doxygen at the declaration)."] + list(fn.sig)
    if pre:
        out += S.PRE_OPEN.split("\n") + pre + [S.PRE_CLOSE]
    out += S.render_body(fz, fn) + fn.tail + ["}"]
    return out


def regions(fz):
    canon, names = solve_scope(fz)
    by_home = {}
    for fn in R.FUNCTIONS:
        by_home.setdefault(fn.home, []).append(render_fn(fz, fn, canon, names))
    out = {}
    for home, fns in by_home.items():
        text = []
        for i, f in enumerate(fns):
            if i:
                text.append("")
            text.extend(f)
        out[home] = text
    return out


CRLF, LF = chr(13) + chr(10), chr(10)


def read_lf(path):
    """A home file's text with LF line ends (a checkout under core.autocrlf holds CRLF)."""
    return (ROOT / path).read_bytes().decode("utf-8").replace(CRLF, LF)


def splice(path, region):
    text = read_lf(path)
    lines = text.split("\n")
    try:
        a = lines.index(S.REGION_OPEN)
        b = lines.index(S.REGION_CLOSE)
    except ValueError:
        raise SystemExit(f"{path}: the generated region markers are missing")
    assert a < b
    return "\n".join(lines[:a + 1] + region + lines[b:])


def survey(fz):
    canon, names = solve_scope(fz)
    covered = {}
    for fn in R.FUNCTIONS:
        for item in fn.body:
            if isinstance(item, S.P):
                a, b = S.resolve(fz, item)
                print(f"{item.row:5} {fn.name:34} {a:5}-{b:<5} {item.form:6} {fz.line(a).strip()[:40]!r} .. "
                      f"{fz.line(b).strip()[:30]!r}")
                for n in range(a, b + 1):
                    covered.setdefault(n, []).append(fn.name)
    for d in R.DROPS:
        a = fz.find(d.first)
        b = a if d.last is None else (fz.find(d.last) if isinstance(d.last, tuple) else fz.find(d.last, a))
        print(f"{d.row:5} {d.cls:34} {a:5}-{b:<5}        {fz.line(a).strip()[:40]!r}")
        for n in range(a, b + 1):
            covered.setdefault(n, []).append(d.cls)
    gaps, doubles = [], []
    for n in range(fz.first, fz.last + 1):
        code = fz.code[n - 1].strip()
        if n not in covered:
            if code:
                gaps.append(n)
        elif len(covered[n]) > 1:
            doubles.append(n)
    print(f"function {fz.first}-{fz.last}; canon {len(canon)} statements; "
          f"uncovered code lines {gaps[:20]}; doubly covered {doubles[:20]}")
    return not gaps and not doubles


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--survey", action="store_true")
    ap.add_argument("--stage", choices=["sg1"])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--base", default=S.BASE)
    a = ap.parse_args(argv)
    fz = S.Frozen(S.git_show(a.base, S.SG_CPP))
    if a.survey:
        return 0 if survey(fz) else 1
    regs = regions(fz)
    bad = 0
    for home, region in regs.items():
        new = splice(home, region)
        cur = read_lf(home)
        crlf = CRLF in (ROOT / home).read_bytes().decode("utf-8")
        if a.check:
            if new != cur:
                print(f"DIFFERS: {home}")
                bad += 1
        elif a.stage and new != cur:
            (ROOT / home).write_bytes((new.replace(LF, CRLF) if crlf else new).encode("utf-8"))
            print(f"wrote {home}")
    if a.check:
        print("check: " + ("identical" if not bad else f"{bad} file(s) differ"))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
