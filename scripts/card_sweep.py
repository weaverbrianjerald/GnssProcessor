"""Deterministic card-citation removal in comment text (measure mode by default).
Pattern classes (comment portion of a line only; string literals never touched):
  P1  a parenthetical that is only a card citation: "(card NOM3 step EP2)", "(cards RF-1, RF-2b)"
  P2  a leading citation inside a parenthetical: "(card NOM3 step EP2; generated by ...)" -> "(generated by ...)"
"""
import re, subprocess, sys
ID = r'[A-Z][A-Za-z0-9]*(?:-[A-Za-z0-9]+)*'
STEP = r'(?:[ \t]+(?:step|steps|section|sections|§|items?|rung|wave|track)[ \t]+[A-Za-z0-9.\-]+(?:[ \t]*(?:,|and|to)[ \t]*[A-Za-z0-9.\-]+)*)?'
CITE = rf'(?:the[ \t]+)?cards?[ \t]+{ID}(?:[ \t]*(?:,|and|/)[ \t]*{ID})*{STEP}'
P1 = re.compile(rf'[ \t]*\([ \t]*{CITE}[ \t]*\)')
P2 = re.compile(rf'\([ \t]*{CITE}[ \t]*[;:,][ \t]*')
STR = re.compile(r'"(?:[^"\
]|\.)*"')
def norm(s):
    """The transform applied to printed text (and to a reference run's outputs at the gate)."""
    s = P1.sub('', s); return P2.sub('(', s)
def sweep_strings(code):
    n = 0
    def f(m):
        nonlocal n
        lit = m.group(0); new = norm(lit)
        if new != lit: n += 1
        return new
    return STR.sub(f, code), n
def comment_span(line):
    s = line.lstrip()
    if s.startswith('*') or s.startswith('/*') or s.startswith('///'):
        return 0 if '"' not in line else None
    i = line.find('//')
    if i >= 0 and line.count('"', 0, i) % 2 == 0: return i
    return None
def main():
    global ns
    apply = '--apply' in sys.argv
    do_str = '--strings' in sys.argv
    ns = 0
    files = [f for f in subprocess.run(['git','ls-files','src','include','tests'],capture_output=True,text=True).stdout.split() if f.endswith(('.cpp','.hpp','.h'))]
    n1=n2=left=0; changed=0; dropped=0
    for f in files:
        t=open(f,encoding='utf-8',errors='surrogateescape',newline='').read(); out=[]; ch=False
        for line in t.splitlines(True):
            body=line.rstrip('\r\n'); eol=line[len(body):]
            i=comment_span(body)
            code, com = (body, '') if i is None else (body[:i], body[i:])
            if do_str and '"' in code and re.search(r'\bcards?[ \t]',code):
                code2,k=sweep_strings(code); ns+=k; code=code2
            if com and re.search(r'\bcards?\b',com,re.I):
                c2,k1=P1.subn('',com); c2,k2=P2.subn('(',c2); n1+=k1; n2+=k2; com=c2
            new=code+com
            if new!=body:
                if re.fullmatch(r'[ \t]*//[ \t]*',com) and code.strip(): new=code.rstrip()
                elif re.fullmatch(r'[ \t]*//[ \t]*',new) and body.strip(): new=None; dropped+=1
                ch=True
            if new is not None:
                if re.search(r'\bcards?[ \t]+[A-Z]',new): left+=1
                out.append(new+eol)
        if ch:
            changed+=1
            if apply: open(f,'w',encoding='utf-8',errors='surrogateescape',newline='').write(''.join(out))
    print(f'P1 {n1}  P2 {n2}  string literals {ns}  dropped empty comment lines {dropped}  files {changed}  lines still naming a card {left}')


if __name__ == '__main__':
    main()
