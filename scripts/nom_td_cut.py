def file_indent(path):
    """4 when the file indents its namespace's contents (a few files do), else 0."""
    text = path.read_text(encoding="utf-8")
    if BEGIN in text:                                  # judge the file without this region
        text = text[:text.index(BEGIN)] + text[text.index(END) + len(END):]
    n4 = len(re.findall(r"^    (?:[A-Za-z_:<>]+ )+network[A-Z]\w*\(", text, re.M))
    n0 = len(re.findall(r"^(?:[A-Za-z_:<>]+ )+network[A-Z]\w*\(", text, re.M))
    return 4 if n4 > 0 and n0 == 0 else 0


def replace_region(text, region, where_re):
    """Replace the marked region, or insert it before the last line matching where_re."""
    if BEGIN in text:
        a = text.rfind("\n", 0, text.index(BEGIN)) + 1      # from the marker line's start
        b = text.index(END, a) + len(END)
        return text[:a] + region + text[b:]
    lines = text.split("\n")
    idx = max(i for i, l in enumerate(lines) if re.match(where_re, l))
    return "\n".join(lines[:idx] + region.split("\n") + [""] + lines[idx:])


def add_includes(text, incs, why):
    lines = text.split("\n")
    first_ns = next(i for i, l in enumerate(lines) if l.startswith("namespace "))
    last_inc = max(i for i, l in enumerate(lines[:first_ns]) if l.startswith("#include"))
    have = set()
    for l in lines[:first_ns]:
        m = re.match(r'#include\s+([<"][^>"]+[>"])', l)
        if m:
            have.add(m.group(1).strip('<>"'))
    proj = sorted(h for h in incs if not h.startswith("<") and h not in have)
    sysh = sorted(h for h in incs if h.startswith("<") and h.strip("<>") not in have)
    if not proj and not sysh:
        return text
    new = ["", f"// {why}:"] + [f'#include "{h}"' for h in proj] + [f"#include {h}" for h in sysh]
    return "\n".join(lines[:last_inc + 1] + new + lines[last_inc + 1:])


