#!/usr/bin/env python3
"""Generate the network run-end reports from the frozen teardown (card NOM step TD1b).

    python scripts/nom_td_cut.py                  # write the reports, the table and the manifest
    python scripts/nom_td_cut.py --survey         # print each report's frozen range and transform
    python scripts/nom_td_cut.py --manifest-only  # rewrite the manifest only; touch no source

The frozen source is networkTeardown as it stood at main 067fdc1, read with `git show`
(no copy is stored).  One canonical table, REPORTS below, names every report: its function,
its home file, the frozen line ranges it carries, and every edit that is not a verbatim
move (a declared substitution, an inserted line, a dropped line).  From that one table the
generator writes

  - each report's definition, in a marked region at the end of its home .cpp (or a whole
    new <Subsystem>RunEnd.cpp), and its declaration with Doxygen in the home header;
  - the declared table kNetworkRunEndReports in src/core/filter/NetworkRunEnd.cpp;
  - networkTeardown in src/core/filter/NetworkTeardown.cpp;
  - the cut's manifest, scripts/nom_td_manifest.json, which scripts/nom_td_verify.py
    reads to prove every relocated body character exact against the frozen source.

Mechanics of one report body (the inverse is in nom_td_verify.py):
  1. The aliases: one declaration per name the body reads from the run (ALIAS below),
     taken from the view `v`, so the moved lines read their original names.
  2. The frozen pieces in order.  A piece is a line range [a, b] with a shift (leading
     spaces removed: 4 for a range that sat inside a `{ }` scope the cut removed).  When
     a report is exactly one braced `if (COND) { ... }` with no else, the generator writes
     `if (!COND) return 0;` and the interior one level out ("guard"); when it is exactly
     one bare `{ ... }` block, it writes the interior one level out ("unwrap").
  3. The tail: `return 0;`, or the report's verdict.

Line numbers are 1-based, inclusive, into the frozen file.

What the generator does not write: the hand-written parts of filter/NetworkRunEnd.hpp
(the view, the row, the count it keeps) and of NetworkRunEnd.cpp and NetworkTeardown.cpp
around their generated regions (marked GEN_BEGIN / GEN_END), and the ordinary edits the
cut needed elsewhere (the existing run-end functions' *RunEnd names and const contexts,
the flag-rate writer's new parameter, the run-context fields no one reads any more).
Re-running it on the tree it produced changes nothing; an edit inside a generated region
belongs in the table here (a declared substitution), or the verifier fails.

Edits after the cut.  Reports and table rows were added after the cut by hand (the table's
post-cut rows), and later cards edited relocated bodies.  Two tables record the edits of
the relocated bodies, so the manifest still proves every body against the frozen source:
REMOVED names the reports whose mechanism was deleted (their frozen ranges become declared
drops, with the reason), and POST_CUT declares every later edit of a surviving body (frozen
lines dropped, substitutions, inserted lines, aliases no longer declared, a new label),
merged into REPORTS before a body is built.  Because the table and the report regions now
hold hand-written post-cut rows, the default mode would overwrite them: after the cut, run
only --manifest-only, which rebuilds every manifest entry from the tables and writes the
manifest alone.
"""
