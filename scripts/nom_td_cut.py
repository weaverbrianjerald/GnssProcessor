def frozen_lines():
    out = subprocess.run(["git", "-C", str(ROOT), "show", f"{FROZEN_REV}:{FROZEN_PATH}"],
                         capture_output=True, check=True)
    text = out.stdout.decode("utf-8")
    return [""] + text.replace("\r\n", "\n").split("\n")   # 1-based


def blank_literals(text):
    out = []
    for m in _CPP.finditer(text):
        s = m.group()
        if m.lastgroup in ("str", "chr", "raw"):
            out.append("".join(c if c == "\n" else " " for c in s))
        else:
            out.append(s)
    return "".join(out)


class Frozen:
    def __init__(self):
        self.raw = frozen_lines()
        body = "\n".join(self.raw[1:])
        self.code = [""] + strip_comments(body).split("\n")
        self.blank = [""] + blank_literals(strip_comments(body)).split("\n")


SIMPLE = re.compile(r"^!?[A-Za-z_]\w*(?:(?:\.|->)[A-Za-z_]\w*(?:\(\))?)*(?:\(\))?$")


def negate(cond):
    """The guard's condition: `!X` for a plain operand, `!(X)` otherwise."""
    c = cond.strip()
    if SIMPLE.match(c) and not c.startswith("!"):
        return "!" + c
    return "!(" + c + ")"


def statement_heads(F, a, b):
    """Top-level statement heads in [a, b]: list of (first_line, last_line, kind, cond)."""
    out, depth, start = [], 0, None
    for i in range(a, b + 1):
        line = F.blank[i]
        if not line.strip():
            continue
        if start is None and depth == 0:
            start = i
        for ch in line:
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
        if depth == 0 and (line.rstrip().endswith(";") or line.rstrip().endswith("}")):
            out.append((start, i))
            start = None
    heads = []
    for s, e in out:
        first = F.code[s].strip()
        if first.startswith("if"):
            # the condition: from `if (` to its matching `)`, possibly over several lines
            txt, depth, j, done = "", 0, s, False
            while j <= e and not done:
                seg = F.code[j].strip()
                k = 0
                if j == s:
                    k = seg.index("(")
                for ch in seg[k:]:
                    if ch == "(":
                        depth += 1
                        if depth == 1:
                            continue
                    elif ch == ")":
                        depth -= 1
                        if depth == 0:
                            done = True
                            break
                    txt += ch
                txt += " "
                j += 1
            heads.append((s, e, "if", re.sub(r"\s+", " ", txt).strip()))
        elif first.startswith("{"):
            heads.append((s, e, "block", None))
        else:
            heads.append((s, e, "stmt", None))
    return heads


def single_shape(F, a, b):
    """('guard', if_line, close_line, cond) / ('unwrap', open, close) / None."""
    code = [i for i in range(a, b + 1) if F.blank[i].strip()]
    if not code:
        return None
    first, last = code[0], code[-1]
    # the range must be exactly one statement whose braces close on its last line
    depth, closed_at = 0, None
    for i in code:
        for ch in F.blank[i]:
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0 and closed_at is None:
                    closed_at = i
                    if i != last:
                        return None
    if closed_at != last or F.blank[last].strip() != "}":
        return None
    m = re.match(r"^\s*if \((.*)\) \{\s*$", F.code[first])
    if m:
        return ("guard", first, last, m.group(1))
    if F.blank[first].strip() == "{":
        return ("unwrap", first, last)
    return None


# ---------------------------------------------------------------------------------------
# The canonical report table.
#
# R(func, label, home, pieces, what, **opts)
#   home    path under src/core without .cpp
#   pieces  list of (a, b) or (a, b, shift) frozen ranges, or ("new", text[, indent]) lines
#   what    the Doxygen body: what the report prints
#   opts:
#     subs       [(line, from, to)]: a declared edit of one frozen line (plain replace)
#     drops      [line]: frozen code lines inside the pieces that are not carried
#     aliases    extra alias names to declare (beyond those detected)
#     no_alias   alias names not to declare
#     tail       the closing statement ("return 0;" by default; None for none)
#     returns    the @return text
#     adapter    the existing function this row calls (its body lives above, unchanged)
#     header     the declaring header when it is not the home's own
#     shape      "auto" (guard or unwrap when the shape allows), or "verbatim"
# ---------------------------------------------------------------------------------------
def R(func, label, home, pieces, what, **opts):
    d = dict(func=func, label=label, home=home, pieces=pieces, what=what)
    d.update(opts)
    return d


