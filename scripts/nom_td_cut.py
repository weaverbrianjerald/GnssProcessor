IDENT = re.compile(r"(?<![\w.>:])([A-Za-z_]\w*)")


def used_names(F, ranges):
    names = set()
    for a, b, _ in ranges:
        for i in range(a, b + 1):
            names.update(IDENT.findall(F.blank[i]))
    return names


def shifted(line, k, what):
    """Remove k leading spaces from a frozen line (a comment line may hold fewer)."""
    if not line.strip():
        return ""
    lead = len(line) - len(line.lstrip(" "))
    if lead < k:
        if line.lstrip().startswith("//"):
            return line.lstrip()
        raise SystemExit(f"{what}: line {line!r} has {lead} leading spaces, cannot shift {k}")
    return line[k:]


def build_function(F, spec, base_indent=0):
    """Return (definition lines, manifest entry, aliases, frozen ranges, shape)."""
    func = spec["func"]
    ranges = [(p[0], p[1], p[2] if len(p) > 2 else 0) for p in spec["pieces"] if p[0] != "new"]
    subs = {}
    for line, frm, to in spec.get("subs", []):
        subs.setdefault(line, []).append((frm, to))
    drops = set(spec.get("drops", []))
    inserts = {}                                  # frozen line -> lines inserted after it
    for line, ins in spec.get("inserts", []):
        inserts.setdefault(line, []).append(ins)

    # The aliases this body reads (and any declared extras), in ALIAS order.  `C` is never
    # detected (several sections declare their own); a report that needs it says so.
    names = used_names(F, ranges)
    for line, lst in subs.items():                # names the declared edits introduce
        text = F.code[line]
        for frm, to in lst:
            text = text.replace(frm, to)
        names.update(IDENT.findall(blank_literals(text)))
    for p in spec["pieces"]:
        if p[0] == "new":
            names.update(IDENT.findall(blank_literals(p[1])))
    for lst in inserts.values():
        for ins in lst:
            names.update(IDENT.findall(blank_literals(ins)))
    names.discard("C")
    want = (names & set(ALIAS_NAMES)) | set(spec.get("aliases", []))
    want -= set(spec.get("no_alias", []))
    aliases = [n for n in ALIAS_NAMES if n in want]

    # The shape: one guarded if, one bare block, or verbatim.
    shape = None
    if spec.get("shape", "auto") == "auto" and len(spec["pieces"]) == 1 and spec["pieces"][0][0] != "new":
        a, b, k = ranges[0]
        shape = single_shape(F, a, b)

    body, pieces = [], []

    def emit_frozen(i, k):
        raw = F.raw[i]
        if i not in drops:
            for frm, to in subs.get(i, []):
                if frm not in raw:
                    raise SystemExit(f"{func}: substitution {frm!r} not found on frozen line {i}")
                raw = raw.replace(frm, to)
            body.append(shifted(raw, k, f"{func}:{i}"))
        body.extend(inserts.get(i, []))           # declared new lines, at their own indent

    for n in aliases:
        decl = ALIAS[ALIAS_NAMES.index(n)][1]
        for j, part in enumerate(decl.split("\n")):
            body.append(("    " + part) if j == 0 else part)
        pieces.append({"new": decl})
    if aliases:
        body.append("")

    if shape and shape[0] == "guard":
        _, s, e, cond = shape
        a, b, k = ranges[0]
        for i in range(a, s):
            emit_frozen(i, k)
        trail = F.raw[s].rstrip()[len(F.code[s].rstrip()):]
        body.append(f"    if ({negate(cond)}) return 0;" + trail)
        for i in range(s + 1, e):
            emit_frozen(i, k + 4)
        pieces.append({"guard": [a, b], "if_line": s, "close_line": e, "shift": k,
                       "cond": cond, "line": f"if ({negate(cond)}) return 0;"})
    elif shape and shape[0] == "unwrap":
        _, s, e = shape
        a, b, k = ranges[0]
        for i in range(a, s):
            emit_frozen(i, k)
        trail = F.raw[s].rstrip()[len(F.code[s].rstrip()):].strip()
        if trail.startswith("//"):
            body.append("    " + trail)
        for i in range(s + 1, e):
            emit_frozen(i, k + 4)
        pieces.append({"unwrap": [a, b], "open_line": s, "close_line": e, "shift": k})
    else:
        for p in spec["pieces"]:
            if p[0] == "new":
                body.append(" " * (p[2] if len(p) > 2 else 4) + p[1])
                pieces.append({"new": p[1]})
                continue
            a, b, k = p[0], p[1], (p[2] if len(p) > 2 else 0)
            for i in range(a, b + 1):
                emit_frozen(i, k)
            pieces.append({"frozen": [a, b], "shift": k})

    tail = spec.get("tail", "return 0;")
    # one blank line at most between blocks, none at the end
    body = [l for j, l in enumerate(body) if l.strip() or (j > 0 and body[j - 1].strip())]
    while body and not body[-1].strip():
        body.pop()
    if tail:
        body.append("    " + tail)
        pieces.append({"new": tail})

    ind = " " * base_indent
    lines = [f"int {func}(const NetworkRunEndView& v) {{"] + body + ["}"]
    lines = [(ind + l) if l.strip() else "" for l in lines]
    entry = {"func": func, "file": f"src/core/{spec['home']}.cpp", "indent": base_indent,
             "pieces": pieces,
             "subs": [{"line": l, "from": f, "to": t} for l, lst in sorted(subs.items()) for f, t in lst],
             "drops": sorted(drops),
             "inserts": [{"after": l, "text": t} for l, lst in sorted(inserts.items()) for t in lst]}
    return lines, entry, aliases, ranges, shape


def gate_text(F, spec, shape):
    if shape and shape[0] == "guard":
        return f"returns 0 at once unless `{shape[3]}`"
    parts = []
    for p in spec["pieces"]:
        if p[0] == "new":
            continue
        for s, e, kind, cond in statement_heads(F, p[0], p[1]):
            prints = any(re.search(r"\blog->|RunEnd\(|Teardown\(|Report\(|traces\.", F.code[i])
                         for i in range(s, e + 1))
            if not prints:
                continue                      # a declaration or a computation: no gate to state
            if kind == "if":
                parts.append(f"`{cond}`")
            elif kind == "block":
                parts.append("always (a block)")
            else:
                parts.append("always")
    seen, out = set(), []
    for x in parts:
        if x not in seen:
            seen.add(x)
            out.append(x)
    if spec.get("adapter") and out == ["always"]:
        return ("none of its own: the row calls the report above on every run, as the teardown "
                "did, and that report applies its own")
    if len(out) == 1:
        return ("prints under " + out[0]) if out[0].startswith("`") else ("prints " + out[0])
    return "each section under its own condition, as in the teardown: " + "; ".join(out)


def includes_for(F, spec, aliases, ranges):
    text = "\n".join(F.code[i] for a, b, _ in ranges for i in range(a, b + 1))
    inc = list(BASE_INCLUDES)
    for n in aliases:
        decl = ALIAS[ALIAS_NAMES.index(n)][1]
        for part, hdr in (("v.run.", "filter/NetworkRunGroups.hpp"),
                          ("v.setup.", "app/NetworkSetupResult.hpp"),
                          ("v.traces.", "logging/NetworkRunTraces.hpp")):
            if part in decl and hdr not in inc:
                inc.append(hdr)
        if n in ALIAS_INCLUDE and ALIAS_INCLUDE[n] not in inc:
            inc.append(ALIAS_INCLUDE[n])
    for pat, hdr in SYMBOL_INCLUDE:
        if re.search(pat, text) and hdr not in inc:
            inc.append(hdr)
    for hdr in spec.get("includes", []):
        if hdr not in inc:
            inc.append(hdr)
    return inc


def wrap(text, width):
    words, out, cur = text.split(), [], ""
    for w in words:
        if cur and len(cur) + 1 + len(w) > width:
            out.append(cur)
            cur = w
        else:
            cur = (cur + " " + w) if cur else w
    if cur:
        out.append(cur)
    return out


def doc_block(spec, gate, indent=""):
    ret = spec.get("returns", RET0)
    lines = ["/**", f" * @brief Run-end report: {spec['label']}.", " *"]
    lines += [" * " + l for l in wrap(spec["what"], 86)]
    lines += [" *"]
    lines += [" * " + l for l in wrap("Gate: " + gate + ".", 86)]
    lines += [" *", " * @param v The run at its end (filter/NetworkRunEnd.hpp)."]
    lines += [" * " + l for l in wrap("@return " + ret, 86)] + [" */"]
    return [(indent + l) if l else l for l in lines]


