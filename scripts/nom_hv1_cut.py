#!/usr/bin/env python3
"""Generator of card NOM3 step HV1a: the local-carry harvest cut by carried kind.

    python scripts/nom_hv1_cut.py [--survey] [--check]

Reads networkHarvestLocalCarries at rows_hv1.BASE (git show) and the canonical table
(scripts/nom_hv1/rows_hv1.py), and writes into the working tree, every edit starting from the
base text of the file it edits (a second run is a no-op; --check reports a file whose bytes
differ from what the generator would write):

  - include/app/NetworkLocalCarryHarvest.hpp (new): HarvestBorder, BlockSegment, BlockSpan,
    StationHarvestBlock, harvestBlockSpans and the spine's declarations;
  - src/core/app/NetworkLocalCarryHarvest.cpp: the orchestrator networkHarvestLocalCarries(run,
    ep), the border begin and end, networkHarvestColumn (the former lambda), the station
    layout, harvestBlockSpans;
  - each kind's harvest in its owner file (the harvest half of the six family files of step
    PB1b, and generated regions in filter/NetworkAmbStateTrace, filter/NetworkChainDatum and
    app/NetworkWarmResume), with its declaration and Doxygen in the owner's header (the two
    run-only resume functions in app/NetworkRunContext.hpp, replacing the old declaration);
  - networkLeveling's call (filter/NetworkLeveling.cpp) and the declared comment edits;
  - step HV1b's field move: the four rx-CB run fields (rows_hv1.FIELD_MOVE) declared in
    NetworkServiceCounters and spelled ctx.counters at their writers and run-end reader.

Each function opens with generated bindings: the frozen parameters it reads (bound as
networkLeveling's EP1 preamble bound them), the frozen alias lines it reads (verbatim, with
the comment block above each), the border members and the station layout it reads.  Below
`// ---- End of the bindings ----` is the frozen text, shifted, under the table's declared
transforms.  --survey prints each row's resolved range at the base and the coverage counts.
scripts/nom_hv1_verify.py checks the result.
"""
import argparse
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import nom_cpp as nc  # noqa: E402
from nom_hv1 import frozen_hv1 as fh  # noqa: E402
from nom_hv1 import rows_hv1 as rows  # noqa: E402
from nom_hv1.texts_hv1 import (DOC, PARAM_DOC, SPINE_HEADER, SPINE_FILE_HEAD,  # noqa: E402
                               SPANS_DEF, EPILOGUE, CENSUS_DECLS, COMMENT_EDITS,
                               LEVELING_PREAMBLE_OLD, LEVELING_NEW)

ROOT = HERE.parent
GEN = "scripts/nom_hv1_cut.py"
BIND_HEAD = ["    // ---- From the run, the epoch and the harvest (card NOM3 step HV1; generated by",
             "    //      scripts/nom_hv1_cut.py, each line checked by scripts/nom_hv1_verify.py). ----"]
BIND_END = "    // ---- End of the bindings ----"
REGION_OPEN = f"// ---- Harvest half (card NOM3 step HV1; generated by {GEN}) ----"
REGION_CLOSE = "// ---- End of the harvest half ----"
HREGION_OPEN = f"// ---- Harvest half, declarations (card NOM3 step HV1; generated by {GEN}) ----"
HREGION_CLOSE = "// ---- End of the harvest half, declarations ----"
PB1B_MARK = ["// ---- Harvest half (card NOM3 step HV1 fills this section; empty after step PB1b) ----",
             "// ---- End of the harvest half ----"]
NS_CLOSE = re.compile(r"^\}\s*//\s*namespace GnssProcessor\s*$")


def fail(msg):
    raise fh.Fail("nom_hv1_cut: " + msg)


def indent_of(l):
    return len(l) - len(l.lstrip(" "))


def unshift(l, s):
    if not l.strip():
        return ""
    if indent_of(l) < s:
        fail(f"cannot shift {s}: {l!r}")
    return l[s:].rstrip()


def negate(cond):
    c = cond.strip()
    if re.fullmatch(r"[A-Za-z_][\w.]*", c):
        return "!" + c
    return "!(" + c + ")"


def code_part(l):
    q = False
    for k in range(len(l) - 1):
        if l[k] == '"' and (k == 0 or l[k - 1] != "\\"):
            q = not q
        if not q and l[k:k + 2] == "//":
            return l[:k].rstrip()
    return l.rstrip()


