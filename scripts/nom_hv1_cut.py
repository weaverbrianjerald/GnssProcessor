def read_base(rel):
    try:
        return fh.git_show(rows.BASE, rel)
    except Exception:
        return None


def ns_close_index(lines, rel):
    k = max((j for j, l in enumerate(lines) if NS_CLOSE.match(l)), default=None)
    if k is None:
        fail(f"{rel}: no namespace close")
    return k


def add_includes(lines, incs, rel):
    have = {l.strip() for l in lines if l.startswith("#include")}
    last = max(j for j, l in enumerate(lines) if l.startswith("#include"))
    new = [i for i in incs if i.split("//")[0].strip() not in {h.split("//")[0].strip() for h in have}]
    return lines[:last + 1] + new + lines[last + 1:]


FROZEN_INCLUDES = None


def owner_source(rel, funcs, fz):
    text = read_base(rel)
    lines = text.split("\n")
    region = [REGION_OPEN, ""]
    for row in funcs:
        region += function_text(fz, row) + [""]
    region.append(REGION_CLOSE)
    if PB1B_MARK[0] in lines:
        k = lines.index(PB1B_MARK[0])
        if lines[k + 1] != PB1B_MARK[1]:
            fail(f"{rel}: the PB1b harvest section is not empty")
        lines = lines[:k] + region + lines[k + 2:]
    else:
        k = ns_close_index(lines, rel)
        lines = lines[:k] + region + [""] + lines[k:]
    incs = ['#include "app/NetworkLocalCarryHarvest.hpp"   // HarvestBorder, StationHarvestBlock (card NOM3 step HV1)',
            '#include "app/NetworkRun.hpp"',
            '#include "app/NetworkEpoch.hpp"'] + FROZEN_INCLUDES
    return "\n".join(add_includes(lines, incs, rel))


def owner_header(rel, funcs):
    text = read_base(rel)
    lines = text.split("\n")
    region = [HREGION_OPEN, "",
              "struct NetworkRun;                          // app/NetworkRun.hpp",
              "struct NetworkEpoch;                        // app/NetworkEpoch.hpp",
              "struct HarvestBorder;                       // app/NetworkLocalCarryHarvest.hpp",
              "struct StationHarvestBlock;                 // app/NetworkLocalCarryHarvest.hpp", ""]
    if any(r[0] == "networkAmbiguityMonitorFeeds" for r in funcs):
        region.insert(-1, "struct PlAmb;                               // filter/NetworkRunTypes.hpp")
    for row in funcs:
        region += declaration(row[0], row) + [""]
    region.append(HREGION_CLOSE)
    k = ns_close_index(lines, rel)
    lines = lines[:k] + region + [""] + lines[k:]
    return "\n".join(add_includes(lines, ["#include <cstddef>", "#include <vector>"], rel))


def spine_source(fz, funcs):
    out = SPINE_FILE_HEAD.split("\n")
    for row in funcs:
        out += function_text(fz, row) + [""]
    out += SPANS_DEF.split("\n")
    out += ["", "} // namespace GnssProcessor", ""]
    return "\n".join(out)


def context_header():
    rel = "include/app/NetworkRunContext.hpp"
    text = read_base(rel)
    lines = text.split("\n")
    k = lines.index("    /// @brief Harvest, stash and prune the station-local carries from this epoch's solve.")
    e = next(j for j in range(k, len(lines)) if lines[j].rstrip().endswith(");"))
    lines = lines[:k] + CENSUS_DECLS.split("\n") + lines[e + 1:]
    return field_move_decls("\n".join(lines))


FM_OPEN = "        // rx-CB carry run counters (armed-only run-end line)."
FM_LAST = "        std::map<std::string, std::pair<long long, long long>> rx_cb_sta_tally;"
FM_AFTER = "        long long n_rxcb_blk_no_block = 0;"


def field_move_decls(text):
    """HV1b: the four rx-CB run fields' declarations, Doxygen and initializers unchanged, from
    NetworkCarryState to NetworkServiceCounters (after the n_rxcb_blk_* counters)."""
    L = text.split("\n")
    a = L.index(FM_OPEN)
    b = L.index(FM_LAST)
    block = L[a:b + 1]
    L = L[:a] + L[b + 1:]
    k = next(j for j, l in enumerate(L) if l.startswith(FM_AFTER))
    return "\n".join(L[:k + 1] + block + L[k + 1:])


def field_move_uses(rel):
    """HV1b: the run-end reader spells the moved fields ctx.counters."""
    text = read_base(rel)
    for f in rows.FIELD_MOVE:
        text = re.sub(r"\bctx\.carry\." + f + r"\b", "ctx.counters." + f, text)
    return text


def leveling_source():
    rel = "src/core/filter/NetworkLeveling.cpp"
    text = read_base(rel)
    if LEVELING_PREAMBLE_OLD not in text:
        fail("NetworkLeveling.cpp: the EP1 preamble and the call are not at the base text")
    text = text.replace(LEVELING_PREAMBLE_OLD, LEVELING_NEW)
    return text.replace('#include "app/NetworkRun.hpp"     // NetworkRun (card NOM3 step EP1)\n',
                        '#include "app/NetworkRun.hpp"     // NetworkRun (card NOM3 step EP1)\n'
                        '#include "app/NetworkLocalCarryHarvest.hpp"   // networkHarvestLocalCarries (card NOM3 step HV1)\n')


def comment_edited(rel, text):
    for r, old, new in COMMENT_EDITS:
        if r == rel:
            if text.count(old) != 1:
                fail(f"{rel}: comment edit anchor occurs {text.count(old)} times: {old[:60]!r}")
            text = text.replace(old, new)
    return text


def outputs(fz):
    global FROZEN_INCLUDES
    FROZEN_INCLUDES = [l for l in fz.L[:fz.sig_line] if l.startswith("#include")
                       and "NetworkRunContext.hpp" not in l]
    by_home = {}
    for row in fz.table:
        if row[1]:
            by_home.setdefault(row[1], []).append(row)
    out = {}
    out["include/app/NetworkLocalCarryHarvest.hpp"] = SPINE_HEADER
    spine = by_home.pop(rows.SPINE)
    out["src/core/app/NetworkLocalCarryHarvest.cpp"] = spine_source(fz, spine)
    for home, funcs in by_home.items():
        d, base = home.split("/")
        out[f"src/core/{d}/{base}.cpp"] = owner_source(f"src/core/{d}/{base}.cpp", funcs, fz)
        if home != "app/NetworkWarmResume":
            out[f"include/{d}/{base}.hpp"] = owner_header(f"include/{d}/{base}.hpp", funcs)
    out["include/app/NetworkRunContext.hpp"] = context_header()
    out["src/core/filter/NetworkLeveling.cpp"] = leveling_source()
    rel = "src/core/filter/NetworkRxCodeBiasCarryRunEnd.cpp"
    out[rel] = field_move_uses(rel)
    for rel in sorted({r for r, _, _ in COMMENT_EDITS}):
        out[rel] = comment_edited(rel, out.get(rel) or read_base(rel))
    return out


def write(rel, text, check):
    p = ROOT / rel
    data = text.replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8")
    old = p.read_bytes() if p.exists() else None
    if check:
        return old == data
    if old != data:
        p.write_bytes(data)
    return True


def survey(fz):
    total, counts, fails = fz.coverage()
    print(f"base {fz.rev}: function {fz.func}, code lines {total}, offsets {sorted(set(fz.offsets.values()))}")
    print("dropped or replaced:", dict(sorted(counts.items())))
    for f, home, shape, pieces, ex in fz.table:
        print(f"  {f:34s} {shape:12s} {pieces}")
    for who, msg in fails:
        print(f"FAIL {who}: {msg}")
    return 1 if fails else 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--survey", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    fz = fh.load()
    rc = survey(fz) if args.survey else (1 if fz.coverage()[2] else 0)
    if rc:
        fail("the table does not resolve on the base (see --survey)")
    if args.survey:
        return 0
    bad = [rel for rel, text in outputs(fz).items() if not write(rel, text, args.check)]
    for rel in bad:
        print(f"differs: {rel}")
    if not args.check:
        print(f"nom_hv1_cut: wrote {len(outputs(fz))} files")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
