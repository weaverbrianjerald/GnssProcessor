def piece_lines(fz, row):
    """The row's frozen lines, drops removed, extracts replaced by their call, subs applied,
    shifted.  Returns [(text, origin)] where origin is a frozen line number, ('call', fn) or
    None."""
    f, home, shape, pieces, ex = row
    L = fz.L
    drops = {n for (a, b) in ex.get("drops", {}) for n in range(a, b + 1)}
    extracts = {a: (b, fn, call) for a, b, fn, call in ex.get("extract", [])}
    subs = ex.get("subs", {})
    out = []
    for a, b, s in pieces:
        n, pending = a, 0
        while n <= b:
            if n in drops:
                n += 1
                continue
            if n in extracts:
                b2, fn, call = extracts[n]
                out.append((" " * (indent_of(L[n - 1]) - s) + call, ("call", fn)))
                n = b2 + 1
                continue
            line = L[n - 1]
            if n in subs:
                old, new = subs[n]
                if line.count(old) != 1:
                    fail(f"{f}: substitution {old!r} occurs {line.count(old)} times at {n}")
                line = line.replace(old, new)
                # DIRECT_CALL: the call's continuation lines are re-aligned to its paren
                if (old, new) == rows.CALL_COL and not code_part(line).endswith(";"):
                    pending = len(new) - len(old)
            elif pending:
                line = " " * pending + line
                if code_part(line).endswith(";"):
                    pending = 0
            out.append((unshift(line, s), n))
            n += 1
    return out


def shape_body(fz, row):
    """The function body (list of text lines, at function indentation) and the leading
    comment lines (lambda only)."""
    f, home, shape, pieces, ex = row
    lines = piece_lines(fz, row)
    lead = []
    if shape == "guard":
        k = next(j for j, (t, o) in enumerate(lines) if fh.is_code(t))
        t = lines[k][0]
        m = re.fullmatch(r"(\s*)if \((.*)\) \{", t)
        if not m:
            fail(f"{f}: the guard line is not `if (C) {{`: {t!r}")
        lines[k] = (f"{m.group(1)}if ({negate(m.group(2))}) return;", lines[k][1])
        if lines[-1][0].strip() != "}":
            fail(f"{f}: the guard does not close with `}}`")
        lines.pop()
    elif shape == "unwrap":
        k = next(j for j, (t, o) in enumerate(lines) if fh.is_code(t))
        if lines[k][0].strip() != "{" or lines[-1][0].strip() != "}":
            fail(f"{f}: not a bare block")
        lines.pop(k)
        lines.pop()
    elif shape == "lambda":
        a0, b0, _ = pieces[0]
        lead = [t for t, o in lines if isinstance(o, int) and a0 <= o <= b0]
        lines = [(t, o) for t, o in lines if not (isinstance(o, int) and a0 <= o <= b0)]
    body = [t for t, o in lines]
    if f == "networkHarvestBorderBegin":
        body = ["    HarvestBorder border;"] + body + ["    return border;"]
    if f == "networkHarvestStationBlock":
        body = ["    StationHarvestBlock sb;"] + body + EPILOGUE
    return body, lead


def orchestrator_body(fz, row):
    f, home, shape, pieces, ex = row
    L = fz.L
    seg = {}
    for a, b, s in pieces:
        seg[a] = [unshift(L[n - 1], s) for n in range(a, b + 1)]
    p = [a for a, b, s in pieces]
    body = ["    networkHarvestHandoverLedger(run, ep);", ""]
    body += seg[p[0]]
    body += ["        HarvestBorder border = networkHarvestBorderBegin(run, ep);",
             "        std::vector<StationHarvestBlock> blocks(stations.size());"]
    body += seg[p[1]]
    body += ["            blocks[i] = networkHarvestStationBlock(run, ep, border, i);",
             "            if (!blocks[i].ok) continue;",
             "            networkHarvestAmbiguityStation(run, ep, border, blocks[i], i);",
             "            networkAmbIfTraceStation(run, ep, blocks[i], i);",
             "            networkHarvestPhaseColourStation(run, ep, border, blocks[i], i);"]
    body += seg[p[2]]
    body += ["        networkPrunePhaseColour(run, ep);",
             "        networkPruneAmbiguities(run, ep);",
             "        networkHarvestSlantIonoBlock(run, ep, border, blocks);",
             "        networkHarvestRxClock(run, ep, border, blocks);",
             "        networkHarvestRxCbBlock(run, ep, border, blocks);",
             "        networkHarvestZwd(run, ep, border, blocks);",
             "        networkHarvestBorderEnd(run, ep, border);",
             "        networkHarvestRxPhaseBias(run, ep);"]
    body += seg[p[3]]
    body += ["    networkRxCbDatumGaugeCensus(run, ep);",
             "    networkHarvestRxCbCarry(run, ep);",
             "    networkResumeFirstEpochRetire(run);"]
    if seg[p[4]] != ["}"]:
        fail("orchestrator: the function close is not `}`")
    return body


