def names_read(lines):
    """Identifiers of a text, members (after `.`, `->`, `::`) excluded."""
    T = nc.Tokens("\n".join(lines))
    out = set()
    for i in range(T.n):
        if T.k(i) == "id" and not (i > 0 and T.t(i - 1) in (".", "->", "::")):
            out.add(T.t(i))
    return out


def alias_statements(fz):
    """The alias block's statements: [(name, [lines with the comment block above])]."""
    (a, b), = [k for k, v in fz.replaced.items() if v == "alias"]
    L = fz.L
    out, pend, cur, skip = [], [], None, False
    for n in range(a, b + 1):
        t = L[n - 1].rstrip()
        if cur is None:
            if not t.strip():
                pend = []
                continue
            if t.strip().startswith("//"):
                # Two comment paragraphs bind no statement: the block's own header and the
                # note on the absent zwd_q alias.  Each is skipped through its first line
                # that ends a sentence.
                if "Alias block (INC-4)" in t or t.strip().startswith("// There is no"):
                    skip = True
                if skip:
                    skip = not t.endswith(".")
                    continue
                pend.append(t)
                continue
            m = re.match(r"\s*(?:const\s+)?(?:auto&|bool|double|long long|int)\s+(\w+)\s*=", t)
            if not m:
                fail(f"alias block: unparsed line {n}: {t!r}")
            cur = (m.group(1), pend + [t])
            pend = []
        else:
            cur[1].append(t)
        if cur is not None and code_part(t).endswith(";"):
            depth = sum(code_part(x).count("{") - code_part(x).count("}") for x in cur[1]
                        if not x.strip().startswith("//"))
            if depth == 0:
                out.append(cur)
                cur = None
    return out


def preamble(fz, row, body):
    f, home, shape, pieces, ex = row
    kept = ex.get("kept", ())
    kept_names = {re.split(r"[\s*&]+", k.strip())[-1] for k in kept}
    run_only = ex.get("run_only", False)
    aliases = alias_statements(fz)
    alias_by = {n: t for n, t in aliases}
    use = names_read(body) - kept_names
    border = "border" in kept_names and f != "networkHarvestBorderBegin"
    sb = "sb" in kept_names
    while True:
        extra = set()
        for n in use:
            if n in alias_by:
                extra |= names_read([x for x in alias_by[n] if not x.strip().startswith("//")])
            if sb and n in rows.LAYOUT_BIND:
                extra |= names_read([rows.LAYOUT_BIND[n]]) - {"sb", "i"}
        extra -= kept_names
        if extra <= use:
            break
        use |= extra
    lines = list(BIND_HEAD)
    for name, decl, rhs in rows.PARAMS:
        if name in use:
            if run_only and rhs.startswith("ep."):
                fail(f"{f}: run-only function reads {name}")
            lines.append(f"    {decl} = {rhs};")
    for name, text in aliases:
        if name in use:
            lines += text
    if border:
        for n, t in rows.BORDER_BIND.items():
            if n in use:
                lines.append("    " + t)
    if sb:
        for n, t in rows.LAYOUT_BIND.items():
            if n in use:
                lines.append("    " + t)
    lines.append(BIND_END)
    return lines


def signature(f, row):
    ex = row[4]
    ret = ex.get("ret", "void")
    params = ["NetworkRun& run"] + ([] if ex.get("run_only") else ["const NetworkEpoch& ep"])
    params += list(ex.get("kept", ()))
    head = f"{ret} {f}("
    one = head + ", ".join(params) + ") {"
    if len(one) <= 100:
        return [one]
    out, cur = [], head
    if len(head) > 56:
        out, cur, head = [head], "    ", "    "
    for k, p in enumerate(params):
        piece = p + (", " if k < len(params) - 1 else ") {")
        if len(cur) + len(piece.rstrip()) > 100 and cur.strip() != head.strip():
            out.append(cur.rstrip())
            cur = " " * len(head) + piece
        else:
            cur += piece
    out.append(cur.rstrip())
    return out


def function_text(fz, row):
    f = row[0]
    if row[2] == "orchestrator":
        body = orchestrator_body(fz, row)
        lead = []
    else:
        body, lead = shape_body(fz, row)
    pre = preamble(fz, row, body)
    return lead + signature(f, row) + pre + body + ["}"]


def declaration(f, row, indent=""):
    ex = row[4]
    ret = ex.get("ret", "void")
    params = ["NetworkRun& run"] + ([] if ex.get("run_only") else ["const NetworkEpoch& ep"])
    params += [re.sub(r"^const (std::size_t|double) ", r"\1 ", k) for k in ex.get("kept", ())]
    brief = DOC[f]
    doc = [indent + "/**"]
    first = True
    for para in brief.split("\n\n"):
        words = para.split()
        cur = indent + (" * @brief " if first else " * ")
        lead = indent + (" *        " if first else " * ")
        for w in words:
            if len(cur) + 1 + len(w) > 100 and cur.strip() not in ("* @brief", "*"):
                doc.append(cur.rstrip())
                cur = lead + w
            else:
                cur = cur + ("" if cur.endswith(" ") else " ") + w
        doc.append(cur.rstrip())
        first = False
        doc.append(indent + " *")
    for p in params:
        name = re.split(r"[\s*&]+", p.strip())[-1]
        text = PARAM_DOC[(f, name)] if (f, name) in PARAM_DOC else PARAM_DOC[name]
        cur = indent + f" * @param {name} "
        lead = indent + " *" + " " * (len(f" @param {name} "))
        for w in text.split():
            if len(cur) + 1 + len(w) > 100 and not cur.endswith(f"@param {name} "):
                doc.append(cur.rstrip())
                cur = lead + w
            else:
                cur = cur + ("" if cur.endswith(" ") else " ") + w
        doc.append(cur.rstrip())
    if ret != "void":
        doc.append(indent + f" * @return {DOC[(f, 'return')]}")
    doc.append(indent + " */")
    sig = [indent + l for l in signature(f, row)]
    sig = [re.sub(r"^const (std::size_t|double) ", r"\1 ", s) for s in sig]
    # declarations drop top-level const of by-value parameters
    sig = [s.replace("const std::size_t i", "std::size_t i").replace("const double ", "double ")
           for s in sig]
    sig[-1] = sig[-1][:-2] + ";"
    return doc + sig


