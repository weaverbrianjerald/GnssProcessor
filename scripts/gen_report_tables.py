#!/usr/bin/env python3
"""Generate LaTeX reference tables for docs/report from authoritative source.

This is the "Tier 3" half of the GnssProcessor documentation tooling: small,
deterministic generators that read a *single source of truth* in the C++ tree
and emit ``.tex`` table fragments under ``docs/report/generated/``.  The point
is that these tables **cannot drift** from the code -- they are regenerated
from the same headers the build compiles, so a renamed flag, a new cycle-slip
detector, or a changed state-key delimiter shows up in the report on the next
run instead of rotting silently.

Generators
----------
1. ``slip_detectors.tex``  -- the cycle-slip detector registry (active vs.
   staged), parsed from ``SlipDetectorRegistry.cpp`` + ``ISlipDetector.hpp`` +
   the ``CycleSlipConfig`` struct.
2. ``config_toggles.tex``  -- boolean feature flags (the ``jval<bool>`` calls in
   ``GnssConfigLoad.cpp``) plus the ``ModelCorrections`` and ``LoggingConfig``
   on/off switches.
3. ``state_keys.tex``      -- every dynamic state-vector key format, reconstructed
   from the ``make*Key`` bodies in ``StateKeySchema.hpp`` by substituting the
   real delimiter / infix / prefix / suffix constants.
4. ``processing_modes.tex`` -- the ``ProcessingMode`` / ``AppMode`` /
   ``DataSource`` / ``DifferencingMode`` enums and the verbatim
   ``differencingModeFor()`` factory that maps config to differencing regime.

Usage
-----
    python scripts/gen_report_tables.py            # regenerate all fragments
    python scripts/gen_report_tables.py --check    # fail if anything changed
                                                   # (CI guard against drift)

The emitted files are consumed by ``docs/report/generated_tables.tex`` via
``\\input{generated/<name>}`` and built with the rest of the report by latexmk.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# --------------------------------------------------------------------------- #
#  Paths
# --------------------------------------------------------------------------- #
REPO = Path(__file__).resolve().parent.parent
OUT_DIR = REPO / "docs" / "report" / "generated"

SRC = {
    "slip_registry": REPO / "src" / "core" / "slip" / "SlipDetectorRegistry.cpp",
    "islip": REPO / "include" / "slip" / "ISlipDetector.hpp",
    "config_types": REPO / "include" / "config" / "GnssConfigTypes.hpp",
    "config_load": REPO / "src" / "core" / "config" / "GnssConfigLoad.cpp",
    "state_keys": REPO / "include" / "filter" / "StateKeySchema.hpp",
    "bssd_transform": REPO / "include" / "measurement" / "BssdTransform.hpp",
    "meas_builder": REPO / "src" / "core" / "measurement" / "MeasurementBuilder.cpp",
}

BANNER = (
    "% =========================================================================\n"
    "%  AUTO-GENERATED by scripts/gen_report_tables.py -- DO NOT EDIT BY HAND.\n"
    "%  Source of truth: {source}\n"
    "%  Re-run `python scripts/gen_report_tables.py` after changing that file.\n"
    "% =========================================================================\n"
)


# --------------------------------------------------------------------------- #
#  Small helpers
# --------------------------------------------------------------------------- #
def read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def clean_doc(s: str) -> str:
    """Strip Doxygen inline commands from a doc comment (e.g. '@c x' -> 'x')."""
    s = re.sub(r"@(?:c|p|a|e|b|ref)\s+", "", s)
    return s.strip()


def ascii_only(s: str) -> str:
    """Reduce a string to ASCII for verbatim contexts (code listings)."""
    m = {"—": "--", "–": "-", "−": "-", "·": "*", "×": "x",
         "≤": "<=", "≥": ">=", "≠": "!=", "→": "->"}
    return "".join(m.get(ch, ch) for ch in s if ch in m or ord(ch) < 128)


# Unicode -> LaTeX.  C++ comments freely use Greek, sub/superscripts, and math
# operators; pdflatex (no fontenc/Greek text font) cannot typeset those raw, so
# we map the ones we know and DROP anything else (incl. the U+FFFD that a
# non-UTF-8 source byte decodes to).  A generated table must never break the
# build, so unknown non-ASCII is silently discarded rather than passed through.
_GREEK = {
    "alpha": "α", "beta": "β", "gamma": "γ", "delta": "δ", "epsilon": "ε",
    "zeta": "ζ", "eta": "η", "theta": "θ", "iota": "ι", "kappa": "κ",
    "lambda": "λ", "mu": "μ", "nu": "ν", "xi": "ξ", "pi": "π", "rho": "ρ",
    "sigma": "σ", "tau": "τ", "phi": "φ", "chi": "χ", "psi": "ψ", "omega": "ω",
    "Gamma": "Γ", "Delta": "Δ", "Theta": "Θ", "Lambda": "Λ", "Xi": "Ξ",
    "Pi": "Π", "Sigma": "Σ", "Phi": "Φ", "Psi": "Ψ", "Omega": "Ω",
}
UNICODE_MAP = {ch: f"$\\{name}$" for name, ch in _GREEK.items()}
UNICODE_MAP.update({
    "—": "---", "–": "--", "−": "$-$",
    "·": r"$\cdot$", "×": r"$\times$", "÷": r"$\div$",
    "≤": r"$\leq$", "≥": r"$\geq$", "≠": r"$\neq$", "≈": r"$\approx$",
    "→": r"$\to$", "←": r"$\leftarrow$", "↔": r"$\leftrightarrow$",
    "∇": r"$\nabla$", "∂": r"$\partial$", "∞": r"$\infty$", "±": r"$\pm$",
    "°": r"$^\circ$", "√": r"$\surd$",
    "ü": r"\"u", "ö": r"\"o", "ä": r"\"a", "ß": r"\ss{}",
    "é": r"\'e", "è": r"\`e", "ñ": r"\~n",
})
# Super/subscript digits -> math.
for _d, _c in enumerate("⁰¹²³⁴⁵⁶⁷⁸⁹"):
    UNICODE_MAP[_c] = f"$^{_d}$"
for _d, _c in enumerate("₀₁₂₃₄₅₆₇₈₉"):
    UNICODE_MAP[_c] = f"$_{_d}$"

_TEX_SPECIALS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def tex_escape(s: str) -> str:
    """Escape a plain-text string for LaTeX, normalising/dropping non-ASCII."""
    out = []
    for ch in s:
        if ch in _TEX_SPECIALS:
            out.append(_TEX_SPECIALS[ch])
        elif ch in UNICODE_MAP:
            out.append(UNICODE_MAP[ch])
        elif ord(ch) < 128:
            out.append(ch)
        # else: unknown non-ASCII -> drop (keeps the build robust).
    return "".join(out)


def tt(s: str) -> str:
    r"""Render a code-ish token in \texttt, escaping LaTeX specials."""
    return r"\texttt{" + tex_escape(s) + "}"


def tt_break(s: str) -> str:
    r"""Like tt() but permits line breaks after '.' and '_' so long dotted
    config keys wrap inside a fixed-width paragraph column instead of
    overflowing the margin."""
    esc = tex_escape(s)
    esc = esc.replace(".", r".\allowbreak{}").replace(r"\_", r"\_\allowbreak{}")
    return r"\texttt{" + esc + "}"


def matched_block(text: str, open_pos: int) -> str:
    """Return the substring from the brace at/after open_pos to its match."""
    start = text.index("{", open_pos)
    depth = 0
    for i in range(start, len(text)):
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[start : i + 1]
    raise ValueError("unbalanced braces")


def enum_members(text: str, enum_name: str):
    """Parse `enum class <enum_name> { A, ///< doc ... };` into [(name, doc)]."""
    m = re.search(r"enum\s+class\s+" + re.escape(enum_name) + r"\b", text)
    if not m:
        return []
    body = matched_block(text, m.end())[1:-1]  # strip outer braces
    members = []
    for raw in body.splitlines():
        line = raw.strip()
        if not line:
            continue
        # Pure continuation comment line -> append to previous member's doc.
        if line.startswith("///<") or line.startswith("///"):
            if members:
                cont = line.lstrip("/<").strip()
                members[-1] = (members[-1][0], (members[-1][1] + " " + cont).strip())
            continue
        # Member line: identifier optionally followed by ',' and a ///< comment.
        mm = re.match(r"([A-Za-z_]\w*)\s*,?\s*(?:///<?\s*(.*))?$", line)
        if mm:
            name = mm.group(1)
            doc = (mm.group(2) or "").strip()
            members.append((name, doc))
    return [(n, clean_doc(d)) for (n, d) in members]


def longtable(colspec: str, headers, rows, caption: str, label: str) -> str:
    """Build a booktabs longtable. `headers`/row cells are pre-formatted TeX."""
    head_row = " & ".join(headers) + r" \\"
    lines = [
        r"\begin{longtable}{" + colspec + "}",
        r"\caption{" + caption + r"}\label{" + label + r"}\\",
        r"\toprule",
        head_row,
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        head_row,
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endfoot",
    ]
    for r in rows:
        lines.append(" & ".join(r) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{longtable}")
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
#  1. Cycle-slip detector registry
# --------------------------------------------------------------------------- #
# enum-name -> CycleSlipConfig bool field + kσ multiplier field (stable mapping;
# the enum names themselves are parsed from source, only this correspondence is
# hand-held because it is not expressed mechanically in one place).
SLIP_FIELD = {
    "MelbourneWubbena": ("mw", "mw_sigma_multiplier"),
    "Graphic": ("graphic", "graphic_sigma_multiplier"),
    "ExtraWideLane": ("ewl", "ewl_sigma_multiplier"),
    "GeometryFree": ("gf", None),
    "IonoFreePhase": ("ifp", None),
}


def gen_slip_detectors() -> tuple[str, int]:
    reg = read(SRC["slip_registry"])
    islip = read(SRC["islip"])
    types = read(SRC["config_types"])

    kinds = enum_members(islip, "SlipDetectorKind")

    # Which kinds have a creator registered? -> the creators() table body.
    m = re.search(r"creators\(\)\s*\{", reg) or re.search(r"creators\(\)", reg)
    registered = set()
    if m:
        body = matched_block(reg, m.end() - 1 if reg[m.end() - 1] == "{" else m.end())
        registered = set(re.findall(r"SlipDetectorKind::(\w+)", body))

    # CycleSlipConfig defaults: `bool mw = true;` and `double X = 8.0;`.
    cyc = matched_block(types, types.index("struct CycleSlipConfig"))
    bool_def = dict(re.findall(r"bool\s+(\w+)\s*=\s*(true|false)\s*;", cyc))
    dbl_def = dict(re.findall(r"double\s+(\w+)\s*=\s*([0-9.]+)\s*;", cyc))

    rows = []
    for name, doc in kinds:
        field, sigma_field = SLIP_FIELD.get(name, (None, None))
        flag = (
            r"\texttt{estimation.cycle\_slip." + tex_escape(field) + "}"
            if field
            else "--"
        )
        default = bool_def.get(field, "?") if field else "?"
        default = {"true": "on", "false": "off", "?": "--"}.get(default, default)
        sigma = dbl_def.get(sigma_field, "--") if sigma_field else "--"
        status = (
            r"\textbf{active}" if name in registered else r"\emph{staged}"
        )
        rows.append(
            [
                tt(name),
                flag,
                default,
                sigma,
                status,
                tex_escape(clean_doc(doc)),
            ]
        )

    table = longtable(
        r"@{}>{\raggedright\arraybackslash}p{2.8cm} "
        r">{\raggedright\arraybackslash}p{3.2cm} c c l "
        r">{\raggedright\arraybackslash}p{3.6cm}@{}",
        [
            r"\textbf{Detector}",
            r"\textbf{Config flag}",
            r"\textbf{Default}",
            r"\textbf{$k\sigma$}",
            r"\textbf{Status}",
            r"\textbf{Combination}",
        ],
        rows,
        caption=(
            "Cycle-slip detectors known to "
            r"\texttt{SlipDetectorRegistry}. \emph{Active} detectors have a "
            r"creator in the factory table and run when their flag is set; "
            r"\emph{staged} detectors are declared in the "
            r"\texttt{SlipDetectorKind} enum but excluded from the build "
            r"(the registry warns and skips them if requested). The $k\sigma$ "
            r"column is the MAD gate multiplier from \texttt{CycleSlipConfig}."
        ),
        label="tab:gen-slip-detectors",
    )
    content = (
        BANNER.format(source="src/core/slip/SlipDetectorRegistry.cpp, "
                      "include/slip/ISlipDetector.hpp, CycleSlipConfig")
        + "\n" + table + "\n"
    )
    (OUT_DIR / "slip_detectors.tex").write_text(content, encoding="utf-8")
    return "slip_detectors.tex", len(rows)


# --------------------------------------------------------------------------- #
#  2. Config feature toggles
# --------------------------------------------------------------------------- #
def _struct_bool_fields(struct_text: str):
    """Yield (field, default, doc) for `bool x{true}; ///< doc` style members."""
    out = []
    pat = re.compile(
        r"bool\s+(\w+)\s*(?:\{\s*(true|false)\s*\}|=\s*(true|false))\s*;"
        r"\s*(?://+<?\s*(.*))?"
    )
    for m in pat.finditer(struct_text):
        field = m.group(1)
        default = m.group(2) or m.group(3)
        doc = clean_doc(m.group(4) or "")
        out.append((field, default, doc))
    return out


def gen_config_toggles() -> tuple[str, dict]:
    load = read(SRC["config_load"])
    types = read(SRC["config_types"])

    # (a) jval<bool> feature flags (the canonical processing/estimation toggles).
    #     Form: member_ = jval<bool>(json, "dotted.path", "legacy", default);
    flag_pat = re.compile(
        r"(\w+)\s*=\s*jval<bool>\s*\(\s*json\s*,\s*"
        r'"([^"]+)"\s*,\s*"([^"]*)"\s*,\s*(true|false)\s*\)',
        re.DOTALL,
    )
    flags = []
    seen = set()
    for m in flag_pat.finditer(load):
        member, path, legacy, default = m.groups()
        if member in seen:
            continue
        seen.add(member)
        flags.append((member, path, legacy, default))
    flags.sort(key=lambda x: x[1])  # by JSON path

    flag_rows = [
        [
            tt_break(path),
            {"true": "on", "false": "off"}[default],
            tt_break(legacy) if legacy else "--",
        ]
        for (_member, path, legacy, default) in flags
    ]
    flag_table = longtable(
        r"@{}>{\raggedright\arraybackslash}p{7.2cm} c "
        r">{\raggedright\arraybackslash}p{5.2cm}@{}",
        [r"\textbf{JSON path}", r"\textbf{Default}", r"\textbf{Legacy alias}"],
        flag_rows,
        caption=(
            r"Top-level boolean feature toggles, parsed from the "
            r"\texttt{jval<bool>} calls in \texttt{GnssConfigLoad.cpp}. The "
            r"legacy alias is the pre-refactor flat key still accepted as a "
            r"fallback."
        ),
        label="tab:gen-feature-flags",
    )

    # (b) ModelCorrections + (c) LoggingConfig struct switches.
    mc = matched_block(types, types.index("struct ModelCorrections"))
    lc = matched_block(types, types.index("struct LoggingConfig"))
    mc_fields = _struct_bool_fields(mc)
    lc_fields = _struct_bool_fields(lc)

    def struct_rows(fields):
        return [
            [tt(f), {"true": "on", "false": "off"}[d], tex_escape(doc)]
            for (f, d, doc) in fields
        ]

    mc_table = longtable(
        r"@{}>{\raggedright\arraybackslash}p{4.5cm} c "
        r">{\raggedright\arraybackslash}p{9.2cm}@{}",
        [r"\textbf{Field}", r"\textbf{Default}", r"\textbf{Effect}"],
        struct_rows(mc_fields),
        caption=(
            r"Physical model on/off switches (\texttt{ModelCorrections}). These "
            r"gate the correction terms applied to the undifferenced "
            r"observation model."
        ),
        label="tab:gen-model-corrections",
    )
    lc_table = longtable(
        r"@{}>{\raggedright\arraybackslash}p{4.5cm} c "
        r">{\raggedright\arraybackslash}p{9.2cm}@{}",
        [r"\textbf{Field}", r"\textbf{Default}", r"\textbf{Channel}"],
        struct_rows(lc_fields),
        caption=(
            r"Logging and CSV-trace channels (\texttt{LoggingConfig}). Each "
            r"toggles one spdlog file logger or one per-epoch CSV trace."
        ),
        label="tab:gen-logging",
    )

    content = (
        BANNER.format(source="src/core/config/GnssConfigLoad.cpp (jval<bool>), "
                      "GnssConfigTypes.hpp (ModelCorrections, LoggingConfig)")
        + "\n\\subsection{Feature toggles}\n"
        + "These are the loop- and state-vector-level switches.\n\n"
        + flag_table
        + "\n\n\\subsection{Model-correction switches}\n\n"
        + mc_table
        + "\n\n\\subsection{Logging and trace channels}\n\n"
        + lc_table
        + "\n"
    )
    (OUT_DIR / "config_toggles.tex").write_text(content, encoding="utf-8")
    return "config_toggles.tex", {
        "feature_flags": len(flag_rows),
        "model_corrections": len(mc_fields),
        "logging": len(lc_fields),
    }


# --------------------------------------------------------------------------- #
#  3. State-key schema (reconstruct each format from the make*Key body)
# --------------------------------------------------------------------------- #
def _parse_key_constants(text: str) -> dict:
    consts = {}
    # char constants: inline constexpr char kX = '_';
    for m in re.finditer(
        r"constexpr\s+char\s+(k\w+)\s*=\s*'(\\?.)'\s*;", text
    ):
        name, lit = m.group(1), m.group(2)
        consts[name] = lit.replace("\\", "")  # '\|' -> '|'
    # string_view constants: inline constexpr std::string_view kX = "DD";
    for m in re.finditer(
        r'constexpr\s+std::string_view\s+(k\w+)\s*=\s*"([^"]*)"\s*;', text
    ):
        consts[m.group(1)] = m.group(2)
    return consts


def _humanize_key(fn: str) -> str:
    name = fn[len("make"):]
    if name.endswith("Key"):
        name = name[: -len("Key")]
    # Insert spaces at camelCase boundaries and fix a few acronyms.
    spaced = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", name)
    fixes = {
        "Nl": "NL", "Wl": "WL", "Dd": "DD", "Ifb": "IFB", "Dcb": "DCB",
        "Sat": "Satellite", "Bssd": "BSSD",
    }
    return " ".join(fixes.get(w, w) for w in spaced.split())


def gen_state_keys() -> tuple[str, int]:
    text = read(SRC["state_keys"])
    consts = _parse_key_constants(text)

    token = re.compile(
        r"out\.append\((\w+)\)"
        r"|out\.push_back\((\w+)\)"
        r"|return\s+std::string\((\w+)\)"
    )

    rows = []
    for m in re.finditer(r"std::string\s+(make\w+Key)\s*\(", text):
        fn = m.group(1)
        # Signature: from '(' after fn to matching ')'.
        paren = text.index("(", m.end() - 1)
        depth = 0
        for i in range(paren, len(text)):
            if text[i] == "(":
                depth += 1
            elif text[i] == ")":
                depth -= 1
                if depth == 0:
                    sig = text[paren + 1 : i]
                    body_start = i
                    break
        params = []
        for p in sig.split(","):
            p = p.strip()
            if p:
                params.append(re.split(r"[\s&*]+", p)[-1])
        body = matched_block(text, body_start)

        fmt_parts = []
        for tm in token.finditer(body):
            ident = tm.group(1) or tm.group(2) or tm.group(3)
            if ident in consts:
                fmt_parts.append(consts[ident])
            elif ident in params:
                fmt_parts.append("<" + ident + ">")
            else:
                fmt_parts.append("<?" + ident + ">")
        fmt = "".join(fmt_parts)
        if not fmt:
            continue
        rows.append(
            [
                tex_escape(_humanize_key(fn)),
                tt(fmt),
                tt(fn),
            ]
        )

    table = longtable(
        r"@{}>{\raggedright\arraybackslash}p{4.6cm} "
        r">{\raggedright\arraybackslash}p{6.3cm} "
        r">{\raggedright\arraybackslash}p{4.3cm}@{}",
        [r"\textbf{State}", r"\textbf{Key format}", r"\textbf{Builder}"],
        rows,
        caption=(
            r"Dynamic state-vector key formats, reconstructed from the "
            r"\texttt{make*Key} bodies in \texttt{StateKeySchema.hpp}. "
            r"Angle-bracketed fields are runtime values; literal characters "
            r"are the delimiter / infix / prefix / suffix constants."
        ),
        label="tab:gen-state-keys",
    )
    content = (
        BANNER.format(source="include/filter/StateKeySchema.hpp")
        + "\n" + table + "\n"
    )
    (OUT_DIR / "state_keys.tex").write_text(content, encoding="utf-8")
    return "state_keys.tex", len(rows)


# --------------------------------------------------------------------------- #
#  4. Processing modes + differencing factory
# --------------------------------------------------------------------------- #
def gen_processing_modes() -> tuple[str, int]:
    types = read(SRC["config_types"])
    bssd = read(SRC["bssd_transform"])
    builder = read(SRC["meas_builder"])

    def enum_table(text, name, caption, label):
        members = enum_members(text, name)
        rows = [[tt(n), tex_escape(d)] for (n, d) in members]
        return (
            longtable(
                r"@{}>{\raggedright\arraybackslash}p{3.6cm} "
                r">{\raggedright\arraybackslash}p{11cm}@{}",
                [r"\textbf{Value}", r"\textbf{Meaning}"],
                rows,
                caption=caption,
                label=label,
            ),
            len(rows),
        )

    pm_t, n_pm = enum_table(
        types, "ProcessingMode",
        r"\texttt{ProcessingMode} -- the estimation algorithm selector.",
        "tab:gen-processing-mode",
    )
    am_t, _ = enum_table(
        types, "AppMode",
        r"\texttt{AppMode} -- top-level post-processing vs.\ real-time dispatch.",
        "tab:gen-app-mode",
    )
    ds_t, _ = enum_table(
        types, "DataSource",
        r"\texttt{DataSource} -- bundled fixtures vs.\ auto-download.",
        "tab:gen-data-source",
    )
    dm_t, _ = enum_table(
        bssd, "DifferencingMode",
        r"\texttt{DifferencingMode} -- the measurement differencing regime.",
        "tab:gen-diff-mode",
    )

    # differencingModeFor() verbatim -- the authoritative config->regime map.
    m = re.search(r"DifferencingMode\s+differencingModeFor\s*\(", builder)
    factory = ""
    if m:
        # back up to start of the return type on that line
        line_start = builder.rfind("\n", 0, m.start()) + 1
        body = matched_block(builder, m.end())
        factory = builder[line_start : builder.index(body) + len(body)]
        factory = ascii_only(factory.rstrip())

    content = (
        BANNER.format(source="GnssConfigTypes.hpp enums, BssdTransform.hpp, "
                      "MeasurementBuilder.cpp::differencingModeFor")
        + "\n\\subsection{Processing modes}\n\n" + pm_t
        + "\n\n\\subsection{Execution mode and data source}\n\n" + am_t
        + "\n\n" + ds_t
        + "\n\n\\subsection{Differencing regime}\n\n" + dm_t
        + "\n\n\\subsection{Config-to-differencing mapping}\n\n"
        + "The differencing regime is resolved once per run by the factory "
        + "below (verbatim from \\texttt{MeasurementBuilder.cpp}):\n\n"
        + "{\\footnotesize\n\\begin{verbatim}\n" + factory
        + "\n\\end{verbatim}}\n"
    )
    (OUT_DIR / "processing_modes.tex").write_text(content, encoding="utf-8")
    return "processing_modes.tex", n_pm


# --------------------------------------------------------------------------- #
#  Driver
# --------------------------------------------------------------------------- #
def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if any generated file would change (CI drift guard).",
    )
    args = ap.parse_args()

    # Snapshot existing content for --check.
    before = {}
    if args.check:
        for p in OUT_DIR.glob("*.tex"):
            before[p.name] = p.read_text(encoding="utf-8")

    OUT_DIR.mkdir(parents=True, exist_ok=True)

    print(f"GnssProcessor report-table generator")
    print(f"  repo : {REPO}")
    print(f"  out  : {OUT_DIR}")
    for label, path in SRC.items():
        if not path.exists():
            print(f"  ERROR: source not found: {path}", file=sys.stderr)
            return 2

    f1, n1 = gen_slip_detectors()
    print(f"  [{f1}] {n1} detectors")
    f2, n2 = gen_config_toggles()
    print(f"  [{f2}] {n2['feature_flags']} feature flags, "
          f"{n2['model_corrections']} model switches, {n2['logging']} log channels")
    f3, n3 = gen_state_keys()
    print(f"  [{f3}] {n3} state-key formats")
    f4, n4 = gen_processing_modes()
    print(f"  [{f4}] {n4} processing modes")

    if args.check:
        changed = []
        for p in sorted(OUT_DIR.glob("*.tex")):
            if before.get(p.name) != p.read_text(encoding="utf-8"):
                changed.append(p.name)
        if changed:
            print("\nDRIFT: generated tables are stale; re-run the generator:",
                  file=sys.stderr)
            for c in changed:
                print(f"  - {c}", file=sys.stderr)
            return 1
        print("\nOK: generated tables are up to date.")
    else:
        print("\nDone.")
    return 0


