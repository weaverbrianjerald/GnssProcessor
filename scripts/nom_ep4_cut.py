def git_show(base, path):
    return subprocess.run(["git", "-C", ROOT, "show", f"{base}:{path}"], capture_output=True,
                          check=True).stdout.decode("utf-8").replace("\r\n", "\n")


def read(path):
    p = os.path.join(ROOT, path)
    if not os.path.exists(p):
        return None
    with open(p, "rb") as f:
        return f.read().decode("utf-8").replace("\r\n", "\n")


def write(path, text):
    with open(os.path.join(ROOT, path), "wb") as f:
        f.write(text.replace("\n", "\r\n").encode("utf-8"))


def body_ids(lines):
    T = ncpp.Tokens("\n".join(lines), "body")
    out = set()
    for i, t in enumerate(T.toks):
        if T.k(i) == "id" and T.t(i - 1) not in (".", "->", "::"):
            out.add(t.text)
    return out


def own_decls(lines):
    """Names declared at the top level of the moved text (they need no binding)."""
    T = ncpp.Tokens("\n".join(lines), "own")
    out = set()
    for s, e in ncpp.statements(T, 0, len(T.toks)):
        try:
            for d in ncpp.parse_declaration(T, s, e) or []:
                out.add(d.name)
        except Exception:
            pass
    return out


def sig(b):
    ps = ([] if b["n"] == "networkMarkerArpCensusCopy" else ["NetworkRun& run"]) + [p for p, _ in b["params"]]
    return f"void {b['n']}({', '.join(ps)})"


