def decl(b):
    out = ["/**", f" * @brief {b['brief']}", " *"]
    words, line = (b["detail"] + "  Setup builder (card NOM3 step EP4): called once from "
                   "Application::runNetwork, in the order scripts/nom3_designs/EP4_design.md section 2 "
                   "states.").split(" "), " *"
    for w in words:
        if len(line) + 1 + len(w) > 96:
            out.append(line.rstrip())
            line = " *"
        line += " " + w if w else " "
    out.append(line.rstrip())
    out.append(" *")
    if b["n"] != "networkMarkerArpCensusCopy":
        out.append(f" * @param run The network run; fills {b['fills']}.")
    for p, doc in b["params"]:
        out.append(f" * @param {p.split()[-1]} {doc}")
    out += [" */", sig(b) + ";"]
    return out


def builder(b, F):
    a, z = b["r"]
    lines = [F[l - 1] for l in range(a, z + 1) if l not in BIND_LINES]
    if "unwrap" in b:
        u0, u1 = b["unwrap"]
        keep = []
        for l in range(a, z + 1):
            if l in BIND_LINES or l in (u0, u1):
                continue
            s = F[l - 1]
            keep.append(s[4:] if a <= l and u0 < l < u1 and s.startswith("        ") else s)
        lines = keep
    ids = body_ids(lines) - own_decls(lines)
    need = {n for n, _ in BIND if n in ids}
    for n in list(need):
        r = ROOT_OF.get(n)
        while r:
            need.add(r)
            r = ROOT_OF.get(r)
    out = [f"// Setup builder (card NOM3 step EP4); documented at its declaration in {b['hpp'][len('include/'):]}.",
           sig(b) + " {"]
    if b["n"] != "networkMarkerArpCensusCopy":
        out += OPEN_MARK
        for n, text in BIND:
            if n not in need:
                continue
            if n in BIND_COMMENTS:
                c0, c1 = BIND_COMMENTS[n]
                out += F[c0 - 1:c1]
            if n == "slip_qc" and b.get("const_slip"):
                text = CONST_SLIP
            out.append("    " + text)
    out.append(END_MARK)
    out += lines
    out.append("}")
    return out


def add_includes(text, incs):
    L = text.split("\n")
    last = max(i for i, l in enumerate(L) if l.startswith("#include"))
    have = set(L)
    new = [f'#include {i if i.startswith("<") else chr(34) + i + chr(34)}' for i in incs]
    new = [x for x in new if x not in have]
    return "\n".join(L[:last + 1] + new + L[last + 1:])


def insert_before_ns_end(text, block):
    L = text.split("\n")
    k = max(i for i, l in enumerate(L) if re.match(r"^\}\s*// *namespace GnssProcessor", l))
    return "\n".join(L[:k] + block + [""] + L[k:])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="8f4f1db")
    a = ap.parse_args()
    F = git_show(a.base, DRIVER).split("\n")
    files = {}

    def get(p):
        if p not in files:
            files[p] = read(p)
        return files[p]

    for b in B:
        body = builder(b, F)
        cpp, hpp = b["cpp"], b["hpp"]
        stem = os.path.basename(hpp)
        if b.get("new"):
            files[hpp] = "\n".join([
                "#pragma once", "/**", f" * @file {stem}", f" * @brief {b['file_brief']}", " *",
                " * The builder is called once from Application::runNetwork (src/core/app/ApplicationNetwork.cpp).",
                " */", "", "namespace GnssProcessor {", ""] + b["fwd"] + [""] + decl(b) +
                ["", "} // namespace GnssProcessor", ""])
        else:
            get(hpp)
            files[hpp] = insert_before_ns_end(files[hpp], b["fwd"] + [""] + decl(b))
        if b.get("new") or b.get("new_cpp"):
            files[cpp] = "\n".join([
                "/**", f" * @file {os.path.basename(cpp)}", f" * @brief {b['file_brief']}", " */",
                f'#include "{hpp[len("include/"):]}"', "", "namespace GnssProcessor {", "", "} // namespace GnssProcessor", ""])
        else:
            get(cpp)
        files[cpp] = add_includes(files[cpp], COMMON_INC + b.get("includes", []) + EXTRA_INC.get(cpp, []))
        files[cpp] = insert_before_ns_end(files[cpp], body)

    starts = {b["r"][0]: b for b in B}
    skip_to = 0
    out = []
    for ln in range(1, len(F) + 1):
        if ln <= skip_to:
            continue
        if ln in starts:
            b = starts[ln]
            out += ["    " + c for c in b.get("pre", [])]
            out.append("    " + b["call"])
            skip_to = b["r"][1]
            continue
        if ln in DROP:
            continue
        out.append(F[ln - 1])
    text = "\n".join(out)
    for o, n in DRIVER_TEXT:
        assert o in text, o
        text = text.replace(o, n, 1)
    files[DRIVER] = add_includes(text, ["filter/NetworkCongruenceSetup.hpp", "filter/NetworkOraclePinSetup.hpp"])
    for p, t in files.items():
        write(p, t)
        print("wrote", p)


if __name__ == "__main__":
    main()
