#!/usr/bin/env python3
"""Render docs/CONFIG_promotion_ledger.md from docs/CONFIG_promotion_ledger.json.

The JSON is the ledger: one row per config key the network loader reads (and the few
other-section keys a network posture depends on), each with one verdict.  The .md is its
reading view: a hand-written head (everything above the GENERATED marker) and the tables
below the marker, rendered from the JSON.  A ledger change is an edit to the JSON followed
by this script; ``--check`` exits 1 when the .md is stale, and docs_index_check.py runs it.

Row fields: ``knob``, ``verdict``, ``area`` (the loader helper or config section),
``default``, ``golden`` (only when the goldens pin another value), ``why`` (one sentence),
``card`` (repo-relative path of the evidence), ``parent`` (PARAM rows), and for the two
machine tiers ``regime`` / ``armed_when`` / ``fingerprinted`` / ``posture_why``, which
make_golden_config.py and config_posture_check.py evaluate.

Usage:  python scripts/ledger_render.py [--check]
"""
import io
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JSON_PATH = os.path.join(ROOT, "docs", "CONFIG_promotion_ledger.json")
MD_PATH = os.path.join(ROOT, "docs", "CONFIG_promotion_ledger.md")
MARKER = "<!-- GENERATED by scripts/ledger_render.py from CONFIG_promotion_ledger.json: edit the JSON, not the text below. -->"

#: Verdicts in reading order, with the one-line meaning printed above each table.
TIERS = [
    ("RECOMMEND_ON", "Arm in its regime. Machine-checked: a regime predicate here and a row in the loader's posture table."),
    ("RECOMMEND_SCOPED", "Arm only in the stated regime. Machine-checked like RECOMMEND_ON."),
    ("ARMED", "Pinned in both goldens by the card named; the golden manifest is the authority."),
    ("UNVALIDATED", "Built and plausible, never graded on the current posture."),
    ("KEEP_OFF", "Measured null or harmful, falsified, or superseded; the code stays as a diagnostic or alternative."),
    ("REMOVE", "Delete candidate: parsed but never read, inert as built, or a retired mechanism with no live use."),
]
#: Verdicts rendered as name lists (the reason for each row is in the JSON).
LISTS = [
    ("TRACE", "Observability only (a CSV, log line or record); solve-inert."),
    ("PARAM", "A setting of the parent knob; the default or golden value is the validated value."),
    ("CORE", "A structural input or always-applied setting with no on/off question."),
]


def card_link(path):
    if not path:
        return ""
    rel = path[5:] if path.startswith("docs/") else "../" + path
    stem = os.path.splitext(os.path.basename(path))[0]
    label = stem.split("_")[0] if "/refound/" in path and not stem.startswith("NETWORK") else stem
    return f"[{label}]({rel})"


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def value(v):
    if v is None:
        return ""
    if isinstance(v, (dict, list, bool)):
        return json.dumps(v)
    return str(v)


def render(led):
    rows = led["knobs"]
    by = {}
    for r in rows:
        by.setdefault(r["verdict"], []).append(r)
    known = {t for t, _ in TIERS} | {t for t, _ in LISTS}
    stray = sorted(set(by) - known)
    if stray:
        raise SystemExit(f"unknown verdict(s) in the ledger: {stray}")
    out = [MARKER, "", f"## Counts ({len(rows)} keys)", "", "| verdict | keys |", "| --- | --- |"]
    for t, _ in TIERS + LISTS:
        out.append(f"| {t} | {len(by.get(t, []))} |")
    for t, meaning in TIERS:
        rs = sorted(by.get(t, []), key=lambda r: (r.get("area", ""), r["knob"]))
        out += ["", f"## {t} ({len(rs)})", "", meaning, ""]
        machine = t.startswith("RECOMMEND")
        values = t != "REMOVE"          # a delete candidate's default and golden value are moot
        head = "| key | default | golden | regime | why | evidence |" if machine else \
               "| key | default | golden | why | evidence |" if values else "| key | why | evidence |"
        out += [head, "|" + " --- |" * (head.count("|") - 1)]
        for r in rs:
            cols = [f"`{r['knob']}`"]
            if values:
                cols += [cell(value(r.get("default"))), cell(value(r.get("golden", "")))]
            if machine:
                cols.append(f"`{cell(r.get('regime', ''))}`" if r.get("regime") else "")
            cols += [cell(r.get("why", "")), card_link(r.get("card", ""))]
            out.append("| " + " | ".join(cols) + " |")
    for t, meaning in LISTS:
        rs = by.get(t, [])
        out += ["", f"## {t} ({len(rs)})", "", meaning, ""]
        groups = {}
        for r in rs:
            g = r.get("parent") if t == "PARAM" and r.get("parent") else r.get("area", "")
            groups.setdefault(g, []).append(r["knob"])
        for g in sorted(groups):
            names = ", ".join(f"`{k}`" for k in sorted(groups[g]))
            out.append(f"- **{g or 'other'}**: {names}")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    led = json.load(io.open(JSON_PATH, encoding="utf-8"))
    md = io.open(MD_PATH, encoding="utf-8").read() if os.path.exists(MD_PATH) else ""
    if MARKER not in md:
        raise SystemExit(f"{MD_PATH}: generated marker not found; the hand-written head must end with it")
    head = md.split(MARKER)[0]
    new = head + render(led)
    if check:
        if new != md:
            print("CONFIG_promotion_ledger.md is stale: run python scripts/ledger_render.py")
            return 1
        print("CONFIG_promotion_ledger.md matches the JSON")
        return 0
    io.open(MD_PATH, "w", encoding="utf-8", newline="\n").write(new)
    print(f"wrote {MD_PATH} ({len(new.encode('utf-8'))} bytes, {len(led['knobs'])} keys)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
