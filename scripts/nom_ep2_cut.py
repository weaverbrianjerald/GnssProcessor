def git_show(base, path):
    return subprocess.run(["git", "-C", ROOT, "show", f"{base}:{path}"], capture_output=True,
                          check=True).stdout.decode("utf-8")


def lines_of(text):
    return text.replace("\r\n", "\n").split("\n")


def read(path):
    with open(os.path.join(ROOT, path), "rb") as f:
        return f.read().decode("utf-8")


def write(path, lines):
    data = "\n".join(lines).replace("\r\n", "\n").replace("\n", "\r\n")
    with open(os.path.join(ROOT, path), "wb") as f:
        f.write(data.encode("utf-8"))


def preamble_map(F):
    """Frozen preamble name -> (line number, text)."""
    out = {}
    for n in range(PREAMBLE[0], PREAMBLE[1] + 1):
        s = F[n - 1]
        if "=" not in s or s.strip().startswith("//"):
            continue
        lhs = s.split("=")[0].split()
        out[lhs[-1].lstrip("&*")] = (n, s)
    return out


def function_text(F, pm, c):
    out = [c["sig"] + " {"]
    out.append(MARK_R if c.get("marker") == "run" else MARK_RE)
    for name in sorted(c["run"], key=lambda k: pm[k][0]):
        out.append(pm[name][1])
    for k in c["ep"]:
        line = EB[k]
        if k == "n_present":
            line = F[1055 - 1]
        elif k == "sec_asm":
            line = F[347 - 1]
        out.append(line)
    out.append(MARK_END)
    if c.get("emit"):
        out.append("    // The event-row forwarder the driver held (card NOM3 step EP2): adds the epoch time.")
        out.extend(F[EMIT_EVENT[0] - 1:EMIT_EVENT[1]])
    subs = {ln: (old, new) for ln, old, new in c.get("sub", [])}
    for rng in c["body"]:
        a, b = rng[0], rng[1]
        dd = rng[2] if len(rng) > 2 else 0
        for n in range(a, b + 1):
            s = F[n - 1]
            if n in subs:
                old, new = subs[n]
                assert old in s, (c["id"], n, s)
                s = s.replace(old, new)
            if dd and s.startswith(" " * dd):
                s = s[dd:]
            out.append(s)
    out.extend(c.get("tail", []))
    out.append("}")
    return out


def insert_gate(text_lines, fn, gate_line):
    """Insert @p gate_line right after the bindings of function @p fn."""
    start = next(i for i, l in enumerate(text_lines)
                 if l.startswith("void " + fn + "(NetworkRun&") and l.rstrip().endswith("{"))
    end = next(i for i in range(start, len(text_lines)) if text_lines[i].strip() == MARK_END.strip()
               or text_lines[i].strip() == "// ---- End of the bindings ----")
    text_lines.insert(end + 1, gate_line)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="7141240")
    args = ap.parse_args()
    F = lines_of(git_show(args.base, DRIVER))
    pm = preamble_map(F)

    # Targets must be at base.
    targets = {c["file"] for c in CUT} | {g[1] for g in GATES} | {DRIVER}
    for t in sorted(targets):
        try:
            base_text = git_show(args.base, t)
        except subprocess.CalledProcessError:
            if os.path.exists(os.path.join(ROOT, t)):
                sys.exit(f"{t}: new file already exists")
            continue
        if read(t).replace(chr(13) + chr(10), chr(10)) != base_text.replace(chr(13) + chr(10), chr(10)):
            sys.exit(f"{t}: differs from {args.base}; reset it first")

    # 1. The new functions, grouped by file, in table order.
    funcs = {}
    for c in CUT:
        funcs.setdefault(c["file"], []).append(function_text(F, pm, c))
    with open(os.path.join(ROOT, "scripts", "nom_ep2", "templates.txt"), encoding="utf-8") as f:
        tmpl = f.read()
    blocks = {}
    for chunk in tmpl.split("@@@ ")[1:]:
        head, _, body = chunk.partition("\n")
        blocks[head.strip()] = body.rstrip("\n").split("\n")
    for path, fl in funcs.items():
        joined = []
        for k, fn in enumerate(fl):
            if k:
                joined.append("")
            joined.extend(fn)
        new_file = path + ":new" in blocks
        if new_file:
            out = []
            for l in blocks[path + ":new"]:
                if l == "@FUNCTIONS@":
                    out.extend(joined)
                else:
                    out.append(l)
            write(path, out + [""])
        else:
            L = lines_of(read(path))
            anchor = blocks[path + ":anchor"][0]
            idx = next(i for i, l in enumerate(L) if l == anchor)
            pre = blocks.get(path + ":before", [])
            ins = pre + joined + [""]
            L[idx:idx] = ins
            if path + ":inc_anchor" in blocks:
                ia = blocks[path + ":inc_anchor"][0]
                j = next(i for i, l in enumerate(L) if l == ia)
                L[j + 1:j + 1] = blocks[path + ":inc"]
            write(path, L)

    # 2. Gates into the seams.
    for _, path, fn, gl in GATES:
        L = lines_of(read(path))
        insert_gate(L, fn, gl)
        write(path, L)

    # 3. The driver.
    repl = {}   # frozen line -> replacement lines ([] drops it)
    for c in CUT:
        first = c["body"][0][0]
        covered = [n for r in c["body"] for n in range(r[0], r[1] + 1)]
        if c["id"] == "S1":
            covered += [1094, 1106]
        if c["id"] == "F1":
            covered += [396]
        for n in covered:
            repl[n] = []
        repl[first] = c["lead"] + c["call"]
    for name in DROP_NAMES:
        repl[pm[name][0]] = []
    for n in DROP_LINES:
        repl.setdefault(n, [])
    for gl, _, _, _ in GATES:
        repl[gl] = []
        call = F[gl]   # the call line follows its gate
        if gl == 1299:   # `if (carry_invariant) {` / call / `}`
            repl[gl + 1] = ["    " + F[gl].strip()]
            repl[gl + 2] = []
        elif gl == 1314:
            repl[gl + 1] = ["    " + F[gl].strip()]
        else:
            repl[gl + 1] = ["    " + call.strip()]
    repl[ORACLE_GATE] = []
    repl[ORACLE_GATE + 1] = ["    " + F[ORACLE_GATE].strip()]
    hdr = blocks[DRIVER + ":header"]
    inc = blocks[DRIVER + ":includes"]
    pre_c = blocks[DRIVER + ":preamble_comment"]
    out = []
    for n, s in enumerate(F, start=1):
        if 15 <= n <= 23:
            if n == 15:
                out.extend(hdr)
            continue
        if 156 <= n <= 158:
            if n == 156:
                out.extend(pre_c)
            continue
        if n in repl:
            out.extend(repl[n])
        else:
            out.append(s)
        if n == 28:
            out.extend(inc)
    write(DRIVER, out)
    print("cut written:", len(CUT), "functions,", len(GATES), "gates; driver",
          len(out), "lines (was", len(F), ")")


if __name__ == "__main__":
    main()
