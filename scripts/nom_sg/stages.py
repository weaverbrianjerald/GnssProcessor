# --------------------------------------------------------------------------- rendering
def resolve(fz, piece):
    a = fz.find(piece.first)
    if piece.last is None:
        b = a
    elif isinstance(piece.last, tuple):
        b = fz.find(piece.last)
    else:
        b = fz.find(piece.last, a)
    assert a <= b, f"piece {piece.first!r}: {a} > {b}"
    return a, b


def apply_subs(lines, subs):
    """The frozen lines with each declared substitution applied exactly once."""
    out = list(lines)
    for s in subs:
        k = len(s.old)
        hits = [i for i in range(len(out) - k + 1) if out[i:i + k] == s.old]
        assert len(hits) == 1, f"substitution {s.cls} {s.old[0]!r}: {len(hits)} matches"
        i = hits[0]
        out[i:i + k] = s.new
    return out


def reindent(line, delta):
    if not line.strip():
        return ""
    if delta >= 0:
        return " " * delta + line
    assert line.startswith(" " * -delta), f"cannot dedent {line!r}"
    return line[-delta:]


def render_piece(fz, piece):
    a, b = resolve(fz, piece)
    lines = apply_subs(fz.lines[a - 1:b], piece.subs)
    return [reindent(l, piece.delta) for l in lines]


def render_body(fz, fn):
    """The body below the preamble: pieces and generated lines in order (no tail)."""
    out = []
    for item in fn.body:
        if isinstance(item, P):
            out.extend(render_piece(fz, item))
        else:
            out.extend(item.lines)
    return out
