def canon(fz):
    """The canon statements in frozen order: (name, lines, deps)."""
    out = []
    for a, b in CANON_RANGES:
        lo, hi = fz.span(a, b)
        cur = []
        for n in range(lo, hi + 1):
            raw = fz.line(n)
            if not cur and (not raw.strip() or raw.strip().startswith("//")):
                continue
            cur.append(n)
            code = "".join(fz.code[k - 1] for k in cur)
            depth = code.count("{") - code.count("}") + code.count("(") - code.count(")")
            if code.rstrip().endswith(";") and depth == 0:
                text = [fz.line(k) for k in cur]
                head = code.split("=", 1)[0]
                name = IDENT.findall(head)[-1]
                rhs = code.split("=", 1)[1]
                out.append((name, text, idents_read(rhs)))
                cur = []
        assert not cur, f"unterminated canon statement at {cur}"
    return out


