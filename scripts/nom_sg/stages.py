def git_show(rev, path, root=ROOT):
    return subprocess.run(["git", "-C", str(root), "show", f"{rev}:{path}"], check=True,
                          capture_output=True).stdout.decode("utf-8")


def blank_code(line, state):
    """Comments and literals of one line blanked (state carries an open block comment)."""
    out, i, n = [], 0, len(line)
    in_block = state[0]
    while i < n:
        c = line[i]
        if in_block:
            if line.startswith("*/", i):
                in_block = False
                out.append("  ")
                i += 2
            else:
                out.append(" ")
                i += 1
            continue
        if line.startswith("//", i):
            out.append(" " * (n - i))
            break
        if line.startswith("/*", i):
            in_block = True
            out.append("  ")
            i += 2
            continue
        if c in "\"'":
            j = i + 1
            while j < n and line[j] != c:
                j += 2 if line[j] == "\\" else 1
            out.append(c + " " * (min(j, n) - i - 1) + (c if j < n else ""))
            i = j + 1
            continue
        out.append(c)
        i += 1
    state[0] = in_block
    return "".join(out)


def code_lines(lines):
    """Each line with comments and literals blanked."""
    st = [False]
    return [blank_code(l, st) for l in lines]


IDENT = re.compile(r"[A-Za-z_]\w*")


def idents_read(code):
    """Identifiers in blanked code that are not member names (after `.`, `->` or `::`)."""
    out = set()
    for m in IDENT.finditer(code):
        pre = code[:m.start()].rstrip()
        if pre.endswith(".") or pre.endswith("->") or pre.endswith("::"):
            continue
        out.add(m.group(0))
    return out


class Frozen:
    """The frozen networkSolveGlue at a base: its lines (1-based) and anchor resolution."""

    def __init__(self, text):
        self.text = text
        self.lines = text.split("\n")
        self.code = code_lines(self.lines)
        starts = [i for i, l in enumerate(self.lines) if l.startswith(SOLVE_SIG)]
        assert len(starts) == 1, "networkSolveGlue definition not found exactly once"
        self.first = starts[0] + 1
        self.last = self.close_line(self.first + 2)   # the signature's `{` line
        assert self.lines[self.last - 1] == "}", self.lines[self.last - 1]

    def line(self, n):
        return self.lines[n - 1]

    def close_line(self, n):
        """The line of the brace closing the last `{` of line n (or of the first later line
        that holds one, for a head that spans lines)."""
        code = self.code
        while code[n - 1].rfind("{") < 0:   # a head spanning lines: its brace comes later
            n += 1
            assert n <= self.last, "no opening brace"
        col = code[n - 1].rfind("{")
        depth = 0
        for k in range(n - 1, len(code)):
            s = code[k][col:] if k == n - 1 else code[k]
            for ch in s:
                if ch == "{":
                    depth += 1
                elif ch == "}":
                    depth -= 1
                    if depth == 0:
                        return k + 1
        raise AssertionError("unbalanced")

    def find(self, anchor, start=None):
        """Resolve an anchor: a unique substring, ("close_of", a), ("from", a, text) (the first
        line at or after anchor a holding text) or ("before", a) (the line before a)."""
        if isinstance(anchor, tuple):
            kind = anchor[0]
            if kind == "close_of":
                return self.close_line(self.find(anchor[1]))
            if kind == "from":
                return self.find(anchor[2], self.find(anchor[1]))
            if kind == "before":
                return self.find(anchor[1]) - 1
            raise AssertionError(f"unknown anchor kind {kind!r}")
        if start is None:
            hits = [n for n in range(self.first, self.last + 1) if anchor in self.lines[n - 1]]
            assert len(hits) == 1, f"anchor {anchor!r}: {len(hits)} matches {hits[:5]}"
            return hits[0]
        for n in range(start, self.last + 1):
            if anchor in self.lines[n - 1]:
                return n
        raise AssertionError(f"anchor {anchor!r} not found from {start}")

    def span(self, first, last=None):
        a = self.find(first)
        if last is None:
            return a, a
        if isinstance(last, tuple):
            return a, self.find(last)
        return a, self.find(last, a)


# --------------------------------------------------------------------------- the table types
class P:
    """A frozen piece: lines first..last at an indent delta, with declared substitutions."""

    def __init__(self, first, last=None, delta=4, form="whole", subs=(), row=""):
        self.first, self.last, self.delta, self.form = first, last, delta, form
        self.subs, self.row = list(subs), row


class G:
    """Generated lines (absolute indentation) of one declared class."""

    def __init__(self, cls, *lines):
        self.cls, self.lines = cls, list(lines)


class Sub:
    """A declared substitution inside a piece: exact frozen lines -> new lines (frozen indent)."""

    def __init__(self, cls, old, new):
        self.cls = cls
        self.old = old if isinstance(old, list) else [old]
        self.new = new if isinstance(new, list) else [new]


class D:
    """A frozen range no new body carries (EXIT_TABLE, DROP, ...), or carried by a hand-written
    function (LAMBDA_TO_FN head and tail, DECL_MOVE)."""

    def __init__(self, cls, first, last=None, row=""):
        self.cls, self.first, self.last, self.row = cls, first, last, row


class Fn:
    """A new function: its home, its signature, its parameters, its body and its tail."""

    def __init__(self, name, home, sig, brief, params, body, tail=(), binds=(), kind="fn"):
        self.name, self.home, self.sig, self.brief = name, home, sig, brief
        self.params = params          # name -> declarator text (the S3 category check)
        self.body, self.tail = body, list(tail)
        self.binds = list(binds)      # (name, line, class) the preamble may use, in order
        self.kind = kind              # "fn" or "comment" (a moved comment block)


