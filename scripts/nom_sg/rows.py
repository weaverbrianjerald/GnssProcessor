def fn_by_name(name):
    for f in FUNCTIONS:
        if f.name == name:
            return f
    raise KeyError(name)


def _complete_params():
    """Each row's typed-value parameters (datum, handoff, we, ceiling, f), from its signature,
    checked against the closed list TYPED."""
    for fn in FUNCTIONS:
        text = " ".join(l.strip() for l in fn.sig)
        if "(" not in text:
            continue
        for p in text[text.index("(") + 1:text.rindex(")")].split(","):
            p = " ".join(p.split())
            name = p.split()[-1].lstrip("&*") if p else ""
            if name in TYPED and name not in fn.params:
                assert p in TYPED[name], f"{fn.name}: typed parameter {p!r} not in the closed list"
                fn.params[name] = p


_complete_params()
