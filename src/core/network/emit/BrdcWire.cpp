void networkBrdcWire(NetworkRunContext& ctx,
                     const GnssConfig& config_,
                     const std::shared_ptr<spdlog::logger>& log,
                     NetworkRunTraces& traces,
                     NetworkSetupResult& setup,
                     const SyncedEpoch& se,
                     NetworkSolutionEpoch& sol) {
    net::NetworkEntities& entities = ctx.entities;   // written: sats
    (void)config_;
    (void)log;
    if (!ctx.knobs.nbp_on || !setup.brdc_apriori) return;
    // --- Alias preamble ---
    const BrdcClockApriori& apriori = *setup.brdc_apriori;
    auto& c = ctx.counters;
    auto& trace = traces.brdc_offset_trace;

    std::map<std::string, int> nbp_prev_iode =
        net::satMap(ctx.entities.sats, &net::SatelliteState::nbp_prev_iode);
    const auto rows = apriori.stampWire(sol, se.time, &LiveEphemerisStore::getInstance(),
                                        nbp_prev_iode);
    net::assignSat(entities, &net::SatelliteState::nbp_prev_iode, nbp_prev_iode);
    ++c.nbp_epochs;
    for (const auto& r : rows) {
        if (r.iode < 0) {
            ++c.nbp_unstamped;
        } else {
            const bool first = (c.nbp_stamped == 0);
            ++c.nbp_stamped;
            if (r.held) ++c.nbp_held; else ++c.nbp_not_held;
            if (r.switched) ++c.nbp_switches;
            c.nbp_records.emplace(r.sat, r.iode);
            c.nbp_offset_min_m = first ? r.offset_m : std::min(c.nbp_offset_min_m, r.offset_m);
            c.nbp_offset_max_m = first ? r.offset_m : std::max(c.nbp_offset_max_m, r.offset_m);
        }
        if (trace)
            trace << se.time.week << ',' << fmt::format("{:.3f}", se.time.tow) << ',' << r.sat
                  << ',' << r.iode << ',' << fmt::format("{:.6f}", r.c_est_m) << ','
                  << fmt::format("{:.6f}", r.offset_m) << ','
                  << fmt::format("{:.6f}", r.c_est_m + r.offset_m) << ','
                  << fmt::format("{:.6f}", r.brdc_m) << ',' << (r.held ? 1 : 0) << ','
                  << (r.switched ? 1 : 0) << '\n';
    }
}

// ---- Run-end reports (generated by scripts/nom_td_cut.py) ----

// Run-end report: the native broadcast clock a priori (NBP).
int networkBrdcWireRunEnd(const NetworkRunEndView& v) {
    const NetworkRunContext& ctx = v.ctx;
    const std::shared_ptr<spdlog::logger>& log = v.log;
    const NetworkSetupResult& setup = v.setup;

    if (!ctx.knobs.nbp_on) return 0;
    // The native broadcast clock a priori.  `stamped 0` is inert wiring;
    // `not held > 0` means a consumer pinned to the stamped IODE found no record.
    const auto& c = ctx.counters;
    const std::size_t fed = setup.brdc_apriori ? setup.brdc_apriori->fedCount() : 0;
    const std::size_t table_sw = setup.brdc_apriori ? setup.brdc_apriori->stats().n_switches : 0;
    log->info("Network (native broadcast clock a priori): {} emitted epoch(s) "
              "stamped; {} clock record(s) stamped, {} unstamped (no selectable record); "
              "{} distinct broadcast records selected on the wire; {} stamp switch(es) "
              "between emissions ({} cut-overs in the table); O on the wire [{:.4f}, "
              "{:.4f}] m; stamped IODE held by the store at consume {} / {} ({} not held); "
              "{} record(s) fed to the store by transmission time.",
              c.nbp_epochs, c.nbp_stamped, c.nbp_unstamped, c.nbp_records.size(),
              c.nbp_switches, table_sw, c.nbp_offset_min_m, c.nbp_offset_max_m,
              c.nbp_held, c.nbp_stamped, c.nbp_not_held, fed);
    return 0;
}

