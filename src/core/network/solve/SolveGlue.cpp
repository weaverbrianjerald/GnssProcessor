/// The H line of a withheld epoch: a product-level heartbeat (an H line with no E line), so a
/// live tail can tell "withheld" from "producer died" (RTA-10).  Before the deferred product
/// writer opens (at the first emit) it is buffered in setup.pending_h_pre_open and flushed at
/// the open, so a leg that opens inside a withhold era still records the era; with no product
/// path (or a v1 immediate open) there is nothing to flush into.  withheld="*" means the whole
/// epoch.  One statistic per wire: when the census feed is armed every H site carries it
/// (H-rider); otherwise the caller passes its own (0.0 when unavailable, the H grammar's
/// sentinel).  The two frozen copies (the gate and the sigma0 withholds) made one.
/// @param run    The run: the product writer or setup.pending_h_pre_open is written.
/// @param ep     The epoch, read: se.
/// @param state  The H state token.
/// @param sigma0 The H line's sigma0 field.
static void networkWithheldHeartbeat(NetworkRun& run, const NetworkEpoch& ep,
                                     NetworkProducerStatus::State state, double sigma0) {
    const GnssConfig& config_ = run.config;
    NetworkRunContext& ctx = run.ctx;
    NetworkSetupResult& setup = run.setup;
    const SyncedEpoch& se = ep.se;
    const auto& nc = config_.getNetworkConfig();
    auto& product_writer = setup.product_writer;
    const bool   emit_epoch_status = ctx.knobs.emit_epoch_status;     // per-epoch H heartbeat in the product file, withheld epochs included (RTA-10)
    if (emit_epoch_status) {
        NetworkProducerStatus hst;
        hst.time.week = se.time.week;
        hst.time.tow  = se.time.tow;
        hst.state     = state;
        hst.sigma0    = sigma0;
        hst.withheld  = "*";
        if (product_writer) {
            product_writer->writeEpochStatus(hst);
            if (nc.product_flush_per_epoch) product_writer->flush();
        } else if (setup.contract_pending) {
            setup.pending_h_pre_open.push_back(hst);
        }
    }
}

// The five exits, as frozen (finding 3 of the SG design: DatumFailed, SolveFailed and
// WeRestoreFailed write no H line and no trace row; kept, and pinned by
// tests/network/test_network_solve_skip.cpp until a separate change alters them).
const std::array<SolveSkipRow, 5> kSolveSkips{{
    //  skip                        disposition          site
    //  datum_changed  T2 sigma0  T2 meters  trace flag  H line  H state                                     tail
    {SolveSkip::DatumFailed,     "datum_failed",      "networkClockDatum",
     false, false, false, -1, false, NetworkProducerStatus::State::Unknown,        nullptr},
    {SolveSkip::GateWithheld,    "gate_withheld",     "networkRankGate",
     true,  false, false,  0, true,  NetworkProducerStatus::State::WithheldGate,   nullptr},
    {SolveSkip::SolveFailed,     "solve_failed",      "networkPrimarySolve",
     true,  false, false, -1, false, NetworkProducerStatus::State::Unknown,        nullptr},
    {SolveSkip::WeRestoreFailed, "we_restore_failed", "networkWithinEpochAdapt",
     true,  true,  false, -1, false, NetworkProducerStatus::State::Unknown,        nullptr},
    {SolveSkip::Sigma0Withheld,  "sigma0_withheld",   "networkSigma0Ceiling",
     true,  true,  true,   1, true,  NetworkProducerStatus::State::WithheldSigma0, networkSigma0WithholdTail},
}};

SolveSkipFacts SolveSkipFacts::of(const SolveDatum& d) {
    SolveSkipFacts f;
    f.plan = &d.plan;
    f.datum_changed = d.datum_changed;
    return f;
}

SolveSkipFacts SolveSkipFacts::of(const SolveDatum& d, const WithinEpochOutcome& we,
                                  const std::vector<int>& est_index_of) {
    SolveSkipFacts f = of(d);
    f.sigma0_adapt = we.sigma0_adapt;
    f.n_adapt = we.n_adapt;
    f.est_index_of = &est_index_of;
    return f;
}

NetworkSolveGlueResult networkSolveSkip(NetworkRun& run, const NetworkEpoch& ep, SolveSkip skip,
                                        const SolveSkipFacts& f) {
    const EpochEvents::Solve& solve_ev = ep.events.solve;
    NetworkRunContext& ctx = run.ctx;
    NetworkRunTraces& traces = run.traces;
    const SyncedEpoch& se = ep.se;
    int n_clock = ep.columns.n_clock;
    int n_pb = ep.columns.n_pb;
    int n_present = ep.columns.n_present;
    int total_pins = ep.assembly.total_pins;
    auto& trace                = traces.trace;
    auto& prev_tow = ctx.counters.prev_tow;
    auto& prev_week = ctx.counters.prev_week;
    auto& n_skipped = ctx.counters.n_skipped;
    const SolveSkipRow& row = kSolveSkips[static_cast<std::size_t>(skip)];
    ++n_skipped;
    // The network trace row: withheld flag 0 for the gate, 1 for the sigma0 ceiling.
    if (row.trace_flag >= 0) {
        if (trace) trace << se.time.week << ',' << fmt::format("{:.3f}", se.time.tow)
                         << ',' << n_present << ',' << n_clock << ',' << n_pb
                         << ',' << f.plan->declared_dimension << ',' << row.trace_flag
                         << ",0,0,0," << total_pins << '\n';
    }
    { EpochStatusRow es;
      if (row.col_t2_sigma0) { es.sigma0 = f.sigma0_adapt; es.n_adapt = f.n_adapt; }
      es.n_present = n_present; es.n_clock_sats = n_clock;
      if (row.col_datum_changed) es.datum_changed = f.datum_changed ? 1 : 0;
      // A withheld epoch is where the tier's first-assess sigma0 and the impulse meter matter
      // most, so the T2 rows carry them onto the disposition row (R0).
      if (row.col_t2_sigma0 && solve_ev.ep_sigma0_first >= 0.0) {
          es.sigma0_first = solve_ev.ep_sigma0_first;
          if (row.col_t2_meters) {
              if (solve_ev.ep_we_refloat_sats >= 0)
                  es.n_we_refloat_sats = solve_ev.ep_we_refloat_sats;
              if (solve_ev.ep_we_clk_move_max >= 0.0) {
                  es.we_clk_move_max_m   = solve_ev.ep_we_clk_move_max;
                  es.we_clk_move_max_sat = solve_ev.ep_we_clk_move_sat;
              }
          }
      }
      networkSolveEpochStatusRow(run, ep, row.disposition, es); }
    // The census sigma0 is computed before the solve (stage 1), so it exists on a gate-withheld
    // epoch; f.sigma0_adapt is 0.0 there, the H grammar's "unavailable" (VALUE_EQUAL).
    if (row.h_line)
        networkWithheldHeartbeat(run, ep, row.h_state,
                                 ctx.knobs.h_sigma0_census ? ctx.carry.ep_h_sigma0_census
                                                           : f.sigma0_adapt);
    if (row.tail) row.tail(run, ep, f);
    prev_week = se.time.week; prev_tow = se.time.tow;
    NetworkSolveGlueResult result;
    result.action = EpochAction::SkipEpoch;
    return result;
}

