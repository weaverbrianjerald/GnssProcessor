void networkDdFrac(NetworkRun& run, const NetworkEpoch& ep) {
    // ---- From the run and the epoch (generated by scripts/nom_ep1_cut.py,
    //      each line checked by scripts/nom_ep1_verify.py). Reads bind through `ep`; writes bind
    //      through the output parameters and are marked `// written`. ----
    NetworkRunContext& ctx = run.ctx;
    const GnssConfig& config_ = run.config;
    const std::shared_ptr<spdlog::logger>& log = run.log;
    NetworkRunTraces& traces = run.traces;
    NetworkSetupResult& setup = run.setup;
    const SyncedEpoch& se = ep.se;
    const NetworkEstimator& est = run.engines.est;
    const Eigen::VectorXd& x_s = ep.solve.x_s;
    const NetworkSbasis::Plan& plan = ep.solve.plan;
    const std::vector<StationAssembly>& asm_res = ep.assembly.asm_res;
    const std::vector<int>& est_index_of = ep.assembly.est_index_of;
    // ---- End of the bindings ----
    // --- Alias preamble: mechanically-derived run-TU aliases (+ reconstructions). --
    const auto& nc = config_.getNetworkConfig();
    auto& stations = setup.stations;
    auto& dd_frac_trace        = traces.dd_frac_trace;
    const bool phase_datum_prioritized = ctx.knobs.phase_datum_prioritized;
    auto& n_loop_epochs = ctx.counters.n_loop_epochs;

    // --- S1: the (cons, signal, sat) -> anchor station map -----------------------
    // docs/SPEC_lane_spectrometer.md §3.3 anchor partition.  The map is emitted here
    // because this seam already evaluates the gauge-pin predicate and walks every
    // station's ambiguity key map, so the map is read off the election that ran
    // instead of being re-derived (a second derivation could disagree with the
    // datum).  It sits outside the DD-fractional gate below on purpose: that block is
    // stride-decimated and stream-gated, while the anchor map is small (bounded by the
    // gauge freedoms, satellites x signals, not by station pairs) and the partition
    // needs it on every processed epoch.  The sticky tree re-elects often, and the
    // grader takes the per-arc mode, which needs the full sequence.
    //
    // The two outputs are complementary: the DD-fractional emit skips pinned
    // ambiguities (the networkIsGaugePinned continue below), so no satellite appears
    // both as a graded DD member and as its own anchor on the same signal.  The two
    // files together cover the gauge, each ambiguity in one of them.
    if (traces.phase_anchor_trace.is_open()) {
        for (std::size_t i = 0; i < stations.size(); ++i) {
            if (est_index_of[i] < 0) continue;
            for (const auto& [amb, slot_idx] : stations[i].params.amb) {
                (void)slot_idx;
                const std::string satellite = amb.sat.str();
                const std::string signal = amb.signal.obsCode(ObsType::Phase);
                if (!networkIsGaugePinned(stations, phase_datum_prioritized,
                                          i, satellite, signal))
                    continue;
                const std::string cst = constellationKey(amb.sat.sys);
                traces.phase_anchor_trace
                    << se.time.week << ',' << fmt::format("{:.3f}", se.time.tow) << ','
                    << cst << ',' << signal << ',' << satellite << ','
                    << stations[i].name << '\n';
            }
        }
        // Flushed every epoch: the stream grades runs that may be killed mid-flight,
        // and an unflushed tail would lose the last epochs of that record.
        traces.phase_anchor_trace.flush();
    }

    // --- Cross-station DD fractional-residual (B5) ----------------------
    // For each present station, back-substitute its local block and read each
    // absolute float ambiguity (x_lin + x_r(col), m) per (sat,signal).  Within a
    // (const,signal), difference each sat against one reference sat (between-sat SD),
    // then difference that across station pairs to form the between-station DD.  A DD
    // near an integer number of cycles is evidence that the float biases support user
    // AR.  The fractional cycle (dd_cyc = dd_m/λ, frac_cyc = dd_cyc − round) is
    // computed here so the CSV is a ready fractional histogram (P1-2).  Excluded from
    // the pool: pinned ambiguities (the whole pivot station under legacy gauge pinning,
    // the anchored (sat,signal) cells under phase_datum_prioritized), since a pinned
    // ambiguity gives a degenerate DD; and GLONASS (FDMA: no common λ per signal, the
    // between-sat SD is not integer).  Read-only; runs only when the trace is open, on
    // the configured epoch stride.
    if (dd_frac_trace.is_open()
        && ((n_loop_epochs - 1)
            % static_cast<size_t>(std::max(1, nc.trace_dd_fractional_epoch_stride)) == 0)) {  // T2e stride
        struct AmbAbs { double value_m; std::size_t est_id; Eigen::Index col; };  // T2a: +est_id,col
        // (const,signal) -> sat -> station index -> absolute float ambiguity (m) plus its
        // (estimator station id, local A_r column) for the T2a joint-covariance request.
        std::map<std::pair<std::string, std::string>,
                 std::map<std::string, std::map<size_t, AmbAbs>>> pool;
        const auto t_dd_pool0 = std::chrono::steady_clock::now();   // T2b timers
        for (size_t i = 0; i < stations.size(); ++i) {
            if (est_index_of[i] < 0) continue;
            // Legacy: skip the whole pivot (all its ambiguities are pinned to
            // zero → degenerate DD).  Prioritized: keep the station and skip only
            // its per-(sat,signal) anchored (pinned) ambiguities below.
            if (!phase_datum_prioritized && stations[i].is_pivot) continue;
            Eigen::VectorXd x_r;
            try {
                x_r = est.reconstructStation(
                    static_cast<std::size_t>(est_index_of[i]), x_s);
            } catch (...) { continue; }
            const auto& h2l = asm_res[i].h2local;
            const StationParams& params = stations[i].params;
            for (const auto& [amb, amb_idx] : params.amb) {
                const std::string satellite = amb.sat.str();
                const std::string signal = amb.signal.obsCode(ObsType::Phase);
                if (networkIsGaugePinned(stations, phase_datum_prioritized,
                                         i, satellite, signal))
                    continue;   // anchored (pinned to 0) → degenerate DD
                const System sys = amb.sat.sys;
                if (sys == System::GLONASS) continue;   // GLONASS FDMA: excluded (no common λ / integer DD)
                const auto hit = h2l.find(amb_idx);
                if (hit == h2l.end()) continue;   // ambiguity column not in A_r this epoch
                if (hit->second < 0
                    || static_cast<Eigen::Index>(hit->second) >= x_r.size()) continue;
                const double value_m =
                    params.slots[static_cast<std::size_t>(amb_idx)].x_lin + x_r(hit->second);
                if (!std::isfinite(value_m)) continue;
                pool[{constellationKey(sys), signal}][satellite][i] =
                    AmbAbs{value_m, static_cast<std::size_t>(est_index_of[i]),
                           static_cast<Eigen::Index>(hit->second)};
            }
        }
        const auto t_dd_pool1 = std::chrono::steady_clock::now();
        // --- T2a/T2b: collect the between-station DDs, optionally subsample, then
        //     propagate the joint conditional covariance once to attach a per-DD formal σ
        //     (cycles).  The DD variance is gᵀ Q g with g=[+1,−1,−1,+1] over the four undiff
        //     ambiguities (sta_a/sat, sta_a/ref, sta_b/sat, sta_b/ref); only the diagonal is
        //     needed, so no dense nd×nd differencing matrix is materialised.  dd_m / dd_cyc /
        //     frac_cyc are computed as in the trace before T2a (benchmark-identical);
        //     dd_sigma_cyc is appended (−1 = covariance unavailable this epoch).
        struct DdOut {
            std::string cons, signal, sat, ref;
            std::size_t sta_a_i, sta_b_i;
            double dd_m, lambda, dd_cyc, frac_cyc;
            std::pair<std::size_t, Eigen::Index> amb[4];  // ia(sat), ra(ref)@a, ib(sat), rb(ref)@b
            int rq[4]{ -1, -1, -1, -1 };                  // request indices, filled post-subsample
        };
        std::vector<DdOut> dds;
        // §6.12.5: advance the per-(cons,signal) reference age map before electing.  Age counts
        // consecutive traced epochs at >= 2 stations; a satellite absent this epoch (or seen at
        // fewer than 2 stations) is erased, so a returning satellite re-enters at age 1 and does not
        // inherit its pre-gap seniority.  A returned reference's newborn legs re-reference the whole
        // trace and read as a network-wide episode, which the `oldest` policy avoids.  The map is
        // maintained under both policies (network.trace_dd_fractional_ref = lowest | oldest), so the
        // `lowest` default reports its own switch rate; it touches no solve input.
        // The channel cell of a pool key (constellation key, signal).
        net::ConstellationTable& cons_rows = ctx.entities.constellations;
        const auto chanSys = [&](const std::string& ck) {
            return net::constellationOfKey(ctx.entities, ck).value_or(System::Unknown);
        };
        for (auto& [cs, satmap] : pool) {
            auto& age = net::put(cons_rows, chanSys(cs.first), &net::ConstellationState::channels,
                                 cs.second, &net::ChannelState::ddfrac_ref_age);
            for (auto it = age.begin(); it != age.end();) {
                const auto hit = satmap.find(it->first);
                if (hit == satmap.end() || hit->second.size() < 2) it = age.erase(it);
                else { ++it->second; ++it; }
            }
            for (const auto& [sat, stamap] : satmap)
                if (stamap.size() >= 2 && age.find(sat) == age.end()) age[sat] = 1;
        }
        for (auto& [cs, satmap] : pool) {
            std::string ref;   // `lowest`: the lexically lowest sat present at ≥2 stations
            for (const auto& [sat, stamap] : satmap)
                if (stamap.size() >= 2) { ref = sat; break; }
            if (ref.empty()) continue;
            // `oldest`: longest continuous presence, ties -> lexically lowest.  `satmap` is a
            // std::map, so the scan runs in lexical order and the strict > keeps the first
            // (lowest) satellite of a tied age.  `oldest` therefore elects the `lowest` choice
            // whenever the lexically lowest candidate shares the maximum age (in particular
            // when every candidate has the same age), so n_ddfrac_ref_age_win counts only the
            // epochs where age changed the election.
            const std::string ref_lowest = ref;
            if (nc.trace_dd_fractional_ref == NetworkDdFracRef::Oldest) {
                const auto& age = net::put(cons_rows, chanSys(cs.first),
                                           &net::ConstellationState::channels, cs.second,
                                           &net::ChannelState::ddfrac_ref_age);
                long long best = -1;
                for (const auto& [sat, stamap] : satmap) {
                    if (stamap.size() < 2) continue;
                    const auto ait = age.find(sat);
                    const long long a = (ait == age.end()) ? 0 : ait->second;
                    if (a > best) { best = a; ref = sat; }
                }
            }
            ++ctx.counters.n_ddfrac_ref_epochs;
            if (ref != ref_lowest) ++ctx.counters.n_ddfrac_ref_age_win;
            {
                auto& prev = net::put(cons_rows, chanSys(cs.first), &net::ConstellationState::channels,
                                      cs.second, &net::ChannelState::ddfrac_ref_prev);
                if (!prev.empty() && prev != ref) ++ctx.counters.n_ddfrac_ref_switch;
                prev = ref;
            }
            // λ for this (const,signal).  GLONASS is already excluded, so the wavelength
            // is the band's and satellite-independent (no FDMA slot: 0); 0 (unknown signal)
            // leaves the cycle columns 0 so the reader falls back to the metre column.  The
            // band is read from the digit alone, as PppUtils::getWavelength read it, so
            // BeiDou digit 1 is B1C here as at the chain datum's rounding; the BeiDou
            // digit-1 decision is owed.
            double lambda = 0.0;
            const System cs_sys = systemFromName(cs.first);
            if (const auto sig = SignalId::fromObsCode(cs_sys, cs.second))
                lambda = wavelengthM(bandOfDigit(cs_sys, sig->digit), /*glo_slot=*/0);
            const auto& rmap = satmap[ref];
            for (const auto& [sat, stamap] : satmap) {
                if (sat == ref) continue;
                for (auto ia = stamap.begin(); ia != stamap.end(); ++ia) {
                    const auto ra = rmap.find(ia->first);
                    if (ra == rmap.end()) continue;
                    const double sd_a = ia->second.value_m - ra->second.value_m;
                    auto ib = ia; ++ib;
                    for (; ib != stamap.end(); ++ib) {
                        const auto rb = rmap.find(ib->first);
                        if (rb == rmap.end()) continue;
                        const double sd_b = ib->second.value_m - rb->second.value_m;
                        const double dd_m = sd_a - sd_b;   // between-station DD (m)
                        const double dd_cyc = (lambda > 0.0) ? (dd_m / lambda) : 0.0;
                        const double frac_cyc =
                            (lambda > 0.0) ? (dd_cyc - std::round(dd_cyc)) : 0.0;
                        DdOut d;
                        d.cons = cs.first; d.signal = cs.second; d.sat = sat; d.ref = ref;
                        d.sta_a_i = ia->first; d.sta_b_i = ib->first;
                        d.dd_m = dd_m; d.lambda = lambda; d.dd_cyc = dd_cyc; d.frac_cyc = frac_cyc;
                        d.amb[0] = { ia->second.est_id, ia->second.col };
                        d.amb[1] = { ra->second.est_id, ra->second.col };
                        d.amb[2] = { ib->second.est_id, ib->second.col };
                        d.amb[3] = { rb->second.est_id, rb->second.col };
                        dds.push_back(std::move(d));
                    }
                }
            }
        }
        const auto t_dd_collect = std::chrono::steady_clock::now();
        const std::size_t n_all_dd = dds.size();
        // T2b: deterministic subsample seeded from (week,tow), reproducible per epoch;
        // 0 = unlimited (full-pair benchmark).  Bounds both the emit and the covariance-
        // request count (the dominant tracer cost at 305 stations).
        const int dd_max_pairs = nc.trace_dd_fractional_max_pairs;
        if (dd_max_pairs > 0 && dds.size() > static_cast<std::size_t>(dd_max_pairs)) {
            std::mt19937 rng(static_cast<unsigned>(se.time.week) * 604800u
                             + static_cast<unsigned>(se.time.tow));
            std::vector<std::size_t> idx(dds.size());
            for (std::size_t j = 0; j < idx.size(); ++j) idx[j] = j;
            std::shuffle(idx.begin(), idx.end(), rng);
            idx.resize(static_cast<std::size_t>(dd_max_pairs));
            std::sort(idx.begin(), idx.end());   // stable emit order
            std::vector<DdOut> kept; kept.reserve(idx.size());
            for (std::size_t j : idx) kept.push_back(std::move(dds[j]));
            dds.swap(kept);
        }
        // Deduplicated (station,col) request set over the (subsampled) DDs.
        std::vector<std::pair<std::size_t, Eigen::Index>> reqs;
        std::map<std::pair<std::size_t, Eigen::Index>, int> req_idx;
        auto reqOf = [&](const std::pair<std::size_t, Eigen::Index>& k) -> int {
            auto it = req_idx.find(k);
            if (it != req_idx.end()) return it->second;
            const int r = static_cast<int>(reqs.size());
            reqs.push_back(k); req_idx[k] = r; return r;
        };
        for (auto& d : dds)
            for (int p = 0; p < 4; ++p) d.rq[p] = reqOf(d.amb[p]);
        // Carry-aware readback (docs/SPEC_carry_aware_covariance.md §6).  Off (default), the
        // expression is the one that predates the carry-aware readback, unchanged.  On, this σ is the σ of
        // the estimator that ran, so `med|frac|` conditioned on it is a test and not a
        // restatement: a uniform fractional part is the expected reading whenever
        // σ_DD ≳ 0.3 cyc, and a null result needs a σ that reflects the carried state.
        const bool dd_carry_aware = ctx.knobs.carry_aware_covariance;
        Eigen::MatrixXd cov;
        if (!reqs.empty()) {
            try { cov = est.jointConditionalCovariance(reqs, plan.shared_datum, dd_carry_aware); }
            catch (...) { cov = Eigen::MatrixXd(); }
        }
        const bool cov_ok =
            (cov.rows() == static_cast<Eigen::Index>(reqs.size()) && cov.rows() > 0);
        const auto t_dd_cov = std::chrono::steady_clock::now();
        for (const DdOut& d : dds) {
            double dd_sigma_cyc = -1.0;   // −1 = covariance unavailable this epoch
            if (cov_ok && d.lambda > 0.0) {
                static const double g[4] = { +1.0, -1.0, -1.0, +1.0 };
                double var = 0.0;
                for (int p = 0; p < 4; ++p)
                    for (int q = 0; q < 4; ++q)
                        var += g[p] * g[q] * cov(d.rq[p], d.rq[q]);
                dd_sigma_cyc = (var > 0.0) ? std::sqrt(var) / d.lambda : 0.0;
            }
            dd_frac_trace
                << se.time.week << ',' << fmt::format("{:.3f}", se.time.tow) << ','
                << d.cons << ',' << d.signal << ',' << d.sat << ',' << d.ref << ','
                << stations[d.sta_a_i].name << ',' << stations[d.sta_b_i].name << ','
                << fmt::format("{:.4f}", d.dd_m) << ','
                << fmt::format("{:.6f}", d.lambda) << ','
                << fmt::format("{:.4f}", d.dd_cyc) << ','
                << fmt::format("{:.4f}", d.frac_cyc) << ','
                << fmt::format("{:.4f}", dd_sigma_cyc) << ','
                // The last column records which covariance produced the σ beside it
                // (1 = carry-aware, 0 = default).  The default σ leaves the carried state
                // out of the local block, so a σ is interpretable only with this flag
                // (docs/SPEC_carry_aware_covariance.md §11; INC-0).
                << (dd_carry_aware ? 1 : 0) << '\n';
        }
        const auto t_dd_emit = std::chrono::steady_clock::now();
        auto ms = [](const auto& a, const auto& b) {
            return std::chrono::duration<double, std::milli>(b - a).count();
        };
        log->info("Network (T2b) DD-frac tracer TOW {:.1f}: pool {:.0f} ms ({} sta), "
                  "collect {:.0f} ms ({} DD{}), cov {:.0f} ms ({} reqs), emit {:.0f} ms",
                  se.time.tow, ms(t_dd_pool0, t_dd_pool1), stations.size(),
                  ms(t_dd_pool1, t_dd_collect), n_all_dd,
                  (dd_max_pairs > 0 && n_all_dd > dds.size())
                      ? fmt::format(" ->{} kept", dds.size()) : std::string(),
                  ms(t_dd_collect, t_dd_cov), reqs.size(), ms(t_dd_cov, t_dd_emit));
    }
}

