bool secondCodeAllowEntryValid(const std::string& entry, std::string* why) {
    const auto refuse = [&](const char* reason) {
        if (why) *why = reason;
        return false;
    };
    if (entry.size() != 3)
        return refuse("not a 3-character RINEX observation code");
    if (obsTypeOf(entry) != ObsType::Code)
        return refuse("not a CODE type (must start with 'C')");
    if (entry[1] != '1')
        return refuse("not on band 1 (band 2 is a follow-up: it would wake "
                      "the untested bridging path of network.sat_isc_state)");
    if (why) why->clear();
    return true;
}

std::vector<std::string> secondCodeCompanions(
    const std::set<std::string>& reported_codes,
    const std::string& selected_code,
    const std::vector<std::string>& allow_list) {

    std::vector<std::string> out;
    // With no selected code the band has no canonical row this epoch, so nothing
    // can be a companion: any allow-listed code that arrives is the fallback case,
    // handled and counted on the receiver side.
    if (selected_code.empty()) return out;
    for (const std::string& sig : allow_list) {
        if (sig == selected_code) continue;                   // the canonical code itself
        if (!reported_codes.count(sig)) continue;             // the station does not track it
        if (std::find(out.begin(), out.end(), sig) != out.end()) continue;  // duplicate entry
        out.push_back(sig);
    }
    return out;
}

void secondCodeCellEdges(const std::set<std::string>& prev,
                         const std::set<std::string>& cur,
                         std::vector<std::string>* opened,
                         std::vector<std::string>* closed) {
    if (opened) {
        opened->clear();
        std::set_difference(cur.begin(), cur.end(), prev.begin(), prev.end(),
                            std::back_inserter(*opened));
    }
    if (closed) {
        closed->clear();
        std::set_difference(prev.begin(), prev.end(), cur.begin(), cur.end(),
                            std::back_inserter(*closed));
    }
}

std::vector<std::size_t> secondCodeIscRows(const std::map<RxCbKey, int>& rx_cb,
                                           const std::vector<std::string>& satellite_ids,
                                           const std::vector<std::string>& signal_types,
                                           std::size_t n_rows,
                                           bool system_aware,
                                           long long* other_system) {
    std::vector<std::size_t> out;
    // The inter-signal states this station holds, by observation code (the historic
    // test) and by (constellation, observation code) (the state's own identity).
    std::set<std::string> isc_codes;
    std::set<std::pair<System, std::string>> isc_states;
    for (const auto& entry : rx_cb) {
        if (entry.first.form != ParamForm::Isc) continue;
        const std::string code = entry.first.signal.obsCode(ObsType::Code);
        isc_codes.insert(code);
        isc_states.emplace(entry.first.sys, code);
    }
    if (isc_codes.empty()) return out;
    const std::size_t mr = std::min(n_rows, signal_types.size());
    for (std::size_t r = 0; r < mr; ++r) {
        const std::string& sig = signal_types[r];
        if (sig.empty() || obsTypeOf(sig) == ObsType::Phase) continue;   // phase untouched
        if (!isc_codes.count(sig)) continue;
        if (r >= satellite_ids.size()) break;
        const std::string& sat = satellite_ids[r];
        if (sat.empty()) continue;
        // A row of another constellation that only shares the observation code: no
        // inter-signal state of its own exists, so it is counted in both forms and
        // dropped only by the aware one.
        if (!isc_states.count({systemOfSat(sat), sig})) {
            if (other_system) ++*other_system;
            if (system_aware) continue;
        }
        out.push_back(r);
    }
    return out;
}

