// Run-end report: the second constellation (GAL).
int networkMultiGnssRunEnd(const NetworkRunEndView& v) {
    const NetworkRunContext& ctx = v.ctx;
    const GnssConfig& config_ = v.config;
    const std::shared_ptr<spdlog::logger>& log = v.log;

    // Second-constellation lines: the inter-system bias; per constellation,
    // the clock S-basis, the geometry-free datum and the clock anchor; and the family
    // census on a single-channel posture.  Silent unless a constellation other than GPS
    // is active.
    networkMultiGnssRunEnd(ctx, config_, log);
    return 0;
}

