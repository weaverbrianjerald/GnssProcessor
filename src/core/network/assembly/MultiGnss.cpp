bool networkMultiGnssActive(const GnssConfig& config) {
    const auto& prio = config.getSignalPriorities();
    for (const std::string& sys : config.getActiveSystems())
        if (sys != systemName(timeReferenceSystem()) && prio.count(sys) != 0) return true;
    return false;
}

bool networkStationNonGpsOnly(const std::vector<PppObservation>& modeled) {
    bool has_gps = false, has_other = false;
    for (const PppObservation& ob : modeled) {
        if (isTimeReference(ob.system))           has_gps   = true;
        else if (ob.system != System::Unknown)    has_other = true;
    }
    return has_other && !has_gps;
}

void networkMultiGnssEpoch(NetworkRun& run, const NetworkEpoch& ep) {
    // ---- From the run and the epoch (generated by scripts/nom_ep1_cut.py,
    //      each line checked by scripts/nom_ep1_verify.py). Reads bind through `ep`; writes bind
    //      through the output parameters and are marked `// written`. ----
    NetworkRunContext& ctx = run.ctx;
    const GnssConfig& config_ = run.config;
    const std::vector<NetStation>& stations = run.setup.stations;
    const std::vector<std::vector<PppObservation>>& modeled = ep.pass_a.modeled;
    const std::vector<bool>& present = ep.pass_a.present;
    // ---- End of the bindings ----
    if (!networkMultiGnssActive(config_)) return;   // GPS alone: one flag test
    auto& M = ctx.counters.mgnss;
    ++M.epochs;

    std::map<std::string, long long> isb_holders;          // system -> stations holding a state
    std::map<std::string, std::set<std::string>> sats;     // letter -> satellites this epoch
    for (std::size_t i = 0; i < stations.size() && i < modeled.size(); ++i) {
        if (stations[i].sm)
            for (const auto& [sys, idx] : stations[i].sm->getSystemTimeOffsetStates()) {
                (void)idx;
                ++isb_holders[sys];
            }
        if (i < present.size() && !present[i]) {
            // A dropped station still says what its epoch looked like: a non-GPS-only
            // epoch is counted whether or not the PD test dropped it (the drop itself
            // is counted at the rejection site).
            if (!modeled[i].empty() && networkStationNonGpsOnly(modeled[i])) {
                ++M.nongps_only_station_epochs;
                M.nongps_only_stations.insert(stations[i].name);
            }
            continue;
        }
        if (modeled[i].empty()) continue;
        std::set<std::string> systems_here;
        for (const PppObservation& ob : modeled[i]) {
            if (ob.satellite.empty()) continue;
            const std::string letter = constellationKey(systemOfSat(ob.satellite));
            ++M.sat_rows[letter];
            sats[letter].insert(ob.satellite);
            // Every constellation but the time reference holds an inter-system bias.
            if (!isTimeReference(ob.system) && ob.system != System::Unknown)
                systems_here.insert(systemName(ob.system));
        }
        for (const std::string& s : systems_here) ++M.isb_station_epochs[s];
        if (networkStationNonGpsOnly(modeled[i])) {
            ++M.nongps_only_station_epochs;
            M.nongps_only_stations.insert(stations[i].name);
        }
    }
    for (const auto& [sys, n] : isb_holders)
        M.isb_stations_max[sys] = std::max(M.isb_stations_max[sys], n);
    for (const auto& [letter, s] : sats)
        M.sats_max[letter] = std::max(M.sats_max[letter], static_cast<long long>(s.size()));
}

void networkMultiGnssNotePivots(NetworkRunContext& ctx, const GnssConfig& config_,
                                const std::map<std::string, std::string>& clock_pivot,
                                const std::map<std::string, std::string>& last_pivot) {
    if (!networkMultiGnssActive(config_)) return;
    auto& M = ctx.counters.mgnss;
    ++M.emits;
    const long long d = static_cast<long long>(clock_pivot.size());
    M.declared_min = (M.declared_min < 0) ? d : std::min(M.declared_min, d);
    M.declared_max = std::max(M.declared_max, d);
    for (const auto& [cst, sat] : clock_pivot) {
        if (!M.first_emit_pivot.count(cst)) M.first_emit_pivot[cst] = sat;
        const auto it = last_pivot.find(cst);
        if (it != last_pivot.end() && !it->second.empty() && it->second != sat)
            ++M.pivot_handovers[cst];
        M.last_emit_pivot[cst] = sat;
    }
}

namespace {

std::string joinMap(const std::map<std::string, long long>& m) {
    std::string s;
    for (const auto& [k, v] : m) s += fmt::format("{}{}:{}", s.empty() ? "" : " ", k, v);
    return s.empty() ? std::string("-") : s;
}

std::string joinPivots(const std::map<std::string, std::string>& m) {
    std::string s;
    for (const auto& [k, v] : m) s += fmt::format("{}{}:{}", s.empty() ? "" : " ", k, v);
    return s.empty() ? std::string("-") : s;
}

}  // namespace

void networkMultiGnssRunEnd(const NetworkRunContext& ctx, const GnssConfig& config_,
                            const std::shared_ptr<spdlog::logger>& log) {
    if (!networkMultiGnssActive(config_)) return;
    const auto& M = ctx.counters.mgnss;

    // (1) The inter-system bias and the non-GPS-only station-epochs (R2).
    log->info("Network (INTER-SYSTEM BIAS over {} epoch(s)): peak stations "
              "holding a state per system [{}]; station-epochs whose local block carried "
              "the column [{}] (a FREE per-epoch local column on this path: no predict, no "
              "process noise, eliminated with the station).  Station-epochs with rows of a "
              "non-GPS system and NO GPS row (receiver clock and inter-system bias "
              "collinear): {} at {} station(s), of which {} dropped by the addStation PD "
              "rejection.  Modelled satellite-epochs per constellation [{}], peak distinct "
              "satellites in one epoch [{}].",
              M.epochs, joinMap(M.isb_stations_max), joinMap(M.isb_station_epochs),
              M.nongps_only_station_epochs,
              static_cast<long long>(M.nongps_only_stations.size()),
              M.nongps_only_pd_drops, joinMap(M.sat_rows), joinMap(M.sats_max));

    // (2) The clock S-basis per constellation (R2).
    log->info("Network (CLOCK S-BASIS per constellation over {} emit(s)): "
              "declared clock-datum dimension min {} max {} (pin mode: one satellite-clock "
              "pivot, one free direction, per constellation); realized pivots at the FIRST "
              "emit [{}], at the LAST emit [{}]; pivot handovers between emitted products "
              "[{}].  The rank gate's observed near-null count over the run: min {} max {} "
              "on {} evaluated epoch(s); S-basis completion folded {} extra direction(s) on "
              "{} epoch(s).",
              M.emits, M.declared_min, M.declared_max, joinPivots(M.first_emit_pivot),
              joinPivots(M.last_emit_pivot), joinMap(M.pivot_handovers),
              ctx.counters.nullspace_obs_min, ctx.counters.nullspace_obs_max,
              ctx.counters.n_gate_evaluated, ctx.counters.n_sbc_dirs,
              ctx.counters.n_sbc_epochs);

    // (3) The geometry-free datum per constellation (R3 iii).
    if (config_.getNetworkConfig().sat_gf_datum != NetworkSatGfDatum::NoneMode) {
        std::string t;
        for (const auto& [c, g] : ctx.counters.sat_gf_by_const)
            t += fmt::format("{}{}: {} pair row(s) = {} at a non-zero broadcast group delay "
                             "+ {} broadcast exactly 0 + {} without a navigation record + {} "
                             "on a pair the latched group delay does not describe; {} extra "
                             "row(s), {} asserting a zero inter-signal correction; {} "
                             "same-band column(s) left estimable; {} carried, {} anchored",
                             t.empty() ? "" : " | ", c, g.rows, g.tgd_hits, g.tgd_zero,
                             g.tgd_missing, g.pair_no_gd, g.extra_rows, g.isc_zero,
                             g.sameband_free, g.carried, g.anchored);
        log->info("Network (SAT-GF DATUM per constellation): [{}].  The fallback "
                  "count of a constellation is its 'without a navigation record' plus its "
                  "'pair ... does not describe' terms; the rule is GPS (L1, L2) at c*T_GD "
                  "and Galileo (E1, E5a) at c*BGD(E1, E5a), both latched at setup.",
                  t.empty() ? std::string("none") : t);
    }

    // (4) The family census on a single-channel posture (the all-channel family table,
    //     which the widening prints itself when it is active).
    if (!config_.networkChannelModeAll()) {
        const auto& C = ctx.counters.channel_all;
        std::string table;
        for (const auto& [key, row] : C.family)
            table += fmt::format("{}{} trk {} mdl {} col {} canon {} extra {}",
                                 table.empty() ? "" : " | ", key, row.sta_tracking,
                                 row.sta_modelling, row.columns, row.rows_canonical,
                                 row.rows_extra);
        log->info("Network (FAMILY CENSUS over {} epoch(s), single channel per "
                  "band): {} (constellation, signal) famil(y|ies).  Per family, peak in one "
                  "epoch: stations TRACKING it, stations MODELLING it, satellite COLUMNS; "
                  "then row-epochs as the station's CANONICAL signal and as an EXTRA channel "
                  "(the second code channel's companions).  [{}]",
                  C.epochs, static_cast<long long>(C.family.size()),
                  table.empty() ? std::string("empty") : table);
    }

    // (5) The guarded temporal clock anchor per constellation.
    if (!M.anchor_folds_anchored.empty() || !M.anchor_folds_loose.empty()
        || !M.anchor_trips.empty())
        log->info("Network (CLOCK ANCHOR per constellation): folds ANCHORED [{}], "
                  "LOOSE [{}], decouplings (every cause) [{}].  The guard statistic removes "
                  "the per-constellation median, so each constellation's common mode is "
                  "its own free per-epoch gauge.",
                  joinMap(M.anchor_folds_anchored), joinMap(M.anchor_folds_loose),
                  joinMap(M.anchor_trips));
}

std::string networkMultiGnssManifestJson(const NetworkRunContext& ctx,
                                         const GnssConfig& config_) {
    if (!networkMultiGnssActive(config_)) return {};
    const auto& M = ctx.counters.mgnss;
    auto obj = [](const std::map<std::string, long long>& m) {
        std::string s = "{";
        bool first = true;
        for (const auto& [k, v] : m) {
            s += fmt::format("{}\"{}\":{}", first ? "" : ",", k, v);
            first = false;
        }
        return s + "}";
    };
    std::string st = "[";
    bool first = true;
    for (const auto& n : M.nongps_only_stations) {
        st += fmt::format("{}\"{}\"", first ? "" : ",", n);
        first = false;
    }
    st += "]";
    return fmt::format("\"inter_system_bias\":{{\"epochs\":{},\"stations_with_state_max\":{},"
                       "\"station_epochs_with_column\":{},\"nongps_only_station_epochs\":{},"
                       "\"nongps_only_pd_drops\":{},\"nongps_only_stations\":{}}}",
                       M.epochs, obj(M.isb_stations_max), obj(M.isb_station_epochs),
                       M.nongps_only_station_epochs, M.nongps_only_pd_drops, st);
}

