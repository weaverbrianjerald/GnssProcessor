/**
 * @brief Run the post-solve satellite-clock QC block for this epoch.
 *
 * Epoch form (generated by scripts/nom_ep1_cut.py): the run and the epoch
 * replace the explicit parameters; the definition binds each former parameter in its preamble,
 * under its former name.
 *
 * @param run The run (network/driver/Run.hpp). Written through non-const bindings: run.ctx (ctx),
 *            run.traces (traces). Read: run.config (config_), run.log (log), run.engines.est
 *            (est).
 * @param ep The epoch (network/driver/Epoch.hpp), read only. Bindings: ep.ws (ws), ep.se (se),
 *           ep.solve.x_s (x_s), ep.columns.registered_clock_sats (registered_clock_sats),
 *           ep.solve.datum_changed (datum_changed), ep.solve.changed_consts (changed_consts),
 *           ep.solve.clk_model_warm (clk_model_warm), ep.clock.pl_now_s (pl_now_s),
 *           ep.clock.dt (dt), ep.solve.retro_feed (retro_feed).
 * @param handoff [in/out] The post-fit hand-off (ep.solve.handoff), written:
 *     handoff.clock_refloat_sats (clock_refloat_sats), handoff.retro_flag_sats
 *     (retro_flag_sats).
 *
 * The former parameters, by binding:
 *   - @p ctx = run.ctx: [in/out] carry (clock_osc / prev_clk), counters (fr_clk_model /
 *     fr_clk_mon / n_emitted) and knobs. Passed whole rather than as ~30 references, so a
 *     missing `&` cannot silently discard a carry mutation; the body opens with an alias
 *     preamble copied from the former run-TU alias block.
 *   - @p config_ = run.config: Reconstructs `nc = config_.getNetworkConfig()`
 *     (trace_clock_full).
 *   - @p log = run.log: "main_log": the clock-model / clock-monitor warnings.
 *   - @p traces = run.traces: clk_mon_trace + the emitEvent forwarder.
 *   - @p ws = ep.ws: EpochWorkspace: read-only source of clk_pred (this epoch's two-state
 *     predictions).
 *   - @p se = ep.se: Current synced epoch (week/TOW for trace + log rows).
 *   - @p est = run.engines.est: sharedCovariance / clockColumn (both const).
 *   - @p x_s = ep.solve.x_s: Post-fit shared solution vector.
 *   - @p registered_clock_sats = ep.columns.registered_clock_sats: This epoch's registered
 *     satellite-clock keys.
 *   - @p datum_changed = ep.solve.datum_changed: Whether a pivot handover re-referenced the
 *     datum.
 *   - @p changed_consts = ep.solve.changed_consts: Constellations whose pivot changed (scoped
 *     wipe).
 *   - @p clk_model_warm = ep.solve.clk_model_warm: clock_model armed and past the warmup
 *     horizon.
 *   - @p pl_now_s = ep.clock.pl_now_s: Continuous-GPS seconds of this epoch (per-sat drift
 *     Δt).
 *   - @p dt = ep.clock.dt: Nominal epoch interval (gap/contiguity fallback).
 *   - @p clock_refloat_sats = handoff.clock_refloat_sats: [in/out] holds the RAIM culprits on
 *     entry; the NIS and monitor culprits are added (fed to the stash refloat).
 *   - @p retro_flag_sats = handoff.retro_flag_sats: [in/out] retro-bump feed
 *     (networkRetroUraBookkeeping).
 *   - @p retro_feed = ep.solve.retro_feed: Whether the retro-bump path is armed this run.
 * @param events The epoch's events; written: qc (cb_excursion_sats).
 */
void networkClockQc(NetworkRun& run, const NetworkEpoch& ep, NetworkPostFitHandoff& handoff, EpochEvents& events);

