/**
 * @brief Re-stash the D2/C1/SH carried quantities, fold this epoch into the carry
 *        LS-VCE monitor, and emit the epoch-status QC row.  This is the per-epoch
 *        producer bookkeeping tail (run after the solve and emit): it persists the carries
 *        for the next epoch's prior, feeds and drains the prior-residual census, steps the
 *        carry VCE apply factor, and writes the per-epoch trace row, the epoch-status
 *        disposition row and the periodic progress log line (present / clock / PB / CB /
 *        dropped-sat counts).  The caller keeps the networkSubBegin/End(SB_STASH_STATUS) brackets.
 *        The VCE monitor's family switches (vce_wants_pb, vce_wants_cb) are read from
 *        @c ctx.knobs (card NOM3 step EP0).
 *
 * Epoch form (card NOM3 step EP1; generated by scripts/nom_ep1_cut.py): the run and the epoch
 * replace the explicit parameters; the definition binds each former parameter in its preamble,
 * under its former name.
 *
 * @param run The run (app/NetworkRun.hpp). Written through non-const bindings: run.ctx (ctx),
 *            run.traces (traces), run.setup (setup), run.engines.carry_vce (carry_vce_est),
 *            run.engines.prires (prires_est). Read: run.config (config_), run.log (log),
 *            run.engines.est (est).
 * @param ep The epoch (app/NetworkEpoch.hpp), read only. Bindings: ep.se (se), ep.solve.x_s
 *           (x_s), ep.solve.plan (plan), ep.solve.handoff.clock_refloat_sats
 *           (clock_refloat_sats), ep.solve.handoff.n_arc_refloat_epoch (n_arc_refloat_epoch),
 *           ep.columns.registered_clock_sats (registered_clock_sats),
 *           ep.columns.registered_code_keys (registered_code_keys), ep.prep.retro_emit_sats
 *           (retro_emit_sats), ep.pass_a.shared_phase_keys (shared_phase_keys),
 *           ep.solve.sigma0_adapt (sigma0_adapt), ep.assembly.total_pins (total_pins),
 *           ep.clock.dt (dt), ep.solve.datum_changed (datum_changed), ep.solve.changed_consts
 *           (changed_consts), ep.columns.n_clock (n_clock), ep.columns.n_present (n_present),
 *           ep.columns.n_pb (n_pb), ep.columns.n_cb (n_cb), ep.pass_a.n_dropped_sats
 *           (n_dropped_sats), ep.solve.n_adapt (n_adapt).
 *
 * The former parameters, by binding:
 *   - @p ctx = run.ctx.
 *   - @p config_ = run.config.
 *   - @p log = run.log.
 *   - @p traces = run.traces.
 *   - @p setup = run.setup.
 *   - @p se = ep.se.
 *   - @p est = run.engines.est.
 *   - @p x_s = ep.solve.x_s.
 *   - @p plan = ep.solve.plan.
 *   - @p carry_vce_est = run.engines.carry_vce.
 *   - @p prires_est = run.engines.prires.
 *   - @p clock_refloat_sats = ep.solve.handoff.clock_refloat_sats.
 *   - @p n_arc_refloat_epoch = ep.solve.handoff.n_arc_refloat_epoch.
 *   - @p registered_clock_sats = ep.columns.registered_clock_sats.
 *   - @p registered_code_keys = ep.columns.registered_code_keys.
 *   - @p retro_emit_sats = ep.prep.retro_emit_sats.
 *   - @p shared_phase_keys = ep.pass_a.shared_phase_keys.
 *   - @p sigma0_adapt = ep.solve.sigma0_adapt.
 *   - @p total_pins = ep.assembly.total_pins.
 *   - @p dt = ep.clock.dt.
 *   - @p datum_changed = ep.solve.datum_changed.
 *   - @p changed_consts = ep.solve.changed_consts.
 *   - @p n_clock = ep.columns.n_clock.
 *   - @p n_present = ep.columns.n_present.
 *   - @p n_pb = ep.columns.n_pb.
 *   - @p n_cb = ep.columns.n_cb.
 *   - @p n_dropped_sats = ep.pass_a.n_dropped_sats.
 *   - @p n_adapt = ep.solve.n_adapt.
 * @param events The epoch's events; written: status.
 */
void networkStashStatus(NetworkRun& run, const NetworkEpoch& ep, EpochEvents& events);

