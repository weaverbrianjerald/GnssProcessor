/**
 * @file PhaseVisibleDiag.hpp
 * @brief The phase-visible consistency instrument (
 *        docs/refound/PVN_phase_visible_nees_2026-09-29.md), a measure-only diagnostic seam.
 *
 * The smoothed phase-bias hold fails because the estimator states the
 * ionosphere-free phase-visible clock of each satellite, @f$D = c - \sum_j w_j p_j@f$ (one
 * phase bias per band, @f$\sum w = 1@f$, @f$\sum w\lambda^2 = 0@f$), to a few millimetres
 * while it wanders centimetres within an arc.  This seam measures that consistency every
 * epoch, on the functional and the constellation contrast of the anchor guard's phase
 * statistic (@ref clockAnchorPhaseStatistic), read without its floor:
 *
 *  - the normalized update @f$e^2 / (S^- - S^+)@f$, where @f$e@f$ is the contrast update of
 *    @f$D@f$ against the dense fold's prior and @f$S^\mp@f$ its contrast-projected prior and
 *    posterior variances.  For a consistent filter every functional's update has variance
 *    @f$g^\top(P^- - P^+)g@f$, so the mean is 1;
 *  - the posterior contrast value and variance, from which the sim's within-arc state NEES
 *    is graded offline (the sim's true @f$D@f$ is constant within a phase-datum era).
 *
 * Seam contract: a free function over the run context that owns no state; the open window
 * lives in @c ctx.carry, the run totals in @c ctx.counters.  The solve and every product are
 * untouched; with the knob off the seam returns before reading anything.
 */
#ifndef GNSSPROCESSOR_NETWORK_PHASE_VISIBLE_DIAG_HPP
#define GNSSPROCESSOR_NETWORK_PHASE_VISIBLE_DIAG_HPP

#include <Eigen/Dense>
#include <vector>

namespace GnssProcessor {

class NetworkEstimator;
class NetworkRunTraces;
struct EpochWorkspace;
struct NetworkRunContext;
struct SyncedEpoch;

/// The normalized update of one functional: @f$e^2 / (S^- - S^+)@f$.
/// @param e_hat  the contrast update (m).
/// @param s_m    the contrast-projected prior variance @f$S^-@f$ (m^2).
/// @param s_p    the contrast-projected posterior variance @f$S^+@f$ (m^2).
/// @param nis    out: the NIS; untouched when the result is false.
/// @return false when @f$S^- - S^+@f$ is not positive or an input is not finite.
bool phaseVisibleNis(double e_hat, double s_m, double s_p, double& nis);

struct NetworkRun;              // network/driver/Run.hpp
struct NetworkEpoch;            // network/driver/Epoch.hpp

/**
 * @brief Run the phase-visible instrument on one kept epoch.
 *
 * Forms the anchor guard's phase statistic with no floor from the epoch's dense fold
 * capture (@c ws.cap_dense_keys / @c ws.cap_dense_cov, the prior) and the solve
 * (@p est's shared covariance and @p x_s, the posterior), writes one trace row per
 * satellite, accumulates the NIS after the 15th epoch into the run totals and the open
 * window, and closes the window every @c knobs.pv_window_ep epochs (its mean NIS and the
 * ratio of the rms update to the rms predicted update sd).  An epoch without a capture is
 * counted and writes nothing.
 *
 * @note Returns immediately when @c ctx.knobs.pv_on is false.
 *
 * Epoch form; the explicit form and its forwarding adapter
 * retired (the unit tests call this form through
 * tests/support/NetworkTestRun.hpp).
 *
 * @param run The run (network/driver/Run.hpp). Written through non-const bindings: run.ctx (ctx),
 *            run.traces (traces). Read: run.engines.est (est).
 * @param ep The epoch (network/driver/Epoch.hpp), read only. Bindings: ep.se (se), ep.solve.x_s
 *           (x_s), ep.ws (ws).
 *
 * The former parameters, by binding:
 *   - @p ctx = run.ctx: Run context: the knob snapshot, the open window, the counters.
 *   - @p traces = run.traces: Trace sinks (@c phase_visible_trace).
 *   - @p se = ep.se: The synced epoch (its time stamps the rows).
 *   - @p est = run.engines.est: The estimator after the epoch's final solve.
 *   - @p x_s = ep.solve.x_s: The shared solution of that solve.
 *   - @p ws = ep.ws: The epoch workspace holding the fold capture.
 */
void networkPhaseVisibleMonitor(NetworkRun& run, const NetworkEpoch& ep);

// ---- Run-end reports (generated by scripts/nom_td_cut.py) ----

struct NetworkRunEndView;

/**
 * @brief Run-end report: the phase-visible consistency (PVN).
 *
 * The phase-visible consistency diagnostic.
 *
 * Gate: returns 0 at once unless `ctx.knobs.pv_on`.
 *
 * @param v The run at its end (network/runend/RunEnd.hpp).
 * @return 0 (this report does not set the exit code).
 */
int networkPhaseVisibleRunEnd(const NetworkRunEndView& v);

// ---- End of the run-end reports ----

/// @brief Run-scope counters of PhaseVisibleDiag, a base of NetworkServiceCounters (network/state/RunContext.hpp).
struct PhaseVisibleDiagCounters {
    // Phase-visible consistency instrument.  `rows 0` means inert.
    long long pv_epochs{0};                ///< epochs the instrument ran
    long long pv_epochs_nocap{0};          ///< …of which without a dense fold capture (no rows)
    long long pv_rows{0};                  ///< satellite-epoch rows formed
    long long pv_su_nonpos{0};             ///< rows whose S- - S+ was not positive (no NIS)
    double    pv_nis_sum{0.0};             ///< summed NIS after epoch 15
    long long pv_nis_n{0};                 ///< NIS values summed
    long long pv_nis_gt{0};                ///< NIS values above 6.63 (chi2(1), 1 %)
    std::vector<double> pv_abs_e;          ///< |contrast update| after epoch 15 (m), the run-end median
    std::vector<double> pv_sqrt_sp;        ///< stated posterior sd sqrt(S+) after epoch 15 (m)
    std::vector<double> pv_sqrt_su;        ///< predicted update sd sqrt(S- - S+) after epoch 15 (m)
    std::vector<double> pv_win_nis;        ///< per window: mean NIS
    std::vector<double> pv_win_ratio;      ///< per window: rms update over rms predicted update sd
    // Phase-visible consistency instrument, measure-only: the open window's sums.
    int       pv_win_ep{0};           ///< epochs in the current window
    double    pv_win_nis_sum{0.0};    ///< summed NIS in the window
    long long pv_win_nis_n{0};        ///< NIS values in the window
    double    pv_win_e2_sum{0.0};     ///< summed squared contrast update (m^2)
    double    pv_win_su_sum{0.0};     ///< summed predicted update variance S- - S+ (m^2)
};

}  // namespace GnssProcessor

#endif  // GNSSPROCESSOR_NETWORK_PHASE_VISIBLE_DIAG_HPP
