/**
 * @brief Run the T1a SH-field health probe for this epoch and update the carry LS-VCE
 *        monitor.  Checks the a₀₀ physical band of the co-estimated SH-VTEC field, writes
 *        the SH health trace and advances the prior-residual census (@p prires_est).  @c ctx.carry.first_vce_s and
 *        @c ctx.carry.last_vce_hour track the hourly LS-VCE trace flush.  The caller keeps
 *        the networkSubBegin/End(SB_T1A) brackets.
 *
 * Epoch form (card NOM3 step EP1; generated by scripts/nom_ep1_cut.py): the run and the epoch
 * replace the explicit parameters; the definition binds each former parameter in its preamble,
 * under its former name.
 *
 * @param run The run (network/driver/Run.hpp). Written through non-const bindings: run.ctx (ctx),
 *            run.traces (traces), run.setup (setup), run.engines.carry_vce (carry_vce_est),
 *            run.engines.prires (prires_est). Read: run.config (config_), run.log (log),
 *            run.engines.est (est).
 * @param ep The epoch (network/driver/Epoch.hpp), read only. Bindings: ep.se (se), ep.solve.x_s
 *           (x_s), ep.assembly.asm_res (asm_res), ep.assembly.est_index_of (est_index_of),
 *           ep.pass_a.modeled (modeled), ep.solve.datum_changed (datum_changed),
 *           ep.clock.pl_now_s (pl_now_s).
 *
 * The former parameters, by binding:
 *   - @p ctx = run.ctx.
 *   - @p config_ = run.config.
 *   - @p log = run.log.
 *   - @p traces = run.traces.
 *   - @p setup = run.setup.
 *   - @p se = ep.se.
 *   - @p est = run.engines.est.
 *   - @p x_s = ep.solve.x_s.
 *   - @p asm_res = ep.assembly.asm_res.
 *   - @p est_index_of = ep.assembly.est_index_of.
 *   - @p modeled = ep.pass_a.modeled.
 *   - @p carry_vce_est = run.engines.carry_vce.
 *   - @p prires_est = run.engines.prires.
 *   - @p datum_changed = ep.solve.datum_changed.
 *   - @p pl_now_s = ep.clock.pl_now_s.
 * @param events The epoch's events; written: qc (rhs_trip_pending).
 */
void networkShHealth(NetworkRun& run, const NetworkEpoch& ep, EpochEvents& events);

