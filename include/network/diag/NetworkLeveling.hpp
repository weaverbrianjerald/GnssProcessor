/**
 * @brief Harvest this epoch's phase-leveling carry from the post-fit solution, stash the
 *        D2/C1 carried quantities into @p ctx.
 *        This is the feed of the zero-q phase-leveling carry (and the LS-VCE leveling-row
 *        fold); it updates the persistent carries that the next epoch's prior depends on.
 *        The caller keeps the networkSubBegin/End(SB_LEVELING) brackets.
 *
 * Epoch form (card NOM3 step EP1; generated by scripts/nom_ep1_cut.py): the run and the epoch
 * replace the explicit parameters; the definition binds each former parameter in its preamble,
 * under its former name.
 *
 * @param run The run (network/driver/NetworkRun.hpp). Written through non-const bindings: run.ctx (ctx),
 *            run.traces (traces), run.setup (setup), run.engines.carry_vce (carry_vce_est),
 *            run.engines.prires (prires_est). Read: run.config (config_), run.log (log),
 *            run.engines.est (est).
 * @param ep The epoch (network/driver/NetworkEpoch.hpp), read only. Bindings: ep.se (se), ep.solve.x_s
 *           (x_s), ep.solve.plan (plan), ep.assembly.asm_res (asm_res),
 *           ep.assembly.est_index_of (est_index_of), ep.clock.carry_warm (carry_warm),
 *           ep.clock.pl_now_s (pl_now_s), ep.columns.registered_clock_sats
 *           (registered_clock_sats), ep.columns.registered_code_keys (registered_code_keys),
 *           ep.pass_a.shared_phase_keys (shared_phase_keys).
 *
 * The former parameters, by binding:
 *   - @p ctx = run.ctx.
 *   - @p config_ = run.config.
 *   - @p log = run.log.
 *   - @p traces = run.traces.
 *   - @p setup = run.setup.
 *   - @p se = ep.se.
 *   - @p est = run.engines.est.
 *   - @p x_s = ep.solve.x_s.
 *   - @p plan = ep.solve.plan.
 *   - @p asm_res = ep.assembly.asm_res.
 *   - @p est_index_of = ep.assembly.est_index_of.
 *   - @p carry_vce_est = run.engines.carry_vce.
 *   - @p prires_est = run.engines.prires.
 *   - @p carry_warm = ep.clock.carry_warm.
 *   - @p pl_now_s = ep.clock.pl_now_s.
 *   - @p registered_clock_sats = ep.columns.registered_clock_sats.
 *   - @p registered_code_keys = ep.columns.registered_code_keys.
 *   - @p shared_phase_keys = ep.pass_a.shared_phase_keys.
 * @param events The epoch's events; written: harvest.
 */
void networkLeveling(NetworkRun& run, const NetworkEpoch& ep, EpochEvents& events);

