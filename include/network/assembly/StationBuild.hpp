// ---- PASS B station build: the step tables (generated by scripts/nom_pb1b_cut.py) ----
//
// PASS B builds every present station's block in parallel (networkAssemblyProduce: one OpenMP
// iteration per station, schedule(dynamic)) and folds the blocks into the estimator serially,
// in station order (networkAssemblyConsume).  The parallel half is kStationBuildSteps: one row
// per family of the station's contributions, walked in table order for one station.  The
// carried-prior family is itself a table, kStationCarrySteps, walked over one StationCarryFrame.
//
// The parallel contract, as a type.  A step receives its station writable (NetStation: the
// measurement pre-pass seeds new states; StationAssembly: the station's own slot) and
// everything else through const references: the run context (knobs, carry maps, counters),
// the configuration, the estimator's column layout, the setup, the epoch, every other station.
// A write to shared state does not compile, except through a pointer member, where const
// stops: each station's sm, model, mm, mw_slip, iono_var, turbo_edit and if_slip (reached
// through setup.stations), the setup's sync, brdc_apriori, sh_model, sh_model2,
// product_writer and consumer, and ctx.carry.slip_oracle, oracle_pin and rhs_prev_frame.
//
// The orders a step may not change, because the normal equations sum in them:
//   - rows: data, phase-datum pins, GLONASS anchors, zero-ionosphere rows, ionosphere ties,
//     SD-EWL, the coupling region, LGM rows (the table's first-appearance order);
//   - diagonal priors (StationCarryFrame::inj): ambiguity, oracle pin, wet delay, receiver
//     code bias, sorted by column with std::sort (not stable), so duplicates coalesce in
//     insertion order;
//   - local-block columns: ambiguity, wet delay, ionosphere, receiver clock, receiver code
//     bias, phase colour (declared as spans in Contributions.cpp kBlk*);
//   - pending coupling rows (CouplingRowBuilder::crows): the ambiguity rows on the inline
//     route (no block); or, when the station's block fails to factor, the phase-colour
//     fallback rows and then the ambiguity fallback rows (both built by local_block, in that
//     order); then the wet-delay row.
// tests/network/test_network_station_build.cpp pins the table orders.
//
// Adding a station contribution: a new step (or an existing family's step) in the family's
// own file, one row of the table with the kinds it creates, its kinds' builder column in
// Contributions.cpp naming the step, and the order constraints above checked by the test.

/// What a top-level step tells the walk.
enum class StationStep : std::uint8_t {
    Next,  ///< Go on to the next step.
    Done,  ///< The station has no usable block this epoch (no innovations, or an H/state
           ///< mismatch); its slot says which, and the consume drops it.
};

/// One station's assembly in PASS B: the station (writable) and a const view of the run.
/// Built by networkAssemblyProduce for one OpenMP iteration and passed to every step.
struct StationBuild {
    // ---- the const view: the run, the epoch, the other stations ----
    const NetworkRunContext&                    ctx;     ///< Knobs, carry maps (find only), counters (read).
    const GnssConfig&                           config;  ///< Bound as config_ in the steps.
    const NetworkEstimator&                     est;     ///< The column layout (frozen after registration).
    const NetworkSetupResult&                   setup;   ///< Stations (the gauge-pin test reads this station only), the SH models.
    const SyncedEpoch&                          se;      ///< The epoch's observations and time.
    const EpochClock&                           clock;   ///< dt, pl_now_s, carry_warm.
    const EpochPassA&                           pass_a;  ///< modeled, present, shared_phase_keys.
    const EpochEvents&                          events;  ///< The epoch's events (the relevel free-epoch latch).
    const std::unique_ptr<GlobalIonosphereMap>& gim;     ///< Application::gim_ for the GIM rows (null unless loaded).
    // ---- this station, writable ----
    const int        i;   ///< Roster index (the frozen loop variable's type: the carry keys are tuple<int, ...>).
    NetStation&      st;  ///< Its state manager and measurement model.
    StationAssembly& R;   ///< Its slot, asm_res[i].
    // ---- what one step hands a later one ----
    EpochMeasurement em;  ///< The measurement update (data_rows writes, congruence_geometry reads).
    Eigen::VectorXd  post_state;                ///< The station's state vector after the update (postUpdateState).
    bool             post_state_ready{false};   ///< True once post_state holds that copy.

    /**
     * @brief The station's state vector after the measurement update, copied once per station
     *        and epoch.
     *
     * The data rows step seeds any new states while it computes the update, so a copy taken
     * before it (the update's own argument) is shorter than this one. Every later step reads
     * the same vector: no step writes the station's state manager, so the first caller's copy
     * is the copy each of them would have made. Call only after the data rows step.
     *
     * @return The copy, valid for the rest of this station's build.
     */
    const Eigen::VectorXd& postUpdateState();
};

/// A top-level step: one family of a station's contributions.
using StationBuildFn = StationStep (*)(StationBuild& build);

/// One row of the station build: one family of a station's contributions.
struct StationBuildStep {
    const char*         name;    ///< Short name ("phase_datum_pins").
    const char*         home;    ///< The family's file (its inject here; its harvest half, step HV1).
    ContributionKindSet kinds;   ///< The row and prior kinds this step can create; 0 for a record-only step.
    StationBuildFn      build;   ///< Gates itself at its first line.
};
inline constexpr std::size_t kStationBuildStepCount = 12;
/// The station build, in walk order (src/core/network/assembly/StationBuild.cpp).
extern const std::array<StationBuildStep, kStationBuildStepCount> kStationBuildSteps;

/// An ambiguity column waiting for the station's local block (or its per-column fallback):
/// written by the ambiguity step, read by the local-block step (a local struct before step PB1b).
struct PlPend {
    Eigen::Index col; int amb_idx; const LocalCarry* lc;
    double var_eff;   ///< var + q·gap, before the tail
    double gap;   ///< clamped
    std::string sat, signal;
};

/// The carried-prior section of one station (the carry steps of the earlier increments, including the
/// rx-CB carry): the values its steps hand each other.  Built by networkStationCarriedPriors on
/// its own stack when the station carries anything this epoch; never copied.
struct StationCarryFrame {
    StationBuild&            build;                ///< The station and the const view.
    const bool               legacy_local_inject;  ///< The leveling carry injects here (the frozen predicate).
    const bool               do_amb_carry;         ///< The ambiguity carry injects (off under carry_invariant).
    const Eigen::VectorXd&   x_lin;                ///< The station's linearization point (build.post_state).
    CouplingRowBuilder       cb;                   ///< The coupling rows and the local block.
    std::vector<std::tuple<Eigen::Index, double, double, RowTag>> inj;        ///< Post-PD diagonal priors (col, Lambda, eta, tag).
    std::vector<std::tuple<Eigen::Index, double, double, RowTag>> inj_prior;  ///< Pre-PD datum rows (RF-PD-fix).
    std::vector<PlPend>        pl_pend;            ///< Ambiguity columns for the block.
    std::vector<LocalBlockCol> iono_bc;            ///< The slant-ionosphere block columns (I-in-block).
    std::vector<LocalBlockCol> rxclk_bc;           ///< The receiver-clock block columns (RX-CLK-in-block).
    std::vector<LocalCarry>    rxclk_pred;         ///< Their drift-predicted carries (rxclk_bc points here; reserved before the first push).
    std::vector<LocalBlockCol> rxcb_bc;            ///< The receiver code-bias block columns (RXCB-IN-BLOCK).
    std::vector<char>          rxcb_ifb;           ///< Which rxcb_bc columns are receiver IFBs.
    std::vector<LocalBlockCol> pc_bc;              ///< The phase-colour block columns.
    std::vector<LocalCarry>    pc_pred;            ///< Their predicted carries (pc_bc points here; reserved before the first push).
};

/// A carry step: one family of the carried priors.
using StationCarryFn = void (*)(StationCarryFrame& carry);

/// One row of the carried-prior section.
struct StationCarryStep {
    const char*         name;    ///< Short name ("oracle_pin").
    const char*         home;    ///< The family's file.
    ContributionKindSet kinds;   ///< The row and prior kinds this step can create.
    StationCarryFn      build;   ///< Gates itself at its first line.
};
inline constexpr std::size_t kStationCarryStepCount = 11;
/// The carried-prior section, in walk order.
extern const std::array<StationCarryStep, kStationCarryStepCount> kStationCarrySteps;

/**
 * @brief Appends @p n zero rows to a station's block: the shared and local design matrices and
 *        the weight and innovation vectors.
 *
 * Every step that adds rows (the pins, the anchors, the ionosphere ties, the coupling rows,
 * the phase-colour rows) grows the block this way and then writes its rows from the old row
 * count, which the caller reads first. The design rows are zeroed; the new weight and
 * innovation entries are left uninitialised, so the caller writes every one of them.
 *
 * @param A_s Shared-border design matrix, gains @p n zero rows.
 * @param A_r Local design matrix, gains @p n zero rows.
 * @param w   Row weights, gains @p n entries.
 * @param y   Row innovations, gains @p n entries.
 * @param n   Number of rows to append.
 */
void networkGrowBlockRows(Eigen::MatrixXd& A_s, Eigen::MatrixXd& A_r, Eigen::VectorXd& w,
                          Eigen::VectorXd& y, Eigen::Index n);

/**
 * @brief Whitens one group of correlated pseudo-observation rows by L^-1 (L L^T = @p cov) and
 *        writes them as unit-information rows into a block grown by networkGrowBlockRows.
 *
 * The rows of a group share one noise covariance (a per-constellation common mode plus each
 * row's own variance), so the group enters the station's diagonal-weight block only after
 * whitening: the same factor is applied to the local design, the shared design when there is
 * one, and the innovation, which makes the rows contribute exactly H^T cov^-1 H and
 * H^T cov^-1 z to the normals.
 *
 * @param cov Row covariance, mc x mc (mc rows in the group).
 * @param Hr  Local design rows of the group, mc x A_r.cols().
 * @param Hs  Shared design rows of the group, mc x A_s.cols(), or null when the group has none.
 * @param zc  Innovations of the group, mc entries.
 * @param out First block row of the group.
 * @param A_s Shared-border design matrix; rows out..out+mc-1 are written when @p Hs is set.
 * @param A_r Local design matrix; rows out..out+mc-1 are written.
 * @param w   Row weights; set to one for the group.
 * @param y   Row innovations; rows out..out+mc-1 are written.
 */
void networkWriteWhitenedRows(const Eigen::MatrixXd& cov, const Eigen::MatrixXd& Hr,
                              const Eigen::MatrixXd* Hs, const Eigen::VectorXd& zc,
                              Eigen::Index out, Eigen::MatrixXd& A_s, Eigen::MatrixXd& A_r,
                              Eigen::VectorXd& w, Eigen::VectorXd& y);

/**
 * @brief Builds one station's block: walks kStationBuildSteps in order.
 * @param build One station's build.
 * @return false when a step ended the build (the slot names the cause).
 */
bool networkStationBuild(StationBuild& build);

/**
 * @brief PASS B's parallel produce: one station's block per OpenMP iteration, into its own
 *        slot.  The frozen loop, its present test and its catch; the body is the walk of
 *        kStationBuildSteps (networkStationBuild).
 *
 * An epoch writer in EP1's form (run, ep, kept, outputs), a row of
 * tests/network/test_network_epoch_contract.cpp; called by Application::networkPassB_.
 * Reads the run (ctx, config, setup, the estimator's layout) and the epoch (se, clock,
 * pass_a) and hands each step a const view of them (StationBuild).
 *
 * @param run      The run (network/driver/Run.hpp).
 * @param ep       The epoch (network/driver/Epoch.hpp), read only: se, clock, pass_a.
 * @param gim      Kept: Application::gim_ (the GIM rows), the one input NetworkRun does not
 *                 hold (decision 4).
 * @param assembly [in/out] asm_res: each iteration writes its own station's slot.
 */
void networkAssemblyProduce(NetworkRun& run, const NetworkEpoch& ep,
                            const std::unique_ptr<GlobalIonosphereMap>& gim,
                            EpochAssembly& assembly);

