/**
 * @brief Emit, store, write and closed-loop-consume this epoch's solution.  See the
 *        file banner for the full step list and the ordering contract.  Parameters
 *        beyond ctx/config_/log/traces/setup carry the epoch-local assembly state,
 *        the five @ref NetworkSolPrepResult locals (@c sol is re-based in place), the
 *        emit-layer engines (@ref NetworkEmitEngines; their switches are
 *        NetworkKnobs::emit_rebase_on), and the
 *        run-level closed-loop tally (@ref ClosedLoopTally), which this function
 *        accumulates.
 *
 * Epoch form (generated by scripts/nom_ep1_cut.py): the run and the epoch
 * replace the explicit parameters; the definition binds each former parameter in its preamble,
 * under its former name.
 *
 * @param run The run (network/driver/Run.hpp). Written through non-const bindings: run.ctx (ctx),
 *            run.traces (traces), run.setup (setup), run.emit (emit_engines), run.closed_loop
 *            (cl_tally). Read: run.config (config_), run.log (log), run.engines.est (est).
 * @param ep The epoch (network/driver/Epoch.hpp), read only. Bindings: ep.se (se), ep.x_emit()
 *           (x_s), ep.clock.pl_now_s (pl_now_s), ep.solve.datum_changed (datum_changed),
 *           ep.solve.sigma0_adapt (sigma0_adapt), ep.prep.epoch_withheld_consts
 *           (epoch_withheld_consts), ep.prep.global_bump (global_bump),
 *           ep.prep.serialized_consts (serialized_consts), ep.prep.retro_emit_sats
 *           (retro_emit_sats), ep.pass_a.present (present), ep.assembly.est_index_of
 *           (est_index_of), ep.pass_a.modeled (modeled), ep.pass_a.shared_phase_keys
 *           (shared_phase_keys), ep.funnel.carry_slipped_ambs (carry_slipped_ambs),
 *           ep.solve.we_t2_opp (we_t2_opp), ep.solve.we_t2_flag (we_t2_flag).
 * @param sol [in/out] ep.prep.sol.
 *
 * The former parameters, by binding:
 *   - @p ctx = run.ctx.
 *   - @p config_ = run.config.
 *   - @p log = run.log.
 *   - @p traces = run.traces.
 *   - @p setup = run.setup.
 *   - @p se = ep.se.
 *   - @p est = run.engines.est.
 *   - @p x_s = ep.x_emit().
 *   - @p pl_now_s = ep.clock.pl_now_s.
 *   - @p datum_changed = ep.solve.datum_changed.
 *   - @p sigma0_adapt = ep.solve.sigma0_adapt.
 *   - @p sol = the output parameter itself (ep.prep.sol at the spine line).
 *   - @p epoch_withheld_consts = ep.prep.epoch_withheld_consts.
 *   - @p global_bump = ep.prep.global_bump.
 *   - @p serialized_consts = ep.prep.serialized_consts.
 *   - @p retro_emit_sats = ep.prep.retro_emit_sats.
 *   - @p emit_engines = run.emit.
 *   - @p present = ep.pass_a.present.
 *   - @p est_index_of = ep.assembly.est_index_of.
 *   - @p modeled = ep.pass_a.modeled.
 *   - @p shared_phase_keys = ep.pass_a.shared_phase_keys.
 *   - @p carry_slipped_ambs = ep.funnel.carry_slipped_ambs.
 *   - @p we_t2_opp = ep.solve.we_t2_opp.
 *   - @p we_t2_flag = ep.solve.we_t2_flag.
 *   - @p cl_tally = run.closed_loop.
 */
void networkEmitStore(NetworkRun& run, const NetworkEpoch& ep, NetworkSolutionEpoch& sol);

