#pragma once
/**
 * @file BrdcWire.hpp
 * @brief Emit seam of the native broadcast clock posture: the wire's clock refers to the stamped broadcast
 *        ephemeris under @c network.apriori_source @c sp3_brdc_clock.
 *
 * The producer's a priori is the continuous a_s(t) = brdc_k(t) + O_s,k
 * (@c BrdcClockApriori), so its estimate C_est is a correction to that.  A consumer holds
 * the broadcast record k, not the offset table, so each clock record goes out as
 * C_wire = C_est + O_s,k with @c iode = k: brdc_k(t) + C_wire = a_s(t) + C_est.  Nothing
 * in the solve moves; the seam runs after the emit-side hold (every reader of C_est,
 * CLK-R, the holds, has run) and before the store push and the product write.
 *
 * Telemetry: the run-end counters of @c NetworkServiceCounters (@c nbp_*) and the O trace
 * @c network_brdc_offset.csv, which lets a grader form C - O.
 */

#include <memory>
#include <array>
#include <set>
#include <string>
#include <utility>

namespace spdlog { class logger; }

namespace GnssProcessor {

struct NetworkRunContext;
class  GnssConfig;
struct NetworkRunTraces;
struct NetworkSetupResult;
struct SyncedEpoch;
struct NetworkSolutionEpoch;

/**
 * @brief Stamp this epoch's clock records with the selected ephemeris and add its offset.
 *
 * For each clock-bearing satellite of @p sol: @c clock_iode = the IODE of the record the
 * native selector chose at the epoch, @c clock_c0_m += O_s,k (m); the store's holding of
 * that record is checked (the in-process consumer reads the same store this epoch); one
 * O-trace row is written; the run-end counters advance.  A satellite with no selectable
 * record keeps its value and @c clock_iode -1 (counted as unstamped).
 *
 * @param ctx     Run context (counters, the per-satellite previous stamp, knobs).
 * @param config_ Configuration (unused beyond the knob already in @p ctx; kept for the
 *                seam contract).
 * @param log     Logger.
 * @param traces  Trace streams (the O trace).
 * @param setup   Setup handoff (the selector).
 * @param se      This epoch.
 * @param sol     This epoch's emission, modified in place.
 *
 * @note Returns immediately unless @c ctx.knobs.nbp_on and the selector exists.
 */
void networkBrdcWire(NetworkRunContext& ctx,
                     const GnssConfig& config_,
                     const std::shared_ptr<spdlog::logger>& log,
                     NetworkRunTraces& traces,
                     NetworkSetupResult& setup,
                     const SyncedEpoch& se,
                     NetworkSolutionEpoch& sol);

// ---- Run-end reports (generated by scripts/nom_td_cut.py) ----

struct NetworkRunEndView;

/**
 * @brief Run-end report: the native broadcast clock a priori (NBP).
 *
 * The native broadcast clock a priori.
 *
 * Gate: returns 0 at once unless `ctx.knobs.nbp_on`.
 *
 * @param v The run at its end (network/runend/RunEnd.hpp).
 * @return 0 (this report does not set the exit code).
 */
int networkBrdcWireRunEnd(const NetworkRunEndView& v);

// ---- End of the run-end reports ----

/// @brief Run-scope counters of BrdcWire, a base of NetworkServiceCounters (network/state/RunContext.hpp).
struct BrdcWireCounters {
    // Native broadcast clock a priori.  `stamped 0` means the wire was never
    // stamped (inert wiring); `not_held > 0` means a consumer could not reconstruct.
    long long nbp_epochs{0};               ///< emitted epochs the wire stamp ran on
    long long nbp_stamped{0};              ///< clock records stamped (iode=k, C_wire = C_est + O)
    long long nbp_unstamped{0};            ///< clock records with no selectable record (value unchanged, no iode)
    long long nbp_held{0};                 ///< stamped records the store held (current or previous) at consume
    long long nbp_not_held{0};             ///< stamped records the store did not hold
    long long nbp_switches{0};             ///< stamp changes of a satellite between its emissions (cut-overs seen on the wire)
    double    nbp_offset_min_m{0.0};       ///< smallest O on the wire (m)
    double    nbp_offset_max_m{0.0};       ///< largest O on the wire (m)
    std::set<std::pair<std::string, int>> nbp_records;   ///< distinct (satellite, IODE) stamped

    // The tracked broadcast a priori (network.apriori_clock_track, network/assembly/
    // AprioriClockTrack.hpp).  All zero with the knob off; `applied 0` with it on is inert
    // wiring.  Closure: every stamped record of a tracked satellite carries its U on the wire.
    long long brd_track_epochs{0};          ///< epochs the track seam ran
    long long brd_track_applied{0};         ///< satellite-epochs whose track moved by a column
    long long brd_track_paused{0};          ///< tracked satellite-epochs with no column (track held)
    long long brd_track_started{0};         ///< satellites tracked for the first time
    long long brd_track_resumed{0};         ///< resumptions after an epoch without a column
    long long brd_track_rows_moved{0};      ///< modelled observations moved by a nonzero track
    std::array<long long, 6> brd_track_inc_hist{};   ///< |increment| below 5, 10, 20, 50, 100 mm and above
    double    brd_track_max_abs_m{0.0};     ///< largest |U| (m)
    long long brd_track_wire{0};            ///< stamped clock records that carried a track on the wire
};

} // namespace GnssProcessor
