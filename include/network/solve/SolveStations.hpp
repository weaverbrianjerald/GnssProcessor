#pragma once
/**
 * @file SolveStations.hpp
 * @brief The stations that enter the solve: the consume and the in-solve track.
 *
 * networkAssemblyConsume folds every assembled station into the estimator in station order;
 * networkSolveStationsTrack counts the stations that entered and marks every return.  The
 * run-end readout of the track is network/runend/SolveStationsRunEnd.cpp.
 */

#include <memory>
#include <map>
#include <string>

namespace GnssProcessor {

struct NetworkRun;              // network/driver/Run.hpp
struct NetworkEpoch;            // network/driver/Epoch.hpp
struct EpochPassA;              // network/driver/Epoch.hpp
struct EpochAssembly;           // network/driver/Epoch.hpp
struct StationAssembly;         // network/driver/RunTypes.hpp

// ---- PASS B serial stages, declarations (generated by scripts/nom_pb1_cut.py) ----

/**
 * @brief Folds every assembled station into the estimator in station order.
 *
 * The empty, mismatch and failed dispositions, addStation, the carried diagonal prior, the
 * PD-rejection naming and its per-epoch roll-up.  Called by networkPassB_.
 *
 * Epoch form (generated by scripts/nom_pb1_cut.py): a serial stage of
 * Application::networkPassB_, cut with the alias lines of networkPassB_ it reads.  Below its
 * bindings is the frozen text; a piece wholly inside one `if` returns early instead
 * (scripts/nom_pb1/declared.py).
 *
 * @param run The run (network/driver/Run.hpp). Bindings: run.ctx (ctx), run.config (config_),
 *            run.log (log), run.setup (setup), run.traces (traces), run.engines.est (est).
 * @param ep The epoch (network/driver/Epoch.hpp), read only. Bindings: ep.se (se),
 *           ep.clock.carry_warm (carry_warm).
 * @param pass_a [in/out] present: a dropped station is cleared. Bindings: pass_a.modeled
 *               (modeled, read only), pass_a.present (present).
 * @param assembly [in/out] est_index_of, total_pins. Bindings: assembly.asm_res (asm_res),
 *                 assembly.est_index_of (est_index_of), assembly.total_pins (total_pins).
 * @return false when the legacy pivot's block was refused (the epoch is then skipped by
 *         networkPassB_).
 */
bool networkAssemblyConsume(NetworkRun& run, const NetworkEpoch& ep, EpochPassA& pass_a,
                            EpochAssembly& assembly);

/**
 * @brief Counts the stations that entered the solve and marks every return (invariant 7's
 *        re-coupling edge).
 *
 * No-op on an aborted epoch.  Called by networkPassB_ after the consume.
 *
 * Epoch form (generated by scripts/nom_pb1_cut.py): a serial stage of
 * Application::networkPassB_, cut with the alias lines of networkPassB_ it reads.  Below its
 * bindings is the frozen text; a piece wholly inside one `if` returns early instead
 * (scripts/nom_pb1/declared.py).
 *
 * @param run The run (network/driver/Run.hpp). Bindings: run.ctx (ctx), run.config (config_),
 *            run.setup (setup), run.traces (traces).
 * @param ep The epoch (network/driver/Epoch.hpp), read only. Bindings: ep.se (se).
 * @param assembly The station blocks, read (est_index_of, asm_res), passed because
 *                 networkPassB_ still writes the group. Bindings: assembly.asm_res (asm_res),
 *                 assembly.est_index_of (est_index_of).
 * @param epoch_ok The consume's verdict (kept: an orchestrator value).
 */
void networkSolveStationsTrack(NetworkRun& run, const NetworkEpoch& ep,
                               const EpochAssembly& assembly, bool epoch_ok);

/**
 * @brief Whether a station's diagonal carried priors are folded into the solve this epoch.
 *
 * The consume installs them after the station's block, and the within-epoch replay installs
 * them again on its fresh system, so the two ask the same question. The priors are folded
 * when the phase-leveling carry is warm or one of the diagonal-only families is armed (the
 * receiver code-bias carry, its datum, an oracle pin: their rows are coalesced into
 * @c carry_cols whether or not the carry is warm, and a gate that built them and then dropped
 * them would leave the run-end clauses reporting folds that never reached the normals) and
 * the station has any.
 *
 * @param carry_warm  The phase-leveling carry is warm this epoch.
 * @param rx_cb_on    The receiver code-bias carry is armed.
 * @param rx_cb_datum The receiver code-bias zero-mean datum is armed.
 * @param R           The station's assembled block (its oracle-pin rows and carried columns).
 * @return true when the station's @c carry_cols are folded through @c addStationPrior.
 */
bool networkCarriedPriorsInstalled(bool carry_warm, bool rx_cb_on, bool rx_cb_datum,
                                   const StationAssembly& R);

// ---- End of the PASS B serial stages, declarations ----

/// @brief Run-scope counters of SolveStations, a base of NetworkServiceCounters (network/state/RunContext.hpp).
struct SolveStationsCounters {

    /// --- The addStation positive-definiteness drop, counted.
    /// The drop removes one station for one epoch
    /// (ApplicationNetworkAssembly.cpp: `present[i]=false`), and
    /// `network_epoch_status.csv` does not report it: `n_present` still counts the
    /// station, and otherwise the only record is a warning line in a rotating log.
    /// These are always counted (the increment costs nothing and writes no output);
    /// `network.trace_station_pd_null` arms the run-end readout and the per-rejection
    /// `sta_pd_dropped` event rows.
    long long pd_drop_epochs = 0;       ///< epochs whose serial consume loop ran (denominator)
    long long pd_drop_total = 0;        ///< station-epochs dropped by the addStation PD rejection
    long long pd_drop_named = 0;        ///< …of those, ones whose null direction was eigen-named (armed only)
    long long pd_drop_pivot_abort = 0;  ///< epochs lost because the rejected station was the legacy pivot
    int       pd_drop_max_ep = 0;       ///< largest per-epoch drop count over the run
    double    pd_drop_max_ep_tow = 0.0; ///< …its epoch
    /// Top-column family census over the named rejections (label prefix:
    /// "AMB" / "IONO" / "CBIAS" / "ZWD" / "CLK" / "RPB" / "ISB" / "other").  The read
    /// script does the per-station and persistence analysis off the event rows; this
    /// is the run-end one-liner that says which family dominates without opening a
    /// trace.
    std::map<std::string, long long> pd_drop_family;
    /// The same census weighted by mass: Σ over rejections of the null eigenvector's
    /// per-family mass Σw² (each rejection contributes 1.0 in total).  The top-column
    /// count above depends on where the top-5 cut fell; this one does not, and here
    /// that matters: the null is spread nearly evenly over a whole band of ambiguities,
    /// so the family ranked first is close to arbitrary while the mass split is stable.
    std::map<std::string, double> pd_drop_family_mass;
    /// --- The actual in-solve station count, and the re-coupling edge of invariant #7
    ///.  `network_epoch_status.csv`'s `n_present` is the roster that
    /// reached the consume loop, not the set that entered the arrowhead, so a
    /// PD-dropped (or assembly-dropped) station still reads as present.  The run-end
    /// tail and `network_run_summary.csv` report these instead, and they are always
    /// accumulated; the `sta_readmitted` event rows ride `network.trace_topology`, the
    /// counters do not.  The per-station return bookkeeping lives here in the run
    /// context so that no seam keeps it in a function-local (the INC-12 rule).
    struct StationSolveTrack {
        bool      ever_in_solve = false;  ///< distinguishes a return from a first sighting
        long long absent_streak = 0;      ///< consecutive consume epochs out of the solve
    };
    std::map<std::string, StationSolveTrack> sta_solve_track;
    long long sta_in_solve_epochs = 0;       ///< number of epochs the above was recorded for (denominator)
    int       sta_in_solve_min = -1;         ///< min over the run (−1 = never recorded)
    double    sta_in_solve_min_tow = 0.0;    ///< …its epoch
    long long sta_readmit_events = 0;        ///< stations that re-entered the solve after ≥ 1 absent epoch
    long long sta_readmit_max_gap_ep = 0;    ///< longest absence that ended in a readmission
};

} // namespace GnssProcessor
