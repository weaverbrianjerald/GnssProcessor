/**
 * @brief Install the accepted DD posterior for this epoch.
 *
 * Epoch form (card NOM3 step EP1; generated by scripts/nom_ep1_cut.py): the run and the epoch
 * replace the explicit parameters; the definition binds each former parameter in its preamble,
 * under its former name.
 *
 * @param run The run (app/NetworkRun.hpp). Written through non-const bindings: run.ctx (ctx),
 *            run.traces (traces), run.engines.carry_driver (carry_driver), run.engines.slip_qc
 *            (slip_qc). Read: run.config (config_), run.log (log), run.engines.est (est),
 *            run.setup.stations (stations), run.setup.carry_par (carry_par),
 *            run.setup.n_threads (n_threads), run.setup.seam_threads (seam_threads).
 * @param ep The epoch (app/NetworkEpoch.hpp), read only. Bindings: ep.solve.x_s (x_s),
 *           ep.solve.plan (plan), ep.se (se), ep.dd_build.carry_arc_amb_key
 *           (carry_arc_amb_key).
 *
 * The former parameters, by binding:
 *   - @p ctx = run.ctx.
 *   - @p config_ = run.config.
 *   - @p log = run.log.
 *   - @p traces = run.traces.
 *   - @p carry_driver = run.engines.carry_driver.
 *   - @p est = run.engines.est.
 *   - @p x_s = ep.solve.x_s.
 *   - @p plan = ep.solve.plan.
 *   - @p se = ep.se.
 *   - @p stations = run.setup.stations.
 *   - @p slip_qc = run.engines.slip_qc.
 *   - @p carry_arc_amb_key = ep.dd_build.carry_arc_amb_key.
 *   - @p carry_par = run.setup.carry_par.
 *   - @p n_threads = run.setup.n_threads.
 *   - @p seam_threads = run.setup.seam_threads.
 *
 * @see NetworkInstallCarry.hpp file banner for the ordering contract.
 * @param events The epoch's events; written: install.
 */
void networkInstallCarry(NetworkRun& run, const NetworkEpoch& ep, EpochEvents& events);

