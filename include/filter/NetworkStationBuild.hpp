/**
 * @brief Folds the per-station tallies of the produce into the run counters, serially and in
 *        station order.
 *
 * The free-epoch skips, the parameter inventory drain, the response table, the oracle pin, the
 * inject-side stale skips, the F3 block telemetry and its non-SPD warning, the LGM edges, the
 * coupling-term census with the resume seam, card CTU and the SD-EWL trace.  Step PB2 splits it
 * by family.  Called by networkPassB_ after the parallel produce (card NOM3 step PB1a).
 *
 * Epoch form (card NOM3 step PB1a; generated by scripts/nom_pb1_cut.py): a serial stage of
 * Application::networkPassB_, cut with the alias lines of networkPassB_ it reads.  Below its
 * bindings is the frozen text; a piece wholly inside one `if` returns early instead
 * (scripts/nom_pb1/declared.py).
 *
 * @param run The run (app/NetworkRun.hpp). Bindings: run.ctx (ctx), run.config (config_),
 *            run.log (log), run.setup (setup), run.traces (traces), run.engines.est (est).
 * @param ep The epoch (app/NetworkEpoch.hpp), read only. Bindings: ep.se (se),
 *           ep.clock.pl_now_s (pl_now_s), ep.pass_a.present (present),
 *           ep.pass_a.shared_phase_keys (shared_phase_keys), ep.columns.registered_clock_sats
 *           (registered_clock_sats).
 * @param assembly The station blocks networkPassB_ is assembling, read (a group the caller
 *                 still writes, so it is passed rather than read through @p ep). Bindings:
 *                 assembly.asm_res (asm_res).
 */
void networkAssemblyTally(NetworkRun& run, const NetworkEpoch& ep,
                          const EpochAssembly& assembly);

