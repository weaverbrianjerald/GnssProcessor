/**
 * @brief Advance the T5 SH-deviation carry Kalman filter and emit the co-estimated
 *        VTEC-coefficient trace for this epoch.  Folds the shared solution's SH-field
 *        deviation into the persistent per-LOS (station|satellite) carry in
 *        @p ctx.carry.sh_dev_carry; that update runs only when @c ctx.knobs.sh_dev_on,
 *        and is a no-op otherwise.  Independently of that switch, writes one row per SH
 *        coefficient to the VTEC-coefficient trace when that trace is open and an SH
 *        model exists.  The caller keeps the networkSubBegin/End(SB_SHDEV_VTEC) brackets.
 *
 * Epoch form (card NOM3 step EP1; generated by scripts/nom_ep1_cut.py): the run and the epoch
 * replace the explicit parameters; the definition binds each former parameter in its preamble,
 * under its former name.
 *
 * @param run The run (app/NetworkRun.hpp). Written through non-const bindings: run.ctx (ctx),
 *            run.traces (traces), run.setup (setup). Read: run.config (config_), run.log (log),
 *            run.engines.est (est).
 * @param ep The epoch (app/NetworkEpoch.hpp), read only. Bindings: ep.se (se), ep.solve.x_s
 *           (x_s), ep.solve.plan (plan), ep.assembly.asm_res (asm_res),
 *           ep.assembly.est_index_of (est_index_of), ep.pass_a.modeled (modeled).
 *
 * The former parameters, by binding:
 *   - @p ctx = run.ctx.
 *   - @p config_ = run.config.
 *   - @p log = run.log.
 *   - @p traces = run.traces.
 *   - @p setup = run.setup.
 *   - @p se = ep.se.
 *   - @p est = run.engines.est.
 *   - @p x_s = ep.solve.x_s.
 *   - @p plan = ep.solve.plan.
 *   - @p asm_res = ep.assembly.asm_res.
 *   - @p est_index_of = ep.assembly.est_index_of.
 *   - @p modeled = ep.pass_a.modeled.
 */
void networkShDevVtec(NetworkRun& run, const NetworkEpoch& ep);

