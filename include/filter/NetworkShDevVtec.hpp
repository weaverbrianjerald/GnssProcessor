/**
 * @brief Ages the SH-deviation carry once per epoch, before PASS B's parallel produce reads it
 *        (T5v2; Iono-2 v3 de-mean; v3k erase-or-re-tap split).
 *
 * Every (station, satellite) in this epoch's slip funnel is erased (a raw-confirmed slip) or
 * re-tapped to steady state (a D5-only entry under network.sh_dev_carry_d5_keep); every entry
 * is then GM-aged to this epoch and dropped past 5 tau; the de-mean removes the
 * information-weighted common mode. No-op unless NetworkKnobs::sh_dev_on.  Serial, called by
 * networkPassB_ (card NOM3 step PB1a).
 *
 * Epoch form (card NOM3 step PB1a; generated by scripts/nom_pb1_cut.py): a serial stage of
 * Application::networkPassB_, cut with the alias lines of networkPassB_ it reads.  Below its
 * bindings is the frozen text; a piece wholly inside one `if` returns early instead
 * (scripts/nom_pb1/declared.py).
 *
 * @param run The run (app/NetworkRun.hpp). Bindings: run.ctx (ctx), run.setup (setup).
 * @param ep The epoch (app/NetworkEpoch.hpp), read only. Bindings: ep.se (se),
 *           ep.funnel.carry_slipped_ambs (carry_slipped_ambs), ep.funnel.carry_slipped_raw
 *           (carry_slipped_raw).
 */
void networkShDevCarryAge(NetworkRun& run, const NetworkEpoch& ep);

