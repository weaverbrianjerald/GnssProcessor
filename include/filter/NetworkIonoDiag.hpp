/**
 * @brief Emit this epoch's iono / ZWD / receiver-state / anchor-info visualization
 *        traces.  Back-substitutes each station's local nuisance blocks (slant iono,
 *        ZWD, receiver clock and biases) from the shared solution and writes the
 *        per-station trace rows.  Diagnostic only: it mutates no estimation state, and
 *        with the viz traces unarmed it writes nothing and the run is byte-identical.
 *        The caller keeps the networkSubBegin/End(SB_IONODIAG) brackets.  The anchor-info
 *        trace reads the resolved clock anchor sigma from @c ctx.knobs.clk_anchor_sigma
 *        (card NOM3 step EP0).
 *
 * Epoch form (card NOM3 step EP1; generated by scripts/nom_ep1_cut.py): the run and the epoch
 * replace the explicit parameters; the definition binds each former parameter in its preamble,
 * under its former name.
 *
 * @param run The run (app/NetworkRun.hpp). Written through non-const bindings: run.ctx (ctx),
 *            run.traces (traces), run.setup (setup), run.engines.est (est). Read: run.config
 *            (config_), run.log (log).
 * @param ep The epoch (app/NetworkEpoch.hpp), read only. Bindings: ep.ws (ws), ep.se (se),
 *           ep.solve.x_s (x_s), ep.solve.plan (plan), ep.assembly.asm_res (asm_res),
 *           ep.assembly.est_index_of (est_index_of), ep.pass_a.modeled (modeled),
 *           ep.columns.registered_clock_sats (registered_clock_sats).
 *
 * The former parameters, by binding:
 *   - @p ctx = run.ctx.
 *   - @p config_ = run.config.
 *   - @p log = run.log.
 *   - @p traces = run.traces.
 *   - @p setup = run.setup.
 *   - @p ws = ep.ws.
 *   - @p se = ep.se.
 *   - @p est = run.engines.est.
 *   - @p x_s = ep.solve.x_s.
 *   - @p plan = ep.solve.plan.
 *   - @p asm_res = ep.assembly.asm_res.
 *   - @p est_index_of = ep.assembly.est_index_of.
 *   - @p modeled = ep.pass_a.modeled.
 *   - @p registered_clock_sats = ep.columns.registered_clock_sats.
 */
void networkIonoDiag(NetworkRun& run, const NetworkEpoch& ep);

