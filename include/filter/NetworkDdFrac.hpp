/**
 * @brief Emit this epoch's cross-station DD fractional-residual (B5) diagnostic trace.
 *        Forms between-station double differences of the absolute float ambiguities,
 *        each against one reference satellite per (constellation, signal) (the
 *        lexically lowest present at 2 or more stations by default;
 *        network.trace_dd_fractional_ref = lowest | oldest), and reduces each to its
 *        fractional cycle for a network_dd_fractional.csv row.  Also writes the
 *        per-epoch phase-anchor map when that trace is open.  Trace-only: it mutates no
 *        estimation state (only the trace's own reference-age bookkeeping and
 *        counters), and it does nothing unless one of the two traces is open.
 *        The caller keeps the subBegin/subEnd(SB_DDFRAC) brackets.
 *
 * The trace's wavelengths come from the identity layer (@c SignalId::wavelengthM,
 * card NOM step N0b); GLONASS is excluded, so no FDMA slot is needed.
 *
 * Epoch form (card NOM3 step EP1; generated by scripts/nom_ep1_cut.py): the run and the epoch
 * replace the explicit parameters; the definition binds each former parameter in its preamble,
 * under its former name.
 *
 * @param run The run (app/NetworkRun.hpp). Written through non-const bindings: run.ctx (ctx),
 *            run.traces (traces), run.setup (setup), run.engines.est (est). Read: run.config
 *            (config_), run.log (log).
 * @param ep The epoch (app/NetworkEpoch.hpp), read only. Bindings: ep.se (se), ep.solve.x_s
 *           (x_s), ep.solve.plan (plan), ep.assembly.asm_res (asm_res),
 *           ep.assembly.est_index_of (est_index_of).
 *
 * The former parameters, by binding:
 *   - @p ctx = run.ctx.
 *   - @p config_ = run.config.
 *   - @p log = run.log.
 *   - @p traces = run.traces.
 *   - @p setup = run.setup.
 *   - @p se = ep.se.
 *   - @p est = run.engines.est.
 *   - @p x_s = ep.solve.x_s.
 *   - @p plan = ep.solve.plan.
 *   - @p asm_res = ep.assembly.asm_res.
 *   - @p est_index_of = ep.assembly.est_index_of.
 */
void networkDdFrac(NetworkRun& run, const NetworkEpoch& ep);

